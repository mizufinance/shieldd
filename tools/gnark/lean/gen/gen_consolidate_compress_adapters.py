#!/usr/bin/env python3
"""Generate consolidate2x1 adapters for deployed compress_to_field slices."""

from __future__ import annotations

import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONTRACTS = ROOT / "ShielddGnarkFormal/Deployed/Contracts/Consolidate2x1"
BRIDGE = ROOT / "ShielddGnarkFormal/Deployed/CompressToField/Bridge.lean"
COMMON_OUT = CONTRACTS / "CompressAdapterCommon.lean"
AGG_OUT = CONTRACTS / "CompressAdapters.lean"

SEGMENTS = [
    # seg, x, y, internal wire offset for base wires 210..912
    # Wave-2 layout (T1-f shared divGen): re-derived from
    # consolidate2x1-deployed-slice-ir.json — 4 instances, contract seg = IR index + 1.
    # Seg48 compresses the NB-1 conservation commitment whose coordinates are
    # the unmaterialized ladder-accumulator LCs Specs.nbX/nbY, not wires: its
    # x/y entries are Lean expressions and its rows are discharged through the
    # flat-vs-stride-run bridge below.
    (5, 17, 18, 0),
    (17, 12, 13, 17739),
    (32, 102, 103, 29920),
    (48, "Specs.nbX rho", "Specs.nbY rho", 33257),
]

# seg -> (lean name, sumAux runs [(start, stride, count)]) for LC-coordinate
# segments; runs must match Specs.nbX/nbY definitionally.
LC_COORDS = {
    48: {
        "x": ("Specs.nbX", [(31915, 5, 149), (32663, 8, 101)]),
        "y": ("Specs.nbY", [(31916, 5, 149), (32664, 8, 101)]),
    },
}

BRIDGE_CHUNK_SIZE = 64
GENERATED = """/-
GENERATED by gen/gen_consolidate_compress_adapters.py — do not edit by hand.
-/
"""


def first_operand(seg: int, row: int) -> str:
    """Verbatim first (A-slot) operand of relationRow{row}, outer parens stripped."""
    src = (CONTRACTS / f"Seg{seg}.lean").read_text()
    m = re.search(
        rf"def relationRow{row} \(rho : Nat -> F\) : Prop :=\n(.*?)(?=\n\ndef )", src, re.S
    )
    body = m.group(1).strip()
    if not body.startswith("("):
        raise ValueError(f"Seg{seg} row{row}: unexpected body start")
    depth = 0
    for i, ch in enumerate(body):
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
            if depth == 0:
                return body[1:i]
    raise ValueError(f"Seg{seg} row{row}: unbalanced parens")


def bare_sum(start: int, stride: int, count: int) -> str:
    return " + ".join(["0"] + [f"rho {start + i * stride}" for i in range(count)])


def chunks(items: list[str], n: int) -> list[list[str]]:
    return [items[i : i + n] for i in range(0, len(items), n)]


def parse_bridge_hyps() -> list[tuple[int, str]]:
    src = BRIDGE.read_text()
    out: list[tuple[int, str]] = []
    for m in re.finditer(r"\(h(\d+) : (.*?)\)\n", src, re.S):
        out.append((int(m.group(1)), re.sub(r"\s+", " ", m.group(2).strip())))
    return out


def validate_bridge_hyps(hyps: list[tuple[int, str]]) -> None:
    expected = [*range(0, 281), *range(535, 1044), *range(1298, 1552)]
    actual = [h for h, _ in hyps]
    if actual != expected:
        raise ValueError("compress bridge hypothesis partition changed")


def bridge_row_for_hyp(h: int) -> int:
    if 0 <= h <= 280:
        return h
    if 535 <= h <= 1043:
        return h - 253
    if 1298 <= h <= 1551:
        return h - 506
    raise ValueError(f"unexpected bridge hypothesis h{h}")


def parse_relation_parts(seg: int) -> list[list[int]]:
    src = (CONTRACTS / f"Seg{seg}.lean").read_text()
    parts: list[list[int]] = []
    for m in re.finditer(
        r"def relationPart(\d+) \(rho : Nat -> F\) : Prop :=\n(.*?)(?=\n\ndef relationPart|\n\ndef relation |\Z)",
        src,
        re.S,
    ):
        idx = int(m.group(1))
        rows = [int(r) for r in re.findall(r"relationRow(\d+) rho", m.group(2))]
        if idx != len(parts):
            raise ValueError(f"non-contiguous relationPart in Seg{seg}: got {idx}, want {len(parts)}")
        parts.append(rows)
    return parts


def seated_type(seg: int, h_type: str) -> str:
    h_type = h_type.replace(": F", f": Seg{seg}.F")
    h_type = re.sub(r"\brho (\d+)", rf"seg{seg}Rho rho \1", h_type)
    return h_type


def emit_relation_unpack(lines: list[str], seg: int, parts: list[list[int]]) -> None:
    part_names = [f"p{i}" for i in range(len(parts))]
    lines.append(f"  unfold Seg{seg}.relation at h")
    lines.append("  rcases h with ⟨")
    for chunk in chunks(part_names, 8):
        lines.append("    " + ", ".join(chunk) + ",")
    lines[-1] = lines[-1].rstrip(",")
    lines.append("  ⟩")


def row_part_map(parts: list[list[int]]) -> dict[int, int]:
    out: dict[int, int] = {}
    for part, rows in enumerate(parts):
        for row in rows:
            if row in out:
                raise ValueError(f"row {row} occurs in relationPart{out[row]} and relationPart{part}")
            out[row] = part
    return out


def part_indices_for_rows(parts: list[list[int]], rows: list[int]) -> list[int]:
    by_row = row_part_map(parts)
    missing = sorted(set(rows) - by_row.keys())
    if missing:
        raise ValueError(f"rows absent from relation parts: {missing}")
    return sorted({by_row[row] for row in rows})


def emit_selected_part_unpack(
    lines: list[str], seg: int, parts: list[list[int]], part_indices: list[int]
) -> None:
    for part in part_indices:
        rows = parts[part]
        lines.append(f"  unfold Seg{seg}.relationPart{part} at p{part}")
        if len(rows) == 1:
            lines.append(f"  have r{rows[0]} := p{part}")
        else:
            lines.append(f"  rcases p{part} with ⟨{', '.join(f'r{r}' for r in rows)}⟩")


def emit_rho_def(lines: list[str], seg: int, x, y, offset: int) -> None:
    xs = x if isinstance(x, str) else f"rho {x}"
    ys = y if isinstance(y, str) else f"rho {y}"
    lines.append(f"def seg{seg}Rho (rho : Nat → Seg{seg}.F) : Nat → Seg{seg}.F")
    lines.append("| 0 => 1")
    lines.append(f"| 17 => {xs}")
    lines.append(f"| 18 => {ys}")
    lines.append(f"| i => if 210 ≤ i ∧ i ≤ 912 then rho (i + {offset}) else rho i")
    lines.append("")


def emit_lc_flat_lemma(lines: list[str], seg: int, coord: str, flat: str) -> None:
    name, runs = LC_COORDS[seg][coord]
    flat = flat.replace(" : F)", f" : Seg{seg}.F)")
    lines.append(f"theorem seg{seg}_flat{coord.upper()} (rho : Nat → Seg{seg}.F) :")
    lines.append(f"    {flat} = {name} rho := by")
    lines.append(f"  unfold {name}")
    for start, stride, count in runs:
        lines.append(
            f"  rw [show Shieldd.GnarkFormal.StrideRun.sumAux rho {start} {stride} {count} ="
        )
        lines.append(f"    {bare_sum(start, stride, count)} from rfl]")
    lines.append("  ring")
    lines.append("")


def emit_recomp_helpers(lines: list[str]) -> None:
    lines.extend(
        [
            "def recBits {n : Nat} (rho : Nat → ZMod n) (base width : Nat) : ZMod n :=",
            "  match width with",
            "  | 0 => 0",
            "  | width + 1 => rho base + 2 * recBits rho (base + 1) width",
            "",
            "def powSumAcc {n : Nat} (rho : Nat → ZMod n) (acc pow : ZMod n) (base width : Nat) : ZMod n :=",
            "  match width with",
            "  | 0 => acc",
            "  | width + 1 => powSumAcc rho (acc + pow * rho base) (2 * pow) (base + 1) width",
            "",
            "theorem powSumAcc_eq {n : Nat} (rho : Nat → ZMod n) (acc pow : ZMod n) (base width : Nat) :",
            "    powSumAcc rho acc pow base width = acc + pow * recBits rho base width := by",
            "  induction width generalizing acc pow base with",
            "  | zero => simp [powSumAcc, recBits]",
            "  | succ width ih =>",
            "      simp [powSumAcc, recBits, ih]",
            "      ring",
            "",
            "theorem recover_ofFn_eq_recBits {n : Nat} (rho : Nat → ZMod n) (base width : Nat) :",
            "    recover_binary_zmod' (List.Vector.ofFn (fun i : Fin width => rho (base + i.val))) =",
            "      recBits rho base width := by",
            "  induction width generalizing base with",
            "  | zero => simp [recover_binary_zmod', recBits]",
            "  | succ width ih =>",
            "      simp only [recover_binary_zmod', recBits, List.Vector.head_ofFn, List.Vector.tail_ofFn]",
            "      have htail : (List.Vector.ofFn fun i : Fin width => rho (base + ↑i.succ)) =",
            "          (List.Vector.ofFn fun i : Fin width => rho (base + 1 + ↑i)) := by",
            "        apply List.Vector.ext",
            "        intro i",
            "        simp [Nat.add_assoc, Nat.add_comm, Nat.add_left_comm]",
            "      rw [htail, ih (base + 1)]",
            "      simp",
            "",
        ]
    )


def emit_bridge_chunks(lines: list[str], hyps: list[tuple[int, str]]) -> None:
    """Bundle the wide extracted bridge boundary into bounded propositions."""
    hyp_chunks = chunks(hyps, BRIDGE_CHUNK_SIZE)
    lines.append("variable [Fact (Nat.Prime Order)]")
    lines.append("")
    for index, chunk in enumerate(hyp_chunks):
        lines.append(f"structure CompressRows{index} (rho : Nat → F) : Prop where")
        for h, typ in chunk:
            lines.append(f"  h{h} : {typ}")
        lines.append("")

    lines.append("theorem inst_compress_deployed_sound_chunked (rho : Nat → F)")
    for index in range(len(hyp_chunks)):
        lines.append(f"    (rows{index} : CompressRows{index} rho)")
    lines.extend(
        [
            "    (hrec1 : recover_binary_zmod' (List.Vector.ofFn (fun i : Fin 253 => rho (231 + i.val))) = rho 230)",
            "    (hrec2 : recover_binary_zmod' (List.Vector.ofFn (fun i : Fin 253 => rho (573 + i.val))) = rho 572)",
            "    (hrho0 : rho 0 = 1) :",
            "    Relation (rho 17) (rho 18) (rho 912 - rho 572) := by",
        ]
    )
    for index, chunk in enumerate(hyp_chunks):
        names = ", ".join(f"h{h}" for h, _ in chunk)
        lines.append(f"  rcases rows{index} with ⟨{names}⟩")
    lines.append("  exact inst_compress_deployed_sound rho")
    for chunk in chunks([f"h{h}" for h, _ in hyps], 24):
        lines.append("    " + " ".join(chunk))
    lines.append("    hrec1 hrec2 hrho0")
    lines.append("")


def emit_recomp_lemma(
    lines: list[str],
    seg: int,
    which: int,
    row: int,
    base: int,
    inp: int,
    parts: list[list[int]],
) -> None:
    part = part_indices_for_rows(parts, [row])[0]
    lines.append(f"theorem seg{seg}_hrec{which} (rho : Nat → Seg{seg}.F)")
    lines.append(f"    (p{part} : Seg{seg}.relationPart{part} rho) :")
    lines.append(
        f"    recover_binary_zmod' (List.Vector.ofFn (fun i : Fin 253 => seg{seg}Rho rho ({base} + i.val))) = "
        f"seg{seg}Rho rho {inp} := by"
    )
    emit_selected_part_unpack(lines, seg, parts, [part])
    lines.append(f"  have hrec := recover_ofFn_eq_recBits (seg{seg}Rho rho) {base} 253")
    lines.append(f"  have hacc : powSumAcc (seg{seg}Rho rho) 0 1 {base} 253 = seg{seg}Rho rho {inp} := by")
    lines.append(f"    unfold Seg{seg}.relationRow{row} at r{row}")
    lines.append(f"    simpa [powSumAcc, seg{seg}Rho] using r{row}")
    lines.append("  rw [hrec]")
    lines.append("  rw [powSumAcc_eq] at hacc")
    lines.append(f"  simpa [seg{seg}Rho] using hacc")
    lines.append("")


def emit_row_chunk(
    seg: int,
    index: int,
    hyp_chunk: list[tuple[int, str]],
    parts: list[list[int]],
) -> str:
    rows = [bridge_row_for_hyp(h) for h, _ in hyp_chunk]
    part_indices = part_indices_for_rows(parts, rows)
    lines: list[str] = [
        GENERATED.rstrip(),
        f"import ShielddGnarkFormal.Deployed.Contracts.Consolidate2x1.CompressAdapterSeg{seg}Base",
        "",
        "set_option maxRecDepth 1000000",
        "set_option maxHeartbeats 20000000",
        "set_option linter.unusedVariables false",
        "",
        "namespace Shieldd.GnarkFormal.Deployed.Contracts.Consolidate2x1",
        "",
        "open Shieldd.GnarkFormal.Extracted.DecafCompressToField",
        "",
        f"theorem seg{seg}_rows{index} (rho : Nat → Seg{seg}.F)",
    ]
    for part in part_indices:
        lines.append(f"    (p{part} : Seg{seg}.relationPart{part} rho)")
    lines.append(f"    : CompressRows{index} (seg{seg}Rho rho) := by")
    emit_selected_part_unpack(lines, seg, parts, part_indices)
    lines.append("  refine ⟨" + ", ".join("?_" for _ in hyp_chunk) + "⟩")
    for h, typ in hyp_chunk:
        row = bridge_row_for_hyp(h)
        lines.append(f"  · unfold Seg{seg}.relationRow{row} at r{row}")
        if seg in LC_COORDS:
            rws = []
            if re.search(r"\brho 17\b", typ):
                rws.append(f"seg{seg}_flatX rho")
            if re.search(r"\brho 18\b", typ):
                rws.append(f"seg{seg}_flatY rho")
            if rws:
                lines.append(f"    rw [{', '.join(rws)}] at r{row}")
        lines.append(f"    simpa [seg{seg}Rho, mul_eq_zero] using r{row}")
    lines.extend(["", "end Shieldd.GnarkFormal.Deployed.Contracts.Consolidate2x1"])
    return "\n".join(lines) + "\n"


def emit_segment_head(
    seg: int, hyps: list[tuple[int, str]], parts: list[list[int]]
) -> str:
    hyp_chunks = chunks(hyps, BRIDGE_CHUNK_SIZE)
    lines: list[str] = [GENERATED.rstrip()]
    for index in range(len(hyp_chunks)):
        lines.append(
            f"import ShielddGnarkFormal.Deployed.Contracts.Consolidate2x1.CompressAdapterSeg{seg}Rows{index}"
        )
    lines.extend(
        [
            "",
            "set_option maxRecDepth 1000000",
            "set_option maxHeartbeats 20000000",
            "set_option linter.unusedVariables false",
            "",
            "namespace Shieldd.GnarkFormal.Deployed.Contracts.Consolidate2x1",
            "",
            "open Shieldd.GnarkFormal.Extracted.DecafCompressToField",
            "",
            f"theorem seg{seg}_sound (rho : Nat → Seg{seg}.F) (h : Seg{seg}.relation rho) : Seg{seg}.spec rho := by",
        ]
    )
    emit_relation_unpack(lines, seg, parts)
    lines.append("  change Shieldd.GnarkFormal.Extracted.DecafCompressToField.Relation")
    lines.append(f"    (seg{seg}Rho rho 17) (seg{seg}Rho rho 18) (seg{seg}Rho rho 912 - seg{seg}Rho rho 572)")
    lines.append(f"  exact inst_compress_deployed_sound_chunked (seg{seg}Rho rho)")
    for index, hyp_chunk in enumerate(hyp_chunks):
        row_indices = [bridge_row_for_hyp(h) for h, _ in hyp_chunk]
        part_args = " ".join(f"p{part}" for part in part_indices_for_rows(parts, row_indices))
        lines.append(f"    (seg{seg}_rows{index} rho {part_args})")
    hrec1_part = part_indices_for_rows(parts, [281])[0]
    hrec2_part = part_indices_for_rows(parts, [791])[0]
    lines.append(f"    (seg{seg}_hrec1 rho p{hrec1_part})")
    lines.append(f"    (seg{seg}_hrec2 rho p{hrec2_part})")
    lines.append("    rfl")
    lines.extend(["", "end Shieldd.GnarkFormal.Deployed.Contracts.Consolidate2x1"])
    return "\n".join(lines) + "\n"


def emit_segment_base(seg: int, x, y, offset: int, parts: list[list[int]]) -> str:
    lines: list[str] = [
        GENERATED.rstrip(),
        "import ShielddGnarkFormal.Deployed.Contracts.Consolidate2x1.CompressAdapterCommon",
        f"import ShielddGnarkFormal.Deployed.Contracts.Consolidate2x1.Seg{seg}",
        "import ShielddGnarkFormal.Deployed.PrimeOrder",
        "",
        "set_option maxRecDepth 1000000",
        "set_option maxHeartbeats 20000000",
        "set_option linter.unusedVariables false",
        "",
        "namespace Shieldd.GnarkFormal.Deployed.Contracts.Consolidate2x1",
        "",
        "open Shieldd.GnarkFormal.Extracted.DecafCompressToField",
        "",
        f"instance seg{seg}FactPrime : Fact (Nat.Prime Seg{seg}.Order) :=",
        "  ⟨Shieldd.GnarkFormal.Deployed.decaf377ScalarFieldPrime⟩",
        "",
    ]
    emit_rho_def(lines, seg, x, y, offset)
    if seg in LC_COORDS:
        emit_lc_flat_lemma(lines, seg, "x", first_operand(seg, 0))
        emit_lc_flat_lemma(lines, seg, "y", first_operand(seg, 1))
    emit_recomp_lemma(lines, seg, 1, 281, 231, 230, parts)
    emit_recomp_lemma(lines, seg, 2, 791, 573, 572, parts)
    lines.append("end Shieldd.GnarkFormal.Deployed.Contracts.Consolidate2x1")
    return "\n".join(lines) + "\n"


def render(adapter_out: Path) -> dict[Path, str]:
    hyps = parse_bridge_hyps()
    validate_bridge_hyps(hyps)
    common: list[str] = [
        GENERATED.rstrip(),
        "import ShielddGnarkFormal.Deployed.CompressToField.Bridge",
        "import Mathlib.Tactic.Ring",
        "",
        "set_option maxRecDepth 1000000",
        "set_option maxHeartbeats 20000000",
        "set_option linter.unusedVariables false",
        "",
        "namespace Shieldd.GnarkFormal.Deployed.Contracts.Consolidate2x1",
        "",
        "open Shieldd.GnarkFormal.Extracted.DecafCompressToField",
        "",
    ]
    emit_recomp_helpers(common)
    emit_bridge_chunks(common, hyps)
    common.append("end Shieldd.GnarkFormal.Deployed.Contracts.Consolidate2x1")
    outputs = {adapter_out / COMMON_OUT.name: "\n".join(common) + "\n"}

    aggregate: list[str] = [GENERATED.rstrip()]
    hyp_chunks = chunks(hyps, BRIDGE_CHUNK_SIZE)
    for seg, x, y, offset in SEGMENTS:
        aggregate.append(f"import ShielddGnarkFormal.Deployed.Contracts.Consolidate2x1.CompressAdapterSeg{seg}")
        parts = parse_relation_parts(seg)
        outputs[adapter_out / f"CompressAdapterSeg{seg}Base.lean"] = emit_segment_base(
            seg, x, y, offset, parts
        )
        for index, hyp_chunk in enumerate(hyp_chunks):
            outputs[adapter_out / f"CompressAdapterSeg{seg}Rows{index}.lean"] = emit_row_chunk(
                seg, index, hyp_chunk, parts
            )
        outputs[adapter_out / f"CompressAdapterSeg{seg}.lean"] = emit_segment_head(
            seg, hyps, parts
        )

    outputs[adapter_out / AGG_OUT.name] = "\n".join(aggregate) + "\n"
    return outputs


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--adapter-out", type=Path, default=CONTRACTS)
    args = parser.parse_args()
    args.adapter_out.mkdir(parents=True, exist_ok=True)

    expected = render(args.adapter_out)
    if args.adapter_out.resolve() == CONTRACTS.resolve():
        generated_patterns = ["CompressAdapterSeg*Base.lean", "CompressAdapterSeg*Rows*.lean"]
        for pattern in generated_patterns:
            for stale in args.adapter_out.glob(pattern):
                if stale not in expected:
                    stale.unlink()

    for path, source in expected.items():
        path.write_text(source)


if __name__ == "__main__":
    main()
