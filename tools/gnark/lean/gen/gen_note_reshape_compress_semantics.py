def _segment(family: Family) -> dict:
    """Validate every certified active instance and return its representative."""

    expected_by_circuit: dict[str, list[int]] = {}
    for circuit, segment in family.instances:
        expected_by_circuit.setdefault(circuit, []).append(segment)
    found: dict[tuple[str, int], dict] = {}
    digest = family.key.split("@", 1)[1]
    for circuit, expected_indices in expected_by_circuit.items():
        matches = [
            segment
            for segment in _circuit_ir(circuit)["segments"]
            if segment.get("proof_template_id") == family.key
        ]
        actual_indices = [segment.get("index") for segment in matches]
        if actual_indices != expected_indices:
            raise ValueError(
                f"{family.key}/{circuit}: active segment roster drifted: "
                f"{actual_indices!r} != {expected_indices!r}"
            )
        for segment in matches:
            if (
                segment.get("op") != "decaf.compress_to_field"
                or segment.get("constraint_count") != ROW_COUNT
                or segment.get("deployed_normalized_relation_sha256_hex")
                != digest
            ):
                raise ValueError(
                    f"{family.key}/{circuit}: active segment shape drifted"
                )
            template = SegmentTemplate.parse(segment)
            seating = template.canonical_wire_seating
            if (
                template.proof_template_id != family.key
                or len(seating) != family.local_wire_count
                or seating[0] != 0
                or len(set(seating)) != len(seating)
            ):
                raise ValueError(
                    f"{family.key}/{circuit}: normalized seating drifted"
                )
            found[(circuit, segment["index"])] = segment
    try:
        return found[family.instances[0]]
    except KeyError as error:
        raise ValueError(
            f"{family.key}: active representative is absent"
        ) from error


def _relation_source(family: Family) -> str:
    paths = sorted(RELATIONS.glob(f"{family.relation_stem}*.lean"))
    if not paths:
        raise ValueError(f"missing normalized relation modules for {family.key}")
    return "\n".join(path.read_text() for path in paths)


def relation_rows(
    source: str,
    row_start: int = 0,
    row_count: int = ROW_COUNT,
) -> dict[int, str]:
    """Parse one contiguous row window from a normalized relation.

    Whole-operation providers use the default 1,046-row relation. Composite
    providers use this same reviewed proof backend against an embedded
    compress prefix while retaining the parent relation's row identifiers.
    """
    all_rows = {
        int(match.group(1)): match.group(2).strip()
        for match in re.finditer(
            r"def relationRow(\d+) \(rho : Nat -> F\) : Prop :=\n"
            r"(.*?)(?=\n\ndef |\n\nend )",
            source,
            re.S,
        )
    }
    expected = set(range(row_start, row_start + row_count))
    if not expected <= all_rows.keys():
        missing = sorted(expected - all_rows.keys())
        raise ValueError(
            "normalized relation row window is incomplete: "
            f"start={row_start} count={row_count} missing={missing[:8]}"
        )
    return {row: all_rows[row] for row in sorted(expected)}


def _rows(source: str) -> dict[int, str]:
    rows = relation_rows(source)
    if set(rows) != set(range(ROW_COUNT)):
        raise ValueError(f"normalized compress relation has {len(rows)} non-contiguous rows")
    return rows


@lru_cache(maxsize=None)
def _relation_lc_graph(family: Family) -> tuple[dict[int, str], dict[str, str]]:
    source = _relation_source(family)
    rows = relation_rows(source, family.row_offset)
    definitions = {
        match.group(1): match.group(2)
        for match in re.finditer(
            r"def (relationLc\d+(?:Part\d+)?) \(rho : Nat -> F\) : F :=\n"
            r"(.*?)(?=\n\ndef |\n\nend )",
            source,
            re.S,
        )
    }
    return rows, definitions


def _relation_lc_names(family: Family, row: int) -> list[str]:
    rows, definitions = _relation_lc_graph(family)
    names: list[str] = []
    pending = list(re.findall(r"\b(relationLc\d+(?:Part\d+)?)\b", rows[row]))
    while pending:
        name = pending.pop(0)
        if name in names:
            continue
        names.append(name)
        pending.extend(
            ref
            for ref in re.findall(r"\b(relationLc\d+(?:Part\d+)?)\b", definitions.get(name, ""))
            if ref not in names
        )
    return names


def _relation_lc_simp(family: Family, row: int) -> str:
    _, definitions = _relation_lc_graph(family)
    names = _relation_lc_names(family, row)
    # The normalized boundary seating may expose the input coordinates through
    # canonical templateRho slots even when the deployed row itself references
    # only a later LC.  Unfold those two boundary roots symmetrically so both
    # sides of `simpa using rN` use the same StructuredLC presentation.
    names = [
        *(name for name in ("relationLc0", "relationLc1") if name in definitions),
        *names,
    ]
    return ", ".join(
        f"{family.relation_namespace}.{name}" for name in dict.fromkeys(names)
    )


def _relation_lc_root(family: Family, row: int) -> str:
    roots = [
        name
        for name in _relation_lc_names(family, row)
        if re.fullmatch(r"relationLc\d+", name)
    ]
    if len(roots) != 1:
        raise ValueError(f"{family.key}: expected one root LC for row {row}, found {roots}")
    return roots[0]


def _relation_lc_chunks(family: Family, row: int) -> list[tuple[str, int, int]]:
    _, definitions = _relation_lc_graph(family)
    parts = [
        name
        for name in _relation_lc_names(family, row)
        if re.fullmatch(r"relationLc\d+Part\d+", name)
    ]
    chunks: list[tuple[str, int, int]] = []
    offset = 0
    for name in parts:
        width = len(re.findall(r"\brho \d+", definitions[name]))
        if width == 0:
            raise ValueError(f"{family.key}: LC chunk {name} is empty")
        chunks.append((name, width, offset))
        offset += width
    if offset != 253:
        raise ValueError(f"{family.key}: LC chunks cover {offset} bits instead of 253")
    return chunks


def _parts(source: str) -> list[list[int]]:
    found: dict[int, list[int]] = {}
    for match in re.finditer(
        r"def relationPart(\d+) \(rho : Nat -> F\) : Prop :=\n(.*?)(?=\n\ndef |\n\nend )",
        source,
        re.S,
    ):
        found[int(match.group(1))] = [
            int(row) for row in re.findall(r"relationRow(\d+) rho", match.group(2))
        ]
    if set(found) != set(range(len(found))):
        raise ValueError("normalized compress relation parts are non-contiguous")
    parts = [found[index] for index in range(len(found))]
    flattened = [row for part in parts for row in part]
    if flattened != list(range(ROW_COUNT)):
        raise ValueError("normalized compress relation parts do not cover rows exactly once")
    return parts


def relation_parts(source: str) -> list[list[int]]:
    """Parse every normalized relation part without assuming a row count."""
    found: dict[int, list[int]] = {}
    for match in re.finditer(
        r"def relationPart(\d+) \(rho : Nat -> F\) : Prop :=\n"
        r"(.*?)(?=\n\ndef |\n\nend )",
        source,
        re.S,
    ):
        found[int(match.group(1))] = [
            int(row)
            for row in re.findall(r"relationRow(\d+) rho", match.group(2))
        ]
    if not found or set(found) != set(range(len(found))):
        raise ValueError("normalized relation parts are absent or non-contiguous")
    parts = [found[index] for index in range(len(found))]
    flattened = [row for part in parts for row in part]
    if flattened != list(range(len(flattened))):
        raise ValueError("normalized relation parts do not cover rows exactly once")
    return parts


def _first_operand(row: str) -> str:
    if not row.startswith("("):
        raise ValueError("compress coordinate row no longer starts with a parenthesized operand")
    depth = 0
    for index, char in enumerate(row):
        if char == "(":
            depth += 1
        elif char == ")":
            depth -= 1
            if depth == 0:
                return row[1:index]
    raise ValueError("unbalanced normalized compress coordinate operand")


def _coordinate_operand(family: Family, row: str) -> str:
    """Return the exact row operand, qualifying its normalized opaque atoms."""
    operand = _first_operand(row)
    unit_wire = re.fullmatch(r"\(1 : F\) \* rho (\d+)", operand)
    if unit_wire is not None:
        return f"rho {unit_wire.group(1)}"
    return re.sub(
        r"\brelationLc(\d+)\b",
        rf"{family.relation_namespace}.relationLc\1",
        operand,
    )


def _part_map(parts: list[list[int]]) -> dict[int, int]:
    result = {}
    for part, rows in enumerate(parts):
        for row in rows:
            if row in result:
                raise ValueError(f"row {row} occurs in multiple relation parts")
            result[row] = part
    return result


def _part_indices(parts: list[list[int]], rows: list[int]) -> list[int]:
    mapping = _part_map(parts)
    missing = sorted(set(rows) - mapping.keys())
    if missing:
        raise ValueError(f"rows absent from normalized relation parts: {missing}")
    return sorted({mapping[row] for row in rows})


def _unpack_parts(lines: list[str], family: Family, parts: list[list[int]], indices: list[int]) -> None:
    exact = family.relation_namespace
    for part in indices:
        rows = parts[part]
        lines.append(f"  unfold {exact}.relationPart{part} at p{part}")
        if len(rows) == 1:
            lines.append(f"  have r{rows[0]} := p{part}")
        else:
            lines.append(f"  rcases p{part} with ⟨{', '.join(f'r{row}' for row in rows)}⟩")


