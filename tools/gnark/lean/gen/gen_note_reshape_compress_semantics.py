def _wire_mapping(family: Family, segment: dict) -> dict[int, int]:
    inverse = {global_wire: local for local, global_wire in enumerate(segment["wire_seating"])}
    mapping = {}
    for extracted in range(210, 913):
        global_wire = extracted + family.internal_offset
        if global_wire not in inverse:
            raise ValueError(f"{family.key}: extracted wire {extracted} is not locally seated")
        mapping[extracted] = inverse[global_wire]
    deltas = {mapping[wire] - wire for wire in range(231, 913)}
    if len(deltas) != 1:
        raise ValueError(f"{family.key}: recomposition range stopped being affine")
    return mapping


def _rho_definition(family: Family, mapping: dict[int, int], x: str, y: str) -> list[str]:
    delta = next(iter({mapping[wire] - wire for wire in range(231, 913)}))
    lines = [
        "def inputX (rho : Nat → F) : F :=",
        f"  {x}",
        "",
        "def inputY (rho : Nat → F) : F :=",
        f"  {y}",
        "",
        "def templateRho (rho : Nat → F) : Nat → F",
        "| 0 => 1",
        "| 17 => inputX rho",
        "| 18 => inputY rho",
    ]
    for wire in range(210, 231):
        lines.append(f"| {wire} => rho {mapping[wire]}")
    if delta < 0:
        affine = f"rho (i - {-delta})"
    else:
        affine = f"rho (i + {delta})"
    lines.extend(
        [
            f"| i => if 231 ≤ i ∧ i ≤ 912 then {affine} else rho i",
            "",
        ]
    )
    return lines


def _recomp_lemma(
    lines: list[str], family: Family, parts: list[list[int]], which: int, row: int, base: int, inp: int
) -> None:
    exact = family.relation_namespace
    chunks = _relation_lc_chunks(family, row)
    part = _part_indices(parts, [row])[0]
    lines.extend(
        [
            f"theorem hrec{which} (rho : Nat → F)",
            f"    (p{part} : {exact}.relationPart{part} rho) :",
            f"    recover_binary_zmod' (List.Vector.ofFn (fun i : Fin 253 => templateRho rho ({base} + i.val))) =",
            f"      templateRho rho {inp} := by",
        ]
    )
    _unpack_parts(lines, family, parts, [part])
    lines.extend(
        [
            f"  have hrow := r{row}",
            f"  have hrec := recover_ofFn_eq_recBits (templateRho rho) {base} 253",
            "  rw [hrec]",
            f"  have hacc := hacc{which} rho hrow",
            "  rw [powSumAcc_eq] at hacc",
            "  simpa only [zero_add, one_mul] using hacc",
            "",
        ]
    )


def _chunks(family: Family, rows: dict[int, str], mapping: dict[int, int]) -> str:
    x, y = _coordinate_operand(family, rows[0]), _coordinate_operand(family, rows[1])
    lines = [
        GENERATED.rstrip(),
        f"import {BINARY_MODULE}",
        f"import {family.relation_module}",
        "import ShielddGnarkFormal.Deployed.PrimeOrder",
        "",
        "set_option maxRecDepth 1000000",
        "set_option maxHeartbeats 20000000",
        "set_option linter.unusedVariables false",
        "",
        f"namespace {family.namespace}",
        "",
        f"open {BINARY_NAMESPACE}",
        "",
        f"def Order : Nat := {ORDER}",
        "abbrev F := ZMod Order",
        "",
        "local instance : Fact (Nat.Prime Order) :=",
        "  ⟨Shieldd.GnarkFormal.Deployed.decaf377ScalarFieldPrime⟩",
        "",
    ]
    lines.extend(_rho_definition(family, mapping, x, y))
    for which, row, base, inp in ((1, 281, 231, 230), (2, 791, 573, 572)):
        chunks = _relation_lc_chunks(family, row)
        root = _relation_lc_root(family, row)
        for index, (name, width, offset) in enumerate(chunks):
            pow_expr = "1" if offset == 0 else f"(2 ^ {offset} : F)"
            pow_literal = str(2 ** offset)
            chunk_base = base + offset
            lines.extend(
                [
                    f"theorem hpart{which}_{index} (rho : Nat → F) :",
                    f"    powSumAcc (templateRho rho) 0 {pow_expr} {chunk_base} {width} = {family.relation_namespace}.{name} rho := by",
                    "  rw [powSumAcc_eq_weightedSum]",
                    f"  simp [weightedSum, templateRho, {family.relation_namespace}.{name}]; ring",
                    "",
                ]
            )
            lines.extend(
                [
                    f"theorem hchunk{which}_{index} (rho : Nat → F) (acc : F) :",
                    f"    powSumAcc (templateRho rho) acc {pow_literal} {chunk_base} {width} = acc + {family.relation_namespace}.{name} rho := by",
                    f"  have h := hpart{which}_{index} rho",
                    "  norm_num at h",
                    "  rw [powSumAcc_add_acc]",
                    "  simpa only [one_mul] using congrArg (fun value => acc + value) h",
                    "",
                ]
            )
        lines.extend(
            [
                f"theorem hacc{which} (rho : Nat → F) (hrow : {family.relation_namespace}.relationRow{row} rho) :",
                f"    powSumAcc (templateRho rho) 0 1 {base} 253 = templateRho rho {inp} := by",
                f"  unfold {family.relation_namespace}.relationRow{row} at hrow",
            ]
        )
        remaining = 253
        for _, width, _ in chunks[:-1]:
            next_remaining = remaining - width
            lines.extend(
                [
                    f"  rw [show ({remaining} : Nat) = {width} + {next_remaining} by norm_num,",
                    "    powSumAcc_split32]",
                ]
            )
            remaining = next_remaining
        lines.append("  norm_num")
        lines.append(
            "  rw [" + ", ".join(
                f"hchunk{which}_{index}" for index in range(len(chunks) - 1, -1, -1)
            ) + "]"
        )
        lines.extend(
            [
                f"  simpa only [zero_add, {family.relation_namespace}.{root}, one_mul, templateRho] using hrow",
                "",
            ]
        )
    lines.append(f"end {family.namespace}")
    return "\n".join(lines) + "\n"


def _base(family: Family, rows: dict[int, str], parts: list[list[int]], mapping: dict[int, int]) -> str:
    lines = [
        GENERATED.rstrip(),
        f"import {family.module}Chunks",
        "",
        "set_option maxRecDepth 1000000",
        "set_option maxHeartbeats 20000000",
        "set_option linter.unusedVariables false",
        "",
        f"namespace {family.namespace}",
        "",
        "open Shieldd.GnarkFormal.Extracted.DecafCompressToField",
        f"open {BINARY_NAMESPACE}",
        "",
    ]
    lines.extend(
        [
            "def spec (rho : Nat → F) : Prop :=",
            "  Relation (inputX rho) (inputY rho) (templateRho rho 912 - templateRho rho 572)",
            "",
        ]
    )
    _recomp_lemma(lines, family, parts, 1, 281, 231, 230)
    _recomp_lemma(lines, family, parts, 2, 791, 573, 572)
    lines.append(f"end {family.namespace}")
    return "\n".join(lines) + "\n"


def _row_chunk(
    family: Family,
    index: int,
    chunk: list[tuple[int, str]],
    parts: list[list[int]],
) -> str:
    exact = family.relation_namespace
    rows = [reviewed.bridge_row_for_hyp(hyp) for hyp, _ in chunk]
    indices = _part_indices(parts, rows)
    lines = [
        GENERATED.rstrip(),
        f"import {family.module}Base",
        f"import {COMMON_MODULE}",
        "",
        "set_option maxRecDepth 1000000",
        "set_option maxHeartbeats 20000000",
        "set_option linter.unusedVariables false",
        "",
        f"namespace {family.namespace}",
        "",
        f"open {COMMON_NAMESPACE}",
        "",
        f"theorem rows{index} (rho : Nat → F)",
    ]
    for part in indices:
        lines.append(f"    (p{part} : {exact}.relationPart{part} rho)")
    lines.append(f"    : CompressRows{index} (templateRho rho) := by")
    _unpack_parts(lines, family, parts, indices)
    lines.append("  refine ⟨" + ", ".join("?_" for _ in chunk) + "⟩")
    for hyp, _ in chunk:
        row = reviewed.bridge_row_for_hyp(hyp)
        lc_simp = _relation_lc_simp(family, row)
        simp = f"[templateRho, inputX, inputY, mul_eq_zero{', ' + lc_simp if lc_simp else ''}]"
        lines.extend(
            [
                f"  · unfold {exact}.relationRow{row} at r{row}",
                f"    simpa {simp} using r{row}",
            ]
        )
    lines.extend(["", f"end {family.namespace}"])
    return "\n".join(lines) + "\n"


def _head(family: Family, hyps: list[tuple[int, str]], parts: list[list[int]]) -> str:
    exact = family.relation_namespace
    chunks = reviewed.chunks(hyps, BRIDGE_CHUNK_SIZE)
    lines = [GENERATED.rstrip()]
    for index in range(len(chunks)):
        lines.append(f"import {family.module}Rows{index}")
    lines.extend(
        [
            "",
            "set_option maxRecDepth 1000000",
            "set_option maxHeartbeats 20000000",
            "set_option linter.unusedVariables false",
            "",
            f"namespace {family.namespace}",
            "",
            f"open {COMMON_NAMESPACE}",
            "",
            f"theorem sound (rho : Nat → F) (h : {exact}.relation rho) : spec rho := by",
            f"  unfold {exact}.relation at h",
            "  rcases h with ⟨",
        ]
    )
    names = [f"p{index}" for index in range(len(parts))]
    for chunk in reviewed.chunks(names, 8):
        lines.append("    " + ", ".join(chunk) + ",")
    lines[-1] = lines[-1].rstrip(",")
    lines.extend(
        [
            "  ⟩",
            "  unfold spec",
            "  exact inst_compress_deployed_sound_chunked (templateRho rho)",
        ]
    )
    for index, hyp_chunk in enumerate(chunks):
        rows = [reviewed.bridge_row_for_hyp(hyp) for hyp, _ in hyp_chunk]
        args = " ".join(f"p{part}" for part in _part_indices(parts, rows))
        lines.append(f"    (rows{index} rho {args})")
    lines.extend(
        [
            f"    (hrec1 rho p{_part_indices(parts, [281])[0]})",
            f"    (hrec2 rho p{_part_indices(parts, [791])[0]})",
            "    rfl",
            "",
            f"end {family.namespace}",
        ]
    )
    return "\n".join(lines) + "\n"


def benchmark_candidates() -> tuple[Path, ...]:
    """Required first/middle/final row shards plus final aggregators."""
    return tuple(
        OUT / f"{family.name}{suffix}.lean"
        for family in FAMILIES
        for suffix in ("Rows0", "Rows8", "Rows16", "")
    )


def generated_files() -> dict[Path, str]:
    hyps = reviewed.parse_bridge_hyps()
    reviewed.validate_bridge_hyps(hyps)
    hyp_chunks = reviewed.chunks(hyps, BRIDGE_CHUNK_SIZE)
    outputs = {
        OUT / "BinaryRecomposition.lean": _binary_recomposition(),
        OUT / "CompressToFieldCommon.lean": _common(hyps),
    }
    bench_labels = (("Rows0", "Rows0"), ("Rows8", "Rows8"), ("Rows16", "Rows16"), ("Final", ""))
    for family in FAMILIES:
        source = _relation_source(family)
        rows, parts = _rows(source), _parts(source)
        mapping = _wire_mapping(family, _segment(family))
        outputs[OUT / f"{family.name}Chunks.lean"] = _chunks(family, rows, mapping)
        outputs[OUT / f"{family.name}Base.lean"] = _base(family, rows, parts, mapping)
        for index, chunk in enumerate(hyp_chunks):
            outputs[OUT / f"{family.name}Rows{index}.lean"] = _row_chunk(
                family, index, chunk, parts
            )
        outputs[OUT / f"{family.name}.lean"] = _head(family, hyps, parts)
        for label, suffix in bench_labels:
            path = BENCH / f"NoteReshapeTemplateCompress{family.name[-8:]}{label}Import.lean"
            outputs[path] = f"import {family.module}{suffix}\n"

    expected = 2 + len(FAMILIES) * (3 + len(hyp_chunks) + len(bench_labels))
    if len(outputs) != expected:
        raise ValueError(f"expected {expected} compress semantic outputs, generated {len(outputs)}")
    combined = "\n".join(text for path, text in outputs.items() if path.parent == OUT)
    forbidden = (
        "NoteReshape2x1",
        "representativeRho",
        "representativeSeating",
        "seg48_flat",
        "seg5_flat",
        "LC_COORDS",
    )
    for marker in forbidden:
        if marker in combined:
            raise ValueError(f"direct normalized compress provider retained {marker}")
    return outputs


if __name__ == "__main__":
    for path, source in generated_files().items():
        write_if_changed(path, source)
