def _validate_is_zero() -> None:
    name = template_name(IS_ZERO_KEY)
    digest = IS_ZERO_KEY.split("@", 1)[1]
    rows = _canonical_rows(digest, 2)
    expected = (
        (
            {1: ORDER - 1},
            {2: 1},
            {0: ORDER - 1, 3: 1},
        ),
        ({1: 1}, {3: 1}, {}),
    )
    if rows != expected:
        raise ValueError(f"{name}: normalized isZero rows drifted")

    facade = RELATIONS / f"{name}.lean"
    if not facade.is_file():
        raise ValueError(f"{name}: missing normalized relation module")
    definitions = re.findall(r"^def ([A-Za-z0-9]+) ", facade.read_text(), re.MULTILINE)
    if definitions != ["relationSegment0", "relation"]:
        raise ValueError(f"{name}: normalized relation facade drifted")


