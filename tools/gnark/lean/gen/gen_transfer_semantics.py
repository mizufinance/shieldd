def camel(text: str) -> str:
    result: list[str] = []
    upper = True
    for char in text:
        if char in "._-":
            upper = True
        elif upper:
            result.append(char.upper())
            upper = False
        else:
            result.append(char)
    return "".join(result)


def template_name(key: str) -> str:
    operation, digest = key.split("@", 1)
    return f"T{camel(operation)}_{digest}"


Lc = dict[int, int]
Row = tuple[Lc, Lc, Lc]


def _canonical_rows(digest: str, expected: int) -> tuple[Row, ...]:
    path = CANONICAL / f"{digest}.sr1cs.gz"
    pattern = re.compile(r"\(constraint \[(.*?)\] \[(.*?)\] \[(.*?)\]\)")
    rows: list[Row] = []
    with gzip.open(path, "rt") as source:
        for raw in source:
            match = pattern.fullmatch(raw.strip())
            if match is None:
                raise ValueError(f"{digest}: malformed canonical row {len(rows)}")
            sides: list[Lc] = []
            for group in match.groups():
                side: Lc = {}
                for coefficient, wire in re.findall(r"\(([-0-9]+) (\d+)\)", group):
                    index = int(wire)
                    value = (side.get(index, 0) + int(coefficient)) % ORDER
                    if value:
                        side[index] = value
                    else:
                        side.pop(index, None)
                sides.append(side)
            rows.append((sides[0], sides[1], sides[2]))
    if len(rows) != expected:
        raise ValueError(f"{digest}: expected {expected} rows, got {len(rows)}")
    return tuple(rows)


def _relation_source(name: str) -> str:
    shards = sorted(
        RELATIONS.glob(f"{name}Defs*.lean"),
        key=lambda path: int(path.stem.removeprefix(name + "Defs")),
    )
    facade = RELATIONS / f"{name}.lean"
    if not shards or not facade.is_file():
        raise ValueError(f"{name}: missing normalized relation modules")
    indices = [int(path.stem.removeprefix(name + "Defs")) for path in shards]
    if indices != list(range(len(indices))):
        raise ValueError(f"{name}: non-contiguous normalized relation shards")
    return "\n".join(path.read_text() for path in (*shards, facade))


def _relation_lc_names(source: str) -> tuple[str, ...]:
    return tuple(sorted(set(re.findall(r"\bdef (relationLc[A-Za-z0-9]+) ", source))))


def _lc_add(left: Lc, right: Lc) -> Lc:
    result = dict(left)
    for wire, coefficient in right.items():
        value = (result.get(wire, 0) + coefficient) % ORDER
        if value:
            result[wire] = value
        else:
            result.pop(wire, None)
    return result


def _lc_scale(coefficient: int, value: Lc) -> Lc:
    return {
        wire: product
        for wire, term in value.items()
        if (product := coefficient * term % ORDER)
    }


def _lc_constant(value: int) -> Lc:
    reduced = value % ORDER
    return {0: reduced} if reduced else {}


def _lc_wire(wire: int) -> Lc:
    return {wire: 1}


def _lc_linear_combination(coefficients: tuple[int, ...], values: tuple[Lc, ...]) -> Lc:
    result: Lc = {}
    for coefficient, value in zip(coefficients, values, strict=True):
        result = _lc_add(result, _lc_scale(coefficient, value))
    return result


def _render_lc(value: Lc) -> str:
    terms: list[str] = []
    constant = value.get(0, 0)
    if constant:
        terms.append(f"({constant} : F)")
    for wire, coefficient in sorted(value.items()):
        if wire:
            terms.append(f"({coefficient} : F) * rho {wire}")
    return " + ".join(terms) if terms else "(0 : F)"


def _singleton(side: Lc, label: str) -> int:
    if len(side) != 1:
        raise ValueError(f"{label}: expected singleton output, got {side}")
    wire, coefficient = next(iter(side.items()))
    if wire == 0 or coefficient != 1:
        raise ValueError(f"{label}: expected coefficient-one witness, got {side}")
    return wire


def _blake2b_field(label: str) -> int:
    return int.from_bytes(
        hashlib.blake2b(label.encode(), digest_size=64).digest(), "little"
    ) % ORDER


def _powers17(value: int) -> tuple[int, int, int, int, int]:
    value %= ORDER
    q2 = value * value % ORDER
    q4 = q2 * q2 % ORDER
    q8 = q4 * q4 % ORDER
    q16 = q8 * q8 % ORDER
    return q2, q4, q8, q16, q16 * value % ORDER


def _cast_certificate(left: int, right: int) -> str:
    if left % ORDER != right % ORDER:
        raise ValueError(f"invalid field-cast certificate: {left} != {right} mod Order")
    return (
        "Shieldd.GnarkFormal.ChoiceFreeZMod.natCast_eq_natCast_of_mod_eq "
        f"Order {left} {right} (by decide) (by decide)"
    )


