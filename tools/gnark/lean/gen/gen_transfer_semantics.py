def _fixed_p17_lemma(
    recovery: SaltRecovery,
    name: str,
    input_value: int,
    powers: tuple[int, int, int, int, int],
) -> str:
    values = (input_value % ORDER, *powers)
    certificates = [
        _cast_certificate(values[0] * values[0], values[1]),
        _cast_certificate(values[1] * values[1], values[2]),
        _cast_certificate(values[2] * values[2], values[3]),
        _cast_certificate(values[3] * values[3], values[4]),
        _cast_certificate(values[4] * values[0], values[5]),
    ]
    return f"""theorem {name} :
    ({powers[-1]} : F) =
      Shieldd.GnarkFormal.Poseidon2Bridge.p17 ({input_value} : F) := by
  exact TransferPoseidon2Trace.p17_from_rows
    ({input_value} : F)
    ({powers[0]} : F) ({powers[1]} : F) ({powers[2]} : F)
    ({powers[3]} : F) ({powers[4]} : F)
    ({certificates[0]}) ({certificates[1]}) ({certificates[2]})
    ({certificates[3]}) ({certificates[4]})
"""


def _render_salt_base(recovery: SaltRecovery) -> str:
    imports = """import ShielddGnarkFormal.ChoiceFreeZModCast
import ShielddGnarkFormal.Deployed.PrimeOrder
import ShielddGnarkFormal.Deployed.Templates.Semantics.TransferPoseidon2Trace
import Mathlib.Tactic.LinearCombination
import Mathlib.Tactic.Ring"""
    definitions = [
        f"def domain : F := ({recovery.domain} : F)",
        f"def label : F := ({recovery.label_value} : F)",
    ]
    definitions.extend(
        f"def input{part} (rho : Nat → F) : F :=\n  {_render_lc(value)}"
        for part, value in enumerate(recovery.inputs)
    )

    fixed = [
        _fixed_p17_lemma(
            recovery,
            "domainP17",
            (recovery.domain + poseidon_rounds(2)[0][1][0]) % ORDER,
            recovery.domain_powers,
        ),
        _fixed_p17_lemma(
            recovery,
            "labelP17",
            (recovery.label_value + poseidon_rounds(2)[0][1][2]) % ORDER,
            recovery.label_powers,
        ),
    ]

    endpoints: list[str] = []
    for gate, state in enumerate(recovery.states):
        endpoints.append(
            f"def endpoint{gate} (rho : Nat → F) : List.Vector F 3 :=\n"
            f"  vec![{', '.join(_render_lc(lane) for lane in state)}]"
        )
        for lane, value in enumerate(state):
            endpoints.append(
                f"theorem endpoint{gate}Lane{lane} (rho : Nat → F) :\n"
                f"    (endpoint{gate} rho)[{lane}] = {_render_lc(value)} := by\n"
                f"  rfl"
            )

    input_links: list[str] = []
    rounds = poseidon_rounds(2)
    for gate in range(1, 39):
        lanes = range(3) if rounds[gate][0] == "fr3" else range(1)
        for lane, part in zip(lanes, recovery.gate_parts[gate], strict=True):
            previous = recovery.states[gate - 1][lane]
            constant = rounds[gate][1][lane]
            current_input = recovery.inputs[part]
            if {
                wire: coefficient
                for wire, coefficient in current_input.items()
                if wire
            } != {
                wire: coefficient for wire, coefficient in previous.items() if wire
            }:
                raise ValueError(
                    f"{recovery.name}: gate {gate} lane {lane} nonconstant input drift"
                )
            previous_constant = previous.get(0, 0)
            input_constant = current_input.get(0, 0)
            certificate = _cast_certificate(
                previous_constant + constant, input_constant
            )
            input_links.append(
                f"""theorem input{part}_eq_arg (rho : Nat → F) :
    input{part} rho =
      (endpoint{gate - 1} rho)[{lane}] + ({constant} : F) := by
  rw [endpoint{gate - 1}Lane{lane}]
  unfold input{part}
  have hc : ({previous_constant + constant} : F) =
      ({input_constant} : F) := by
    exact {certificate}
  rw [← hc]
  ring
"""
            )

    return (
        _salt_prelude(recovery, imports)
        + "\n".join(definitions)
        + "\n\n"
        + "\n".join(fixed)
        + "\n"
        + "\n\n".join(endpoints)
        + "\n\n"
        + "\n".join(input_links)
        + f"\nend Shieldd.GnarkFormal.Deployed.Templates.Semantics.{recovery.name}\n"
    )


# Keep each Poseidon round in its own Lean module.  The endpoint expressions are
# flattened circuit linear combinations, so composing several rounds in one
# theorem makes elaboration retain every progressively larger polynomial at
# once.  Per-round modules preserve the same proof chain while bounding peak
# memory and making the release build practical on the verifier host.
GATE_RANGES = tuple((gate, gate) for gate in range(39))


def _raw_gate_state(recovery: SaltRecovery, gate: int) -> tuple[Lc, Lc, Lc]:
    rounds = poseidon_rounds(2)
    if gate == 0:
        part = recovery.gate_parts[0][0]
        sbox_values = (
            _lc_constant(recovery.domain_powers[-1]),
            _lc_wire(recovery.outputs[part]),
            _lc_constant(recovery.label_powers[-1]),
        )
    elif rounds[gate][0] == "fr3":
        sbox_values = tuple(
            _lc_wire(recovery.outputs[part])
            for part in recovery.gate_parts[gate]
        )
    else:
        previous = recovery.states[gate - 1]
        constants = rounds[gate][1]
        passive_lanes = []
        for lane in (1, 2):
            value = dict(previous[lane])
            value[0] = value.get(0, 0) + constants[lane]
            passive_lanes.append(value)
        sbox_values = (
            _lc_wire(recovery.outputs[recovery.gate_parts[gate][0]]),
            *passive_lanes,
        )

    raw_state: list[Lc] = []
    for row in MDS:
        value: Lc = {}
        for coefficient, lane in zip(row, sbox_values, strict=True):
            for wire, term in lane.items():
                value[wire] = value.get(wire, 0) + coefficient * term
        raw_state.append(value)
    return tuple(raw_state)  # type: ignore[return-value]


def _render_gate_casts(
    recovery: SaltRecovery, gate: int
) -> tuple[list[str], tuple[tuple[str, ...], ...]]:
    raw_state = _raw_gate_state(recovery, gate)
    definitions: list[str] = []
    lane_names: list[tuple[str, ...]] = []
    for lane, (raw, reduced) in enumerate(
        zip(raw_state, recovery.states[gate], strict=True)
    ):
        names: list[str] = []
        for index, wire in enumerate(sorted(set(raw) | set(reduced))):
            left = raw.get(wire, 0)
            right = reduced.get(wire, 0)
            if left == right:
                continue
            name = f"hc{lane}_{index}"
            names.append(name)
            definitions.extend(
                [
                    f"    have {name} : ({left} : F) = ({right} : F) := by",
                    f"      exact {_cast_certificate(left, right)}",
                ]
            )
        lane_names.append(tuple(names))
    return definitions, tuple(lane_names)


def _render_salt_parts(
    recovery: SaltRecovery, range_index: int, start: int, stop: int
) -> str:
    relation = f"Shieldd.GnarkFormal.Deployed.Templates.Relations.{recovery.name}"
    imports = f"""import ShielddGnarkFormal.Deployed.Templates.Semantics.{recovery.name}Base
import ShielddGnarkFormal.Deployed.Templates.Relations.{recovery.name}
import Mathlib.Tactic.LinearCombination"""
    parts = [
        part
        for gate in range(start, stop + 1)
        for part in recovery.gate_parts[gate]
    ]
    theorems = []
    for part in parts:
        rows = " ".join(
            f"{relation}.relationRow{row}" for row in range(part * 5, part * 5 + 5)
        )
        outputs = tuple(range(2 + part * 5, 7 + part * 5))
        lc_unfold = "\n".join(
            f"  try unfold {relation}.{name} at h0 h4"
            for name in recovery.relation_lcs
        )
        theorems.append(
            f"""theorem part{part}_sound (rho : Nat → F)
    (h : {relation}.relationPart{part} rho) :
    rho {outputs[-1]} =
      Shieldd.GnarkFormal.Poseidon2Bridge.p17 (input{part} rho) := by
  unfold {relation}.relationPart{part} {rows} at h
  rcases h with ⟨h0, h1, h2, h3, h4⟩
{lc_unfold}
  apply TransferPoseidon2Trace.p17_from_rows
      (input{part} rho) (rho {outputs[0]}) (rho {outputs[1]})
      (rho {outputs[2]}) (rho {outputs[3]}) (rho {outputs[4]})
  · unfold input{part}; linear_combination h0
  · linear_combination h1
  · linear_combination h2
  · linear_combination h3
  · unfold input{part}; linear_combination h4
"""
        )
    return (
        _salt_prelude(recovery, imports, f"Parts{range_index}")
        + f"open Shieldd.GnarkFormal.Deployed.Templates.Semantics.{recovery.name}\n\n"
        + "\n".join(theorems)
        + f"\nend Shieldd.GnarkFormal.Deployed.Templates.Semantics."
        f"{recovery.name}Parts{range_index}\n"
    )


def _render_salt_gates(
    recovery: SaltRecovery, range_index: int, start: int, stop: int
) -> str:
    if start != stop:
        raise ValueError("Transfer salt gate modules must contain exactly one round")
    relation = f"Shieldd.GnarkFormal.Deployed.Templates.Relations.{recovery.name}"
    trace = (
        "Shieldd.GnarkFormal.Deployed.Templates.Semantics.TransferPoseidon2Trace"
    )
    base = f"Shieldd.GnarkFormal.Deployed.Templates.Semantics.{recovery.name}"
    imports = f"""import ShielddGnarkFormal.Deployed.Templates.Semantics.{recovery.name}Parts{range_index}
import ShielddGnarkFormal.Deployed.Poseidon2Link
import ShielddGnarkFormal.ChoiceFreeZModCast
import Mathlib.Tactic.Ring"""
    parts = [
        part
        for gate in range(start, stop + 1)
        for part in recovery.gate_parts[gate]
    ]
    binders = " ".join(
        f"(p{part} : {relation}.relationPart{part} rho)" for part in parts
    )
    previous_binder = ""
    if start:
        previous_binder = (
            f"\n    (hPrev : {trace}.state{start - 1} domain (rho 1) label = "
            f"endpoint{start - 1} rho)"
        )
    lines = []
    rounds = poseidon_rounds(2)
    for gate in range(start, stop + 1):
        gate_parts = recovery.gate_parts[gate]
        for part in gate_parts:
            lines.append(
                f"  have hp{part} := {base}Parts{range_index}.part{part}_sound rho p{part}"
            )
        if gate == 0:
            part = gate_parts[0]
            raw_lanes = ",\n        ".join(
                f"Shieldd.GnarkFormal.Deployed.Poseidon2Link.row3 "
                f"({row[0]} : F) ({row[1]} : F) ({row[2]} : F) "
                f"({recovery.domain_powers[-1]} : F) "
                f"(rho {recovery.outputs[part]}) "
                f"({recovery.label_powers[-1]} : F)"
                for row in MDS
            )
            lines.extend(
                [
                    f"  have h{gate} : {trace}.state0 domain (rho 1) label = "
                    "endpoint0 rho := by",
                    "    let raw0 : List.Vector F 3 := vec![",
                    f"        {raw_lanes}]",
                    f"    have hd : ({recovery.domain_powers[-1]} : F) =",
                    "        Shieldd.GnarkFormal.Poseidon2Bridge.p17",
                    f"          ((vec![domain, rho 1, label])[0] + {trace}.roundConstants0[0]) := by",
                    f"      simpa [domain, {trace}.roundConstants0] using domainP17",
                    f"    have hw : rho {recovery.outputs[part]} = "
                    "Shieldd.GnarkFormal.Poseidon2Bridge.p17",
                    f"        ((vec![domain, rho 1, label])[1] + {trace}.roundConstants0[1]) := by",
                    f"      simpa [input{part}, {trace}.roundConstants0, add_comm] "
                    f"using hp{part}",
                    f"    have hl : ({recovery.label_powers[-1]} : F) =",
                    "        Shieldd.GnarkFormal.Poseidon2Bridge.p17",
                    f"          ((vec![domain, rho 1, label])[2] + {trace}.roundConstants0[2]) := by",
                    f"      simpa [label, {trace}.roundConstants0] using labelP17",
                    f"    have hRaw : {trace}.state0 domain (rho 1) label = raw0 := by",
                    f"      unfold {trace}.state0 raw0",
                    "      exact Shieldd.GnarkFormal.Deployed.Poseidon2Link.fr_eq3",
                    "        (vec![domain, rho 1, label]) "
                    f"{trace}.roundConstants0",
                    f"        ({recovery.domain_powers[-1]} : F) (rho {recovery.outputs[part]}) "
                    f"({recovery.label_powers[-1]} : F)",
                    "        hd hw hl",
                    "    rw [hRaw]",
                    "    unfold raw0",
                ]
            )
        else:
            lanes = range(3) if rounds[gate][0] == "fr3" else range(1)
            for lane, part in zip(lanes, gate_parts, strict=True):
                lines.extend(
                    [
                        f"  have ha{gate}_{lane} : rho {recovery.outputs[part]} = "
                        "Shieldd.GnarkFormal.Poseidon2Bridge.p17",
                        f"      ((endpoint{gate - 1} rho)[{lane}] + "
                        f"({rounds[gate][1][lane]} : F)) := by",
                        f"    rw [hp{part}, input{part}_eq_arg]",
                    ]
                )
            previous = "hPrev" if gate == start else f"h{gate - 1}"
            theorem = "fr_eq3" if rounds[gate][0] == "fr3" else "pr_eq3"
            output_args = " ".join(
                f"(rho {recovery.outputs[part]})" for part in gate_parts
            )
            proof_args = " ".join(f"ha{gate}_{lane}" for lane in lanes)
            lines.extend(
                [
                    f"  have h{gate} : {trace}.state{gate} domain (rho 1) label = "
                    f"endpoint{gate} rho := by",
                    f"    unfold {trace}.state{gate}",
                    f"    rw [{previous}]",
                    f"    rw [Shieldd.GnarkFormal.Deployed.Poseidon2Link.{theorem}",
                    f"      (endpoint{gate - 1} rho) {trace}.roundConstants{gate}",
                    f"      {output_args} {proof_args}]",
                ]
            )

        cast_definitions, lane_casts = _render_gate_casts(recovery, gate)
        lines.extend(cast_definitions)
        if gate == 0:
            simp_items = [
                "endpoint0",
                "Shieldd.GnarkFormal.Deployed.Poseidon2Link.row3",
            ]
        else:
            simp_items = [
                f"{trace}.roundConstants{gate}",
                f"endpoint{gate}",
                f"endpoint{gate - 1}",
                "Shieldd.GnarkFormal.Deployed.Poseidon2Link.row3",
            ]
        lines.extend(
            [
                "    apply List.Vector.eq",
                f"    simp [{', '.join(simp_items)}]",
            ]
        )
        if any(lane_casts):
            if not all(lane_casts):
                raise ValueError(
                    f"{recovery.name}: gate {gate} has mixed cast-free lanes"
                )
            lines.append("    constructor")
            for lane, names in enumerate(lane_casts):
                indent = "    · " if lane == 0 else "      · "
                if lane == 1:
                    lines.append("    · constructor")
                lines.append(f"{indent}ring_nf")
                lines.append(
                    f"{' ' * (len(indent) - 2)}  rw [{', '.join(names)}]"
                )
    return (
        _salt_prelude(recovery, imports, f"Gates{range_index}")
        + f"open Shieldd.GnarkFormal.Deployed.Templates.Semantics.{recovery.name}\n\n"
        + f"""theorem sound (rho : Nat → F) {binders}{previous_binder} :
    {trace}.state{stop} domain (rho 1) label = endpoint{stop} rho := by
{chr(10).join(lines)}
  exact h{stop}

end Shieldd.GnarkFormal.Deployed.Templates.Semantics.{recovery.name}Gates{range_index}
"""
    )


def _render_salt_main(recovery: SaltRecovery) -> str:
    relation = f"Shieldd.GnarkFormal.Deployed.Templates.Relations.{recovery.name}"
    namespace = f"Shieldd.GnarkFormal.Deployed.Templates.Semantics.{recovery.name}"
    trace = (
        "Shieldd.GnarkFormal.Deployed.Templates.Semantics.TransferPoseidon2Trace"
    )
    imports = "\n".join(
        f"import ShielddGnarkFormal.Deployed.Templates.Semantics."
        f"{recovery.name}Gates{index}"
        for index in range(len(GATE_RANGES))
    )
    imports += "\nimport ShielddGnarkFormal.TransferSaltBridge"
    unpack = "\n".join(
        f"  rcases h with ⟨p{part}, h⟩" for part in range(52)
    )
    thread = []
    for index, (start, stop) in enumerate(GATE_RANGES):
        parts = [
            part
            for gate in range(start, stop + 1)
            for part in recovery.gate_parts[gate]
        ]
        previous = "" if index == 0 else f" h{index - 1}"
        thread.append(
            f"  have h{index} := {namespace}Gates{index}.sound rho "
            f"{' '.join(f'p{part}' for part in parts)}{previous}"
        )
    return f"""{GENERATED_HEADER}{imports}

set_option maxRecDepth 1000000
set_option maxHeartbeats 20000000

namespace {namespace}

attribute [-instance] ZMod.instField
open scoped Shieldd.GnarkFormal.ChoiceFreeZMod

local instance : Fact (Nat.Prime Order) :=
  ⟨Shieldd.GnarkFormal.Deployed.decaf377ScalarFieldPrime⟩

def spec (rho : Nat → F) : Prop :=
  Shieldd.GnarkFormal.TransferSaltBridge.TransferSaltSpec
    domain (rho 1) label ((endpoint38 rho)[1])

theorem sound (rho : Nat → F) (h : {relation}.relation rho) : spec rho := by
  unfold {relation}.relation at h
{unpack}
  have p52 := h
{chr(10).join(thread)}
  unfold spec Shieldd.GnarkFormal.TransferSaltBridge.TransferSaltSpec
  calc
    (endpoint38 rho)[1] =
        ({trace}.state38 domain (rho 1) label)[1] := by
      exact congrArg (fun state => state[1]) h{len(GATE_RANGES) - 1}.symm
    _ = Shieldd.GnarkFormal.Poseidon377.hash2 domain (rho 1) label := by
      exact {trace}.output_eq_hash2 domain (rho 1) label

end {namespace}
"""


def _salt_files(recovery: SaltRecovery) -> dict[Path, str]:
    result = {
        OUT / f"{recovery.name}Base.lean": _render_salt_base(recovery),
        OUT / f"{recovery.name}.lean": _render_salt_main(recovery),
    }
    for index, (start, stop) in enumerate(GATE_RANGES):
        result[OUT / f"{recovery.name}Parts{index}.lean"] = _render_salt_parts(
            recovery, index, start, stop
        )
        result[OUT / f"{recovery.name}Gates{index}.lean"] = _render_salt_gates(
            recovery, index, start, stop
        )
    return result


def generated_files() -> dict[Path, str]:
    outputs = {
        OUT / "TransferPoseidon2Trace.lean": _render_trace(),
        OUT / f"{template_name(IS_ZERO_KEY)}.lean": _render_is_zero(),
    }
    for digest, label in SALT_KEYS.items():
        for path, source in _salt_files(_recover_salt(digest, label)).items():
            previous = outputs.get(path)
            if previous is not None and previous != source:
                raise ValueError(f"conflicting Transfer semantic output {path}")
            outputs[path] = source
    combined = "\n".join(outputs.values())
    for forbidden in (
        "representativeRho",
        "representativeSeating",
        "Contracts.Transfer",
        "axiom ",
        "sorry",
    ):
        if forbidden in combined:
            raise ValueError(f"Transfer semantic output retained {forbidden!r}")
    expected_mains = {
        OUT / f"{template_name(IS_ZERO_KEY)}.lean",
        *(
            OUT / f"TGadgetTransferSalt_{digest}.lean"
            for digest in SALT_KEYS
        ),
    }
    if not expected_mains <= outputs.keys():
        raise ValueError("Transfer semantic main-provider set is incomplete")
    return outputs


def main() -> None:
    for path, source in generated_files().items():
        write_if_changed(path, source)


if __name__ == "__main__":
    main()
