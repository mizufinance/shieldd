@dataclass(frozen=True)
class SaltRecovery:
    digest: str
    label: str
    name: str
    rows: tuple[Row, ...]
    inputs: tuple[Lc, ...]
    outputs: tuple[int, ...]
    gate_parts: tuple[tuple[int, ...], ...]
    states: tuple[tuple[Lc, Lc, Lc], ...]
    domain: int
    label_value: int
    domain_powers: tuple[int, int, int, int, int]
    label_powers: tuple[int, int, int, int, int]
    relation_lcs: tuple[str, ...]


def _recover_salt(digest: str, label: str) -> SaltRecovery:
    name = f"TGadgetTransferSalt_{digest}"
    rows = _canonical_rows(digest, 265)
    source = _relation_source(name)
    row_defs = {int(value) for value in re.findall(r"\bdef relationRow(\d+) ", source)}
    part_defs = {int(value) for value in re.findall(r"\bdef relationPart(\d+) ", source)}
    if row_defs != set(range(265)) or part_defs != set(range(53)):
        raise ValueError(f"{name}: normalized row/part facade drifted")

    domain = _blake2b_field(SALT_DOMAIN_LABEL)
    label_value = _blake2b_field(label)
    constants = poseidon_rounds(2)
    c0 = constants[0][1]
    domain_powers = _powers17(domain + c0[0])
    label_powers = _powers17(label_value + c0[2])

    gate_parts: list[tuple[int, ...]] = []
    cursor = 0
    states: list[tuple[Lc, Lc, Lc]] = []
    inputs: list[Lc] = []
    outputs: list[int] = []
    previous: tuple[Lc, Lc, Lc] | None = None

    for gate, (kind, round_constants) in enumerate(constants):
        count = 3 if kind == "fr3" else 1
        if gate == 0:
            # Domain and label are compile-time constants, so only the nonce
            # lane remains in the normalized relation.
            count = 1
            lanes = (1,)
        else:
            lanes = tuple(range(count))
        parts = tuple(range(cursor, cursor + count))
        gate_parts.append(parts)
        sbox_values: list[Lc]
        if gate == 0:
            expected_inputs = (
                _lc_add(_lc_wire(1), _lc_constant(round_constants[1])),
            )
            sbox_values = [
                _lc_constant(domain_powers[-1]),
                {},
                _lc_constant(label_powers[-1]),
            ]
        elif kind == "fr3":
            assert previous is not None
            expected_inputs = tuple(
                _lc_add(previous[lane], _lc_constant(round_constants[lane]))
                for lane in lanes
            )
            sbox_values = [{}, {}, {}]
        else:
            assert previous is not None
            expected_inputs = (
                _lc_add(previous[0], _lc_constant(round_constants[0])),
            )
            sbox_values = [
                {},
                _lc_add(previous[1], _lc_constant(round_constants[1])),
                _lc_add(previous[2], _lc_constant(round_constants[2])),
            ]

        for part, lane, expected_input in zip(parts, lanes, expected_inputs, strict=True):
            chunk = rows[part * 5 : part * 5 + 5]
            first = chunk[0]
            if first[0] != first[1] or first[0] != expected_input:
                raise ValueError(f"{name}: gate {gate} lane {lane} input drifted")
            chain_outputs = tuple(
                _singleton(row[2], f"{name}: part {part}") for row in chunk
            )
            if chain_outputs != tuple(range(2 + part * 5, 7 + part * 5)):
                raise ValueError(f"{name}: part {part} witness chain drifted")
            if chunk[1][0] != _lc_wire(chain_outputs[0]) or chunk[1][1] != chunk[1][0]:
                raise ValueError(f"{name}: part {part} square-2 row drifted")
            if chunk[2][0] != _lc_wire(chain_outputs[1]) or chunk[2][1] != chunk[2][0]:
                raise ValueError(f"{name}: part {part} square-4 row drifted")
            if chunk[3][0] != _lc_wire(chain_outputs[2]) or chunk[3][1] != chunk[3][0]:
                raise ValueError(f"{name}: part {part} square-8 row drifted")
            if (
                chunk[4][0] != _lc_wire(chain_outputs[3])
                or chunk[4][1] != expected_input
            ):
                raise ValueError(f"{name}: part {part} x17 row drifted")
            inputs.append(expected_input)
            outputs.append(chain_outputs[-1])
            sbox_values[lane] = _lc_wire(chain_outputs[-1])

        current = tuple(
            _lc_linear_combination(MDS[lane], tuple(sbox_values))
            for lane in range(3)
        )
        states.append(current)  # type: ignore[arg-type]
        previous = current  # type: ignore[assignment]
        cursor += count

    if cursor != 53 or len(inputs) != 53 or len(outputs) != 53:
        raise ValueError(f"{name}: expected exactly 53 surviving S-boxes")
    if states[-1][1] != {
        256: MDS[1][0],
        261: MDS[1][1],
        266: MDS[1][2],
    }:
        raise ValueError(f"{name}: final output LC drifted")
    return SaltRecovery(
        digest=digest,
        label=label,
        name=name,
        rows=rows,
        inputs=tuple(inputs),
        outputs=tuple(outputs),
        gate_parts=tuple(gate_parts),
        states=tuple(states),
        domain=domain,
        label_value=label_value,
        domain_powers=domain_powers,
        label_powers=label_powers,
        relation_lcs=_relation_lc_names(source),
    )


