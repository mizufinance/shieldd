        ("ShielddGnarkFormal.Deployed.NetBalance.Ladder", "ShielddGnarkFormal.RvkFixedRun"),
        ("ShielddGnarkFormal.NbFixedGenSeg46", "ShielddGnarkFormal.RvkFixedGenInst0"),
