def generated_dummy_rvk_semantic_files(
    out: Path = DEFAULT_OUT,
    template_name_fn: Callable[[str], str] = default_template_name,
) -> dict[Path, str]:
    """Return the exact dummy-RVK provider sources after fail-closed recovery."""
    seating = recover()
    relation_source = _relation_source()
    name = template_name_fn(TEMPLATE_KEY)
    support_ns = f"Shieldd.GnarkFormal.Deployed.Templates.Semantics.{name}.DummyRvkSupport"
    relation = f"Shieldd.GnarkFormal.Deployed.Templates.Relations.{RELATION_STEM}"
    relation_module = relation.replace("Shieldd.GnarkFormal", "ShielddGnarkFormal")
    root_prefix = f"{name}DummyRvk"
    module_root = f"ShielddGnarkFormal.Deployed.Templates.Semantics.{root_prefix}"
    outputs = {
        out / f"{root_prefix}Base.lean": GENERATED_HEADER + _emit_base(name, support_ns, relation_module)
    }
    for ladder, rungs in zip(LADDERS, seating["rungs"], strict=True):
        module_prefix = module_root + ladder.label
        with _configured(ladder, relation_source):
            modules = rvk_emitter.emit_blind_modules({"rows": seating["rows"], "blind": rungs})
            modules.pop("NbAdapterSeg46Blind")
            modules.pop("NbAdapterSeg46BlindEndpoint")
            binary = rvk_emitter.emit_to_binary_modules().pop("NbAdapterSeg46BlindBits")
        for old_name, source in modules.items():
            suffix = old_name.removeprefix("NbAdapterSeg46Blind")
            rewritten = _rewrite(source, ladder, module_prefix, support_ns, relation)
            outputs[out / f"{root_prefix}{ladder.label}{suffix}.lean"] = GENERATED_HEADER + rewritten
        rewritten_binary = _rewrite(binary, ladder, module_prefix, support_ns, relation)
        outputs[out / f"{root_prefix}{ladder.label}Bits.lean"] = GENERATED_HEADER + rewritten_binary
        outputs[out / f"{root_prefix}{ladder.label}Trace.lean"] = GENERATED_HEADER + _emit_trace(
            ladder, module_prefix, support_ns
        )
    with _configured(LADDERS[0], relation_source):
        native_add = _emit_native_add(module_root, support_ns, relation)
    outputs[out / f"{root_prefix}NativeAdd.lean"] = GENERATED_HEADER + native_add
    outputs[out / f"{name}.lean"] = GENERATED_HEADER + _emit_provider(
        name, module_root, support_ns, relation
    )
    forbidden = (
        "fun _ h => h", "spec (rho : Nat -> F) : Prop :=\n  relation rho",
        "axiom ", "native_decide", "identity semantics",
    )
    combined = "\n".join(outputs.values())
    for marker in forbidden:
        if marker in combined:
            raise ValueError(f"dummy RVK semantic output contains forbidden marker {marker!r}")
    if "Decaf377Assumptions.rvk" not in combined or "EdwardsBridge.onCurve" not in combined:
        raise ValueError("dummy RVK provider omitted equality or on-curve semantics")
    candidates = set(benchmark_candidates(out, template_name_fn))
    if not candidates.issubset(outputs):
        raise ValueError(f"dummy RVK benchmark candidates missing: {sorted(candidates - set(outputs))}")
    return outputs
