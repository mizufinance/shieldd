def camel(text: str) -> str:
    result: list[str] = []
    upper = True
    for char in text:
        if char in "._-":
            upper = True
        elif upper:
            result.append(char.upper())
            upper = False
        else:
            result.append(char)
    return "".join(result)


def default_template_name(key: str) -> str:
    operation, digest = key.split("@", 1)
    return f"T{camel(operation)}_{digest}"


Lc = dict[int, int]
Row = tuple[Lc, Lc, Lc]


def _segment() -> dict:
    ir_path = ROOT / f"crates/core/component/shielded-pool/formal/{CIRCUIT}-deployed-slice-ir.json"
    ir = json.loads(ir_path.read_text())
    matches = [item for item in ir["segments"] if item["index"] == SEGMENT]
    if len(matches) != 1:
        raise ValueError(f"{CIRCUIT}: expected one segment {SEGMENT}")
    segment = matches[0]
    pins = {
        "op": "decaf.randomized_verification_key.dummy",
        "template_key": TEMPLATE_KEY,
        "constraint_count": CONSTRAINT_COUNT,
    }
    for field, expected in pins.items():
        if segment.get(field) != expected:
            raise ValueError(
                f"{CIRCUIT}:Seg{SEGMENT} {field} drift: "
                f"{segment.get(field)!r} != {expected!r}"
            )
    if segment["end"] - segment["start"] != CONSTRAINT_COUNT:
        raise ValueError("dummy RVK representative row range drift")
    seating = segment["wire_seating"]
    if len(seating) != LOCAL_WIRE_COUNT or len(set(seating)) != LOCAL_WIRE_COUNT:
        raise ValueError("dummy RVK normalized wire seating drift")
    if seating[0] != 0:
        raise ValueError("dummy RVK constant wire is not local wire zero")
    return segment


def normalized_rows() -> list[Row]:
    segment = _segment()
    inverse = {global_wire: local for local, global_wire in enumerate(segment["wire_seating"])}
    pattern = re.compile(r"\(constraint \[(.*?)\] \[(.*?)\] \[(.*?)\]\)$")
    rows: list[Row] = []
    index = 0
    artifact = ROOT / f"tools/gnark/artifacts/{CIRCUIT}/{CIRCUIT}.sr1cs"
    with artifact.open() as source_file:
        for raw in source_file:
            line = raw.strip()
            if not line.startswith("(constraint "):
                continue
            if index >= segment["end"]:
                break
            if index >= segment["start"]:
                match = pattern.fullmatch(line)
                if match is None:
                    raise ValueError(f"unparseable dummy RVK SR1CS row {index}")
                sides: list[Lc] = []
                for group in match.groups():
                    side: Lc = {}
                    for coefficient, wire in re.findall(r"\(([-0-9]+) (\d+)\)", group):
                        global_wire = int(wire)
                        if global_wire not in inverse:
                            raise ValueError(f"dummy RVK row references unseated wire {global_wire}")
                        local = inverse[global_wire]
                        value = (side.get(local, 0) + int(coefficient)) % ORDER
                        if value:
                            side[local] = value
                        else:
                            side.pop(local, None)
                    sides.append(side)
                rows.append((sides[0], sides[1], sides[2]))
            index += 1
    if len(rows) != CONSTRAINT_COUNT:
        raise ValueError(f"expected {CONSTRAINT_COUNT} dummy RVK rows, got {len(rows)}")
    return rows


def _singleton(side: Lc, label: str) -> int:
    if len(side) != 1:
        raise ValueError(f"{label}: expected singleton witness, got {side}")
    wire, coefficient = next(iter(side.items()))
    if wire == 0 or coefficient != 1:
        raise ValueError(f"{label}: expected coefficient-one witness, got {side}")
    return wire


def _rungs(rows: list[Row], ladder: Ladder) -> tuple[rvk_emitter.BlindRung, ...]:
    result: list[rvk_emitter.BlindRung] = []
    previous_end = ladder.copy_row
    for index, (acc_x, acc_y) in enumerate(ladder.accumulators):
        block_size = 5 if index < 149 else 8
        acc_x_row = previous_end + block_size - 1
        acc_y_row = previous_end + block_size
        if rows[acc_x_row][2] != {acc_x: 1} or rows[acc_y_row][2] != {acc_y: 1}:
            raise ValueError(f"{ladder.label} rung {index + 1}: accumulator seating drift")
        block = tuple(range(previous_end + 1, acc_y_row + 1))
        bit = ladder.bit_base + index + 1
        if not any(bit in rows[row][0] or bit in rows[row][1] for row in block):
            raise ValueError(f"{ladder.label} rung {index + 1}: bit seating drift")
        result.append(rvk_emitter.BlindRung(
            index, bit, acc_x, acc_y, acc_x_row, acc_y_row, block, block_size == 8,
        ))
        previous_end = acc_y_row
    if previous_end != ladder.row_end:
        raise ValueError(f"{ladder.label}: ladder endpoint row drift")
    return tuple(result)


def recover() -> dict:
    """Fail closed on the two audited ladders and native-add tail."""
    rows = normalized_rows()
    rung_sets = []
    for ladder in LADDERS:
        for offset, row in enumerate(range(ladder.bit_rows[0], ladder.bit_rows[1] + 1)):
            bit = ladder.bit_base + offset
            if rows[row] != ({bit: 1}, {0: 1, bit: ORDER - 1}, {}):
                raise ValueError(f"{ladder.label}: boolean row {row} drift")
        if rows[ladder.copy_row][2] != {ladder.scalar_wire: 1}:
            raise ValueError(f"{ladder.label}: scalar recomposition target drift")
        rungs = _rungs(rows, ladder)
        if rungs[-1].acc_x != ladder.row_end or rungs[-1].acc_y != ladder.row_end + 1:
            raise ValueError(f"{ladder.label}: final accumulator wire drift")
        rung_sets.append(rungs)

    tail_targets = (3611, 3612, 3613, 3614, 3615, 3616)
    for row, target in zip(TAIL_ROWS[:6], tail_targets, strict=True):
        if rows[row][2] != {target: 1}:
            raise ValueError(f"native-add row {row}: target drift")
    if rows[3616][0] != {OUT_X: 1} or rows[3617][0] != {OUT_Y: 1}:
        raise ValueError("native-add output wire drift")
    return {"rows": rows, "rungs": tuple(rung_sets)}


def _relation_source() -> str:
    shards = sorted(
        RELATIONS_ROOT.glob(f"{RELATION_STEM}Defs*.lean"),
        key=lambda path: int(path.stem.removeprefix(RELATION_STEM + "Defs")),
    )
    indices = [int(path.stem.removeprefix(RELATION_STEM + "Defs")) for path in shards]
    if not shards or indices != list(range(len(shards))):
        raise ValueError("dummy RVK normalized relation shards are not contiguous")
    facade = RELATIONS_ROOT / f"{RELATION_STEM}.lean"
    if not facade.is_file():
        raise ValueError("dummy RVK normalized relation facade is missing")
    bodies: list[str] = []
    for path in (*shards, facade):
        lines = path.read_text().splitlines()
        start = next((i for i, line in enumerate(lines) if line.startswith("namespace ")), None)
        ends = [i for i, line in enumerate(lines) if line.startswith("end ")]
        if start is None or not ends or ends[-1] <= start:
            raise ValueError(f"{path}: malformed normalized relation namespace")
        bodies.append("\n".join(lines[start + 1:ends[-1]]) + "\n")
    source = "\n\ndef dummyRvkRelationShardBoundary : Prop := True\n\n".join(bodies)
    covered = {int(match.group(1)) for match in re.finditer(r"def relationRow(\d+) ", source)}
    if covered != set(range(CONSTRAINT_COUNT)):
        raise ValueError("dummy RVK normalized Lean relation coverage drift")
    return source


def _generator_doubles() -> list[tuple[int, int]]:
    x, y = GEN_X, GEN_Y_MINUS_ONE + 1
    result = [(x, y)]
    for _ in range(250):
        xx, yy = x * x % ORDER, y * y % ORDER
        x = 2 * x * y * pow(yy - xx, -1, ORDER) % ORDER
        y = (yy + xx) * pow(2 - (yy - xx), -1, ORDER) % ORDER
        result.append((x, y))
    return result


@contextmanager
def _configured(ladder: Ladder, relation_source: str) -> Iterator[None]:
    names = (
        "ROW_COUNT", "AMOUNT_BLOCKS", "BLIND_BIT_BASE", "BLIND_BINARY_ROWS",
        "BLIND_COPY_ROW", "BLIND_WIRE", "BLIND_ACCS", "OUT_X_WIRE",
        "OUT_Y_WIRE", "NB_GX", "NB_GYM1", "CONTRACTS_SOURCE",
    )
    saved = {name: getattr(rvk_emitter, name) for name in names}
    saved_doubles = rvk_emitter.blind_gen_doubles
    saved_source, saved_rows = dtk.SOURCE_CONTRACTS, dtk.ROW_COUNT
    virtual = RELATIONS_ROOT / (".dummy-rvk-provider-" + ladder.label)
    source_key = (str(virtual.resolve()), 46)
    parts_key = (str(virtual.resolve()), 46, CONSTRAINT_COUNT)
    old_source = dtk._SOURCE_CACHE.get(source_key)
    old_parts = dtk._RELATION_PARTS_CACHE.get(parts_key)
    try:
        rvk_emitter.ROW_COUNT = CONSTRAINT_COUNT
        rvk_emitter.AMOUNT_BLOCKS = ()
        rvk_emitter.BLIND_BIT_BASE = ladder.bit_base
        rvk_emitter.BLIND_BINARY_ROWS = ladder.bit_rows
        rvk_emitter.BLIND_COPY_ROW = ladder.copy_row
        rvk_emitter.BLIND_WIRE = ladder.scalar_wire
        rvk_emitter.BLIND_ACCS = ladder.accumulators
        rvk_emitter.OUT_X_WIRE, rvk_emitter.OUT_Y_WIRE = ladder.accumulators[-1]
        rvk_emitter.NB_GX = GEN_X
        rvk_emitter.NB_GYM1 = GEN_Y_MINUS_ONE
        rvk_emitter.blind_gen_doubles = _generator_doubles
        rvk_emitter.CONTRACTS_SOURCE = virtual
        dtk.SOURCE_CONTRACTS = virtual
        dtk.ROW_COUNT = CONSTRAINT_COUNT
        dtk._SOURCE_CACHE[source_key] = relation_source
        dtk._RELATION_PARTS_CACHE.pop(parts_key, None)
        yield
    finally:
        for name, value in saved.items():
            setattr(rvk_emitter, name, value)
        rvk_emitter.blind_gen_doubles = saved_doubles
        dtk.SOURCE_CONTRACTS, dtk.ROW_COUNT = saved_source, saved_rows
        if old_source is None:
            dtk._SOURCE_CACHE.pop(source_key, None)
        else:
            dtk._SOURCE_CACHE[source_key] = old_source
        if old_parts is None:
            dtk._RELATION_PARTS_CACHE.pop(parts_key, None)
        else:
            dtk._RELATION_PARTS_CACHE[parts_key] = old_parts


