        ("Shieldd.GnarkFormal.Deployed.NetBalance.NbFixedStepRel", "Shieldd.GnarkFormal.RvkFixedBaseLadder.FixedStepRel"),
        ("Shieldd.GnarkFormal.Deployed.NetBalance.Cb_onCurve", "Shieldd.GnarkFormal.RvkFixedBaseConstants.C_onCurve"),
        ("Shieldd.GnarkFormal.Deployed.NetBalance.Cb", "Shieldd.GnarkFormal.RvkFixedBaseConstants.C"),
