@dataclass(frozen=True)
class Ladder:
    label: str
    row_start: int
    bit_base: int
    scalar_wire: int
    copy_row: int
    fused_x: int
    fused_y: int
    split_x: int
    split_y: int
    row_end: int

    @property
    def accumulators(self) -> tuple[tuple[int, int], ...]:
        return tuple(
            [(self.fused_x + 5 * i, self.fused_y + 5 * i) for i in range(149)]
            + [(self.split_x + 8 * i, self.split_y + 8 * i) for i in range(101)]
        )

    @property
    def bit_rows(self) -> tuple[int, int]:
        return self.row_start, self.row_start + 250


