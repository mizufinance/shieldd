#!/usr/bin/env python3
"""Generate direct exact semantic providers for routing templates."""

from __future__ import annotations

import re
from pathlib import Path

import formal_json


ROOT = Path(__file__).resolve().parents[4]
LEAN = ROOT / "tools/gnark/lean"
INVENTORY = ROOT / "tools/gnark/artifacts/certified-template-inventory.json"
RELATIONS = LEAN / "ShielddGnarkFormal/Deployed/Templates/Relations"
OUT = LEAN / "ShielddGnarkFormal/Deployed/Templates/Semantics"


def camel(text: str) -> str:
    result: list[str] = []
    upper = True
    for char in text:
        if char in "._-":
            upper = True
        elif upper:
            result.append(char.upper())
            upper = False
        else:
            result.append(char)
    return "".join(result)


def template_name(key: str) -> str:
    operation, digest = key.split("@", 1)
    return f"T{camel(operation)}_{digest}"


def relation_body(source: str, name: str) -> str:
    match = re.search(
        r"def relation \(rho : Nat -> F\) : Prop :=\n"
        r"(.*?)(?=\n\nend )",
        source,
        re.DOTALL,
    )
    if match is None:
        raise ValueError(f"{name}: cannot recover exact relation body")
    body = match.group(1).rstrip()
    if body == "relation rho":
        raise ValueError(f"{name}: recursive relation body")
    return body


def render(key: str) -> str:
    name = template_name(key)
    relation_module = (
        "Shieldd.GnarkFormal.Deployed.Templates.Relations." + name
    )
    source = (RELATIONS / f"{name}.lean").read_text()
    body = relation_body(source, name)
    namespace = (
        "Shieldd.GnarkFormal.Deployed.Templates.Semantics." + name
    )
    return f"""/-
GENERATED by gen/gen_routing_semantics.py -- do not edit.
-/
import ShielddGnarkFormal.Deployed.Templates.Relations.{name}
import Mathlib.Data.ZMod.Basic

set_option maxRecDepth 1000000
set_option maxHeartbeats 50000000

namespace {namespace}

def Order : Nat := 8444461749428370424248824938781546531375899335154063827935233455917409239041
abbrev F := ZMod Order

open {relation_module}

/-- The exact normalized routing relation, exposed independently of seating. -/
def spec (rho : Nat -> F) : Prop :=
{body}

theorem sound (rho : Nat -> F)
    (h : {relation_module}.relation rho) : spec rho := by
  unfold {relation_module}.relation at h
  simpa only [spec] using h

end {namespace}
"""


def generated_files() -> dict[Path, str]:
    inventory = formal_json.read_template_inventory(INVENTORY)
    keys = sorted(
        template["template_key"]
        for template in inventory["templates"]
        if template["op"].startswith("routing.")
    )
    if not keys:
        raise ValueError("certified template inventory has no routing templates")
    return {OUT / f"{template_name(key)}.lean": render(key) for key in keys}
