#!/usr/bin/env python3
"""Generate the exact local semantic provider for Transfer's threshold flag.

The recovery is intentionally specific to the reviewed 896-row relation.  It
validates both canonical SR1CS row order and normalized Lean row/part coverage,
including the final is-regulated selector row, before emitting a direct
relation-to-semantics proof.
"""

from __future__ import annotations

import re
from pathlib import Path

import gen_transfer_semantics as common
from write_if_changed import write_if_changed


ROOT = Path(__file__).resolve().parents[4]
FORMAL = ROOT / "tools/gnark/lean/ShielddGnarkFormal"
OUT = FORMAL / "Deployed/Templates/Semantics"

DIGEST = "9cff3d70e943aa401049c5bfb32ca36b67892e27bb28d1be48bb6acb16e8a202"
NAME = f"TThresholdFlag_{DIGEST}"
REL = f"Shieldd.GnarkFormal.Deployed.Templates.Relations.{NAME}"
NS = f"Shieldd.GnarkFormal.Deployed.Templates.Semantics.{NAME}"
ROW_COUNT = 896
PART_COUNT = 180
CHUNK = 16
INLINE_LESS_COUNT = 15

Lc = common.Lc
Row = common.Row

GENERATED_HEADER = """/-
GENERATED by gen/gen_transfer_threshold_semantics.py — do not edit by hand.
-/
"""


def _lc(*terms: tuple[int, int]) -> Lc:
    result: Lc = {}
    for wire, coefficient in terms:
        value = (result.get(wire, 0) + coefficient) % common.ORDER
        if value:
            result[wire] = value
        else:
            result.pop(wire, None)
    return result


def _expect(rows: tuple[Row, ...], index: int, expected: Row) -> None:
    if rows[index] != expected:
        raise ValueError(
            f"{DIGEST}: row {index} drifted\n"
            f"expected={expected}\nactual={rows[index]}"
        )


def _expect_commutative_product(
    rows: tuple[Row, ...], index: int, expected: Row
) -> None:
    actual = rows[index]
    if actual != expected and actual != (expected[1], expected[0], expected[2]):
        raise ValueError(
            f"{DIGEST}: row {index} product drifted\n"
            f"expected={expected} up to A/B swap\nactual={actual}"
        )


def recover() -> tuple[tuple[Row, ...], Lc]:
    """Validate the comparator and gated-output row, returning the flag LC."""

    rows = common._canonical_rows(DIGEST, ROW_COUNT)
    if len(rows) != ROW_COUNT:
        raise ValueError(
            f"{DIGEST}: expected {ROW_COUNT} rows, got {len(rows)}; "
            "the ungated threshold relation is not a semantic provider"
        )
    zero: Lc = {}
    one = _lc((0, 1))

    for index in range(128):
        bit = index + 1
        _expect_commutative_product(
            rows, index, (_lc((bit, 1)), _lc((0, 1), (bit, -1)), zero)
        )
    amount_lc = _lc(*((index + 1, 1 << index) for index in range(128)))
    _expect_commutative_product(rows, 128, (one, amount_lc, _lc((129, 1))))

    for index in range(128):
        row = 129 + index
        bit = 130 + index
        _expect_commutative_product(
            rows, row, (_lc((bit, 1)), _lc((0, 1), (bit, -1)), zero)
        )
    threshold_lc = _lc(*((130 + index, 1 << index) for index in range(128)))
    _expect_commutative_product(
        rows, 257, (one, threshold_lc, _lc((258, 1)))
    )

    # First MSB rung: pe=1 and il=0 let gnark omit three materializations.
    _expect_commutative_product(
        rows,
        258,
        (_lc((257, 1)), _lc((0, 1), (128, -1)), _lc((259, 1))),
    )
    _expect_commutative_product(
        rows,
        259,
        (_lc((128, 2)), _lc((257, 1)), _lc((260, 1))),
    )
    prefix = _lc((0, 1), (128, -1), (257, -1), (260, 1))
    less = _lc((259, 1))

    for bit_index in range(126, -1, -1):
        row = 260 + 5 * (126 - bit_index)
        a = bit_index + 1
        b = bit_index + 130
        prefix_without_a = row + 1
        less_at = row + 2
        overlap = row + 3
        double_ab = row + 4
        prefix_out = row + 5
        _expect_commutative_product(
            rows,
            row,
            (_lc((0, 1), (a, -1)), prefix, _lc((prefix_without_a, 1))),
        )
        _expect_commutative_product(
            rows,
            row + 1,
            (_lc((prefix_without_a, 1)), _lc((b, 1)), _lc((less_at, 1))),
        )
        _expect_commutative_product(
            rows,
            row + 2,
            (_lc((less_at, 1)), less, _lc((overlap, 1))),
        )
        _expect_commutative_product(
            rows,
            row + 3,
            (_lc((a, 2)), _lc((b, 1)), _lc((double_ab, 1))),
        )
        _expect_commutative_product(
            rows,
            row + 4,
            (
                prefix,
                _lc((0, 1), (a, -1), (b, -1), (double_ab, 1)),
                _lc((prefix_out, 1)),
            ),
        )
        prefix = _lc((prefix_out, 1))
        less = common._lc_add(
            less, _lc((less_at, 1), (overlap, -1))
        )

    if prefix != _lc((895, 1)):
        raise ValueError(f"{DIGEST}: final prefix is {prefix}, expected rho 895")
    output = common._lc_add(one, common._lc_scale(-1, less))
    expected_terms = 2 * 128
    if len(output) != expected_terms:
        raise ValueError(
            f"{DIGEST}: final flag has {len(output)} terms, "
            f"expected {expected_terms}"
        )
    _expect_commutative_product(
        rows,
        895,
        (_lc((896, 1)), output, _lc((897, 1))),
    )
    return rows, output


def _definitions(source: str) -> dict[str, str]:
    matches = list(
        re.finditer(
            r"^def (relation(?:Row|Part|Lc)[A-Za-z0-9]*)\b.*? :=\n",
            source,
            re.MULTILINE,
        )
    )
    result: dict[str, str] = {}
    for index, match in enumerate(matches):
        end = matches[index + 1].start() if index + 1 < len(matches) else len(source)
        result[match.group(1)] = source[match.end() : end]
    return result


def _validate_relation(source: str, rows: tuple[Row, ...]) -> tuple[tuple[int, ...], ...]:
    definitions = _definitions(source)
    row_names = sorted(
        int(name.removeprefix("relationRow"))
        for name in definitions
        if name.startswith("relationRow")
    )
    if row_names != list(range(ROW_COUNT)):
        raise ValueError(f"{NAME}: normalized row facade is not exact")
    parts: list[tuple[int, ...]] = []
    for part in range(PART_COUNT):
        body = definitions.get(f"relationPart{part}")
        if body is None:
            raise ValueError(f"{NAME}: missing relationPart{part}")
        indices = tuple(map(int, re.findall(r"relationRow(\d+) rho", body)))
        expected = tuple(range(5 * part, min(5 * part + 5, ROW_COUNT)))
        if indices != expected:
            raise ValueError(
                f"{NAME}: part {part} rows {indices}, expected {expected}"
            )
        parts.append(indices)
    facade = source[source.rfind(f"namespace {REL}") :]
    facade_parts = tuple(map(int, re.findall(r"relationPart(\d+) rho", facade)))
    if facade_parts != tuple(range(PART_COUNT)):
        raise ValueError(f"{NAME}: relation facade does not cover each part once")

    # The emitted Lean relation is checked independently against the same raw
    # rows by the normalized-relation generator; require the expected count here
    # so a stale or partial facade cannot produce a provider.
    if len(rows) != sum(map(len, parts)):
        raise ValueError(f"{NAME}: raw/Lean row count mismatch")
    return tuple(parts)


def _dependency_closure(
    definitions: dict[str, str], root: str
) -> tuple[str, ...]:
    result: list[str] = []
    seen: set[str] = set()

    def visit(name: str) -> None:
        for dependency in re.findall(r"\b(relationLc[A-Za-z0-9]*)\b", definitions[name]):
            if dependency in definitions and dependency not in seen:
                seen.add(dependency)
                result.append(dependency)
                visit(dependency)

    visit(root)
    return tuple(result)


def _unpack_relation(
    selected_parts: tuple[int, ...], *, hypothesis: str = "h"
) -> list[str]:
    selected = set(selected_parts)
    pattern = ", ".join(
        f"p{part}" if part in selected else "_" for part in range(PART_COUNT)
    )
    lines = [
        f"  unfold {REL}.relation at {hypothesis}",
        f"  rcases {hypothesis} with ⟨{pattern}⟩",
    ]
    for part in selected_parts:
        rows = tuple(range(5 * part, min(5 * part + 5, ROW_COUNT)))
        lines.append(f"  unfold {REL}.relationPart{part} at p{part}")
        if len(rows) == 1:
            lines.append(f"  have r{rows[0]} := p{part}")
        else:
            lines.append(
                "  rcases p"
                f"{part} with ⟨"
                + ", ".join(f"r{row}" for row in rows)
                + "⟩"
            )
    return lines


def _unfold_rows(
    row_indices: tuple[int, ...], definitions: dict[str, str]
) -> list[str]:
    lines: list[str] = []
    for row in row_indices:
        root = f"relationRow{row}"
        dependencies = _dependency_closure(definitions, root)
        names = " ".join(
            f"{REL}.{name}" for name in (root, *dependencies)
        )
        lines.append(f"  unfold {names} at r{row}")
    return lines


def _less_lc(count: int) -> Lc:
    if not 0 <= count <= 127:
        raise ValueError(f"invalid threshold less count: {count}")
    return _lc(
        (259, 1),
        *(
            term
            for index in range(count)
            for term in ((262 + 5 * index, 1), (263 + 5 * index, -1))
        ),
    )


def _render_signed_lc(lc: Lc) -> str:
    terms: list[str] = []
    for wire, coefficient in sorted(lc.items()):
        signed = (
            coefficient - common.ORDER
            if coefficient > common.ORDER // 2
            else coefficient
        )
        if wire == 0:
            terms.append(f"({signed} : F)")
        else:
            terms.append(f"({signed} : F) * rho {wire}")
    return " + ".join(terms) if terms else "(0 : F)"


def _structured_less_body(count: int | str) -> str:
    return (
        "Shieldd.GnarkFormal.StructuredLC.eval rho "
        "(({ const := (0 : F), runs := "
        f"[⟨(-1 : F), 263, 5, {count}⟩, "
        f"⟨(1 : F), 262, 5, {count}⟩], "
        "residual := [((1 : F), 259)] } : "
        "Shieldd.GnarkFormal.StructuredLC F))"
    )


def _validate_less_shapes(definitions: dict[str, str]) -> None:
    for count in range(127):
        row = 262 + 5 * count
        dependencies = _dependency_closure(
            definitions, f"relationRow{row}"
        )
        if count <= INLINE_LESS_COUNT:
            if dependencies:
                raise ValueError(
                    f"{NAME}: less count {count} unexpectedly uses "
                    f"{dependencies}"
                )
            if "StructuredLC.eval" in definitions[f"relationRow{row}"]:
                raise ValueError(
                    f"{NAME}: less count {count} unexpectedly structured"
                )
            continue
        if len(dependencies) != 1:
            raise ValueError(
                f"{NAME}: less count {count} has dependencies "
                f"{dependencies}"
            )
        actual = definitions[dependencies[0]].strip()
        expected = _structured_less_body(count)
        if actual != expected:
            raise ValueError(
                f"{NAME}: less count {count} structured LC drifted\n"
                f"expected={expected}\nactual={actual}"
            )


