def generated_files() -> dict[Path, str]:
    rows, output_lc = recover()
    source = common._relation_source(NAME)
    _validate_relation(source, rows)
    definitions = _definitions(source)
    _validate_less_shapes(definitions)
    files = {
        OUT / f"{NAME}Base.lean": _render_base(output_lc),
        OUT / f"{NAME}AmountBits.lean": _render_bits(
            definitions,
            label="amount",
            base=1,
            output=129,
            first_row=0,
            recomposition_row=128,
        ),
        OUT / f"{NAME}ThresholdBits.lean": _render_bits(
            definitions,
            label="threshold",
            base=130,
            output=258,
            first_row=129,
            recomposition_row=257,
        ),
        OUT / f"{NAME}.lean": _render_main(definitions),
    }
    for lo in range(0, 128, CHUNK):
        files[OUT / f"{NAME}Ladder{lo}.lean"] = _render_ladder_chunk(
            definitions, lo, lo + CHUNK
        )
    return files


def generate(*, check: bool = False) -> None:
    files = generated_files()
    for path, contents in files.items():
        if check:
            if not path.is_file() or path.read_text() != contents:
                raise SystemExit(f"stale generated threshold provider: {path}")
        else:
            write_if_changed(path, contents)
    if not check:
        print(f"wrote {len(files)} exact Transfer threshold provider modules")


def main() -> None:
    import argparse

    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generate(check=args.check)


if __name__ == "__main__":
    main()
