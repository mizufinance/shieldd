@dataclass(frozen=True)
class StructuredLc:
    constant: int
    runs: tuple[tuple[int, int, int, int], ...]
    residual: tuple[tuple[int, int], ...]

    def flat_lc(self) -> Lc:
        result: Lc = {0: self.constant} if self.constant else {}
        for coefficient, start, stride, count in self.runs:
            for index in range(count):
                wire = start + stride * index
                result[wire] = (
                    result.get(wire, 0) + coefficient
                ) % ORDER
        for coefficient, wire in self.residual:
            result[wire] = (
                result.get(wire, 0) + coefficient
            ) % ORDER
        return _clean(result)


