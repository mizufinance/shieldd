@cache
def recover(template: Template) -> Recovery:
    _validate_registry(template)
    rows = _canonical_rows(template.digest)
    if len(rows) != template.row_count:
        raise ValueError(
            f"{template.digest}: expected {template.row_count} rows, "
            f"got {len(rows)}"
        )
    referenced_wires = {
        wire for row in rows for side in row for wire in side if wire
    }
    if referenced_wires != set(range(1, template.local_wire_count)):
        raise ValueError(f"{template.digest}: local wire boundary drifted")

    source = _relation_source(template.name)
    normalized_rows = {
        int(row) for row in re.findall(r"\bdef relationRow(\d+) ", source)
    }
    if normalized_rows != set(range(template.row_count)):
        raise ValueError(f"{template.digest}: normalized row set drifted")
    _relation_parts(source, template.row_count)
    _validate_fixed_prefix(template, rows)

    user = _recover_window2_slice(template, user=True)
    issuer = _recover_window2_slice(template, user=False)
    if user.scalar != issuer.scalar:
        raise ValueError("user and issuer ACK scalar boundaries diverged")

    (
        flag,
        computed_x,
        computed_y,
        published_x,
        published_y,
        adjust_x,
        adjust_y,
    ) = _recover_boundaries(template, rows, user, issuer)

    if template.flag_row is not None:
        _validate_boolean_row(
            rows[template.flag_row], flag, "shared-secret flag row"
        )

    owners: list[tuple[int, str]] = []
    if template.flag_row is not None:
        owners.append((template.flag_row, "flag_boolean"))
    owners.extend(
        (template.fixed_start + index, "fixed_rvk")
        for index in range(1805)
    )
    owners.extend(
        (template.equivalent_start + index, "equivalent")
        for index in range(3)
    )
    owners.extend(
        (template.user_start + index, "user_ack")
        for index in range(template.issuer_start - template.user_start)
    )
    owners.extend(
        (template.issuer_start + index, "issuer_ack")
        for index in range(template.selector_start - template.issuer_start)
    )
    owners.extend(
        (template.selector_start + index, "selector")
        for index in range(2)
    )
    ownership = _validate_ownership(template.row_count, owners)

    return Recovery(
        template=template,
        rows=rows,
        esk_wire=user.scalar,
        flag=_freeze(flag),
        computed_x=_freeze(computed_x),
        computed_y=_freeze(computed_y),
        published_x=_freeze(published_x),
        published_y=_freeze(published_y),
        user=user,
        issuer=issuer,
        selector_adjust_x=adjust_x,
        selector_adjust_y=adjust_y,
        ownership=ownership,
    )


@cache
def recover_fixed(template: Template) -> FixedRecovery:
    recovery = recover(template)
    rvk_source = _relation_source(RVK_NAME)
    shared_source = _relation_source(template.name)
    rvk_structured = _structured_lcs(rvk_source)
    shared_structured = _structured_lcs(shared_source)
    seam_by_rvk: dict[int, int] = {}

    for rvk_row in range(1805):
        shared_row = template.fixed_start + rvk_row
        rvk_names = _lc_names(rvk_source, rvk_row)
        shared_names = _lc_names(shared_source, shared_row)
        if len(rvk_names) != len(shared_names):
            # The shared normalization expands forty short frontier rows
            # directly while standalone RVK keeps their ≤15-term runs named.
            # Their raw canonical row identity is already pinned above; the
            # generated row proof opens only those compact RVK atoms.
            if (
                rvk_row < 292
                or rvk_row > 331
                or shared_names
                or len(rvk_names) not in (1, 2)
            ):
                raise ValueError(
                    f"{template.digest}: unexpected fixed row {rvk_row} "
                    "named-LC arity drift"
                )
            continue
        for rvk_lc, shared_lc in zip(
            rvk_names, shared_names, strict=True
        ):
            previous = seam_by_rvk.setdefault(rvk_lc, shared_lc)
            if previous != shared_lc:
                raise ValueError(
                    f"{template.digest}: RVK LC {rvk_lc} maps to both "
                    f"{previous} and {shared_lc}"
                )

    non_structured: list[tuple[int, int]] = []
    for rvk_lc, shared_lc in seam_by_rvk.items():
        rvk_is_structured = rvk_lc in rvk_structured
        shared_is_structured = shared_lc in shared_structured
        if rvk_is_structured != shared_is_structured:
            raise ValueError(
                f"{template.digest}: fixed LC {rvk_lc}/{shared_lc} "
                "normalization kinds diverged"
            )
        if not rvk_is_structured:
            non_structured.append((rvk_lc, shared_lc))
            continue
        expected = _shift_lc(
            rvk_structured[rvk_lc].flat_lc(),
            template.fixed_shift,
        )
        actual = shared_structured[shared_lc].flat_lc()
        if expected != actual:
            raise ValueError(
                f"{template.digest}: fixed LC {rvk_lc}/{shared_lc} "
                "expanded semantics drifted"
            )

    if len(non_structured) != 1 or non_structured[0][0] != 0:
        raise ValueError(
            f"{template.digest}: expected only flat RVK LC 0, got "
            f"{non_structured}"
        )
    flat_rvk_lc, flat_shared_lc = non_structured[0]

    computed_names = (
        _single_lc_name(
            shared_source,
            template.equivalent_start,
            "fixed computed X",
        ),
        _single_lc_name(
            shared_source,
            template.equivalent_start + 1,
            "fixed computed Y",
        ),
    )
    computed_x_lc, computed_y_lc = (
        int(name.removeprefix("relationLc"))
        for name in computed_names
    )
    for rvk_lc, shared_lc, recovered, label in (
        (1556, computed_x_lc, dict(recovery.computed_x), "X"),
        (1555, computed_y_lc, dict(recovery.computed_y), "Y"),
    ):
        if rvk_lc not in rvk_structured:
            raise ValueError(f"RVK computed {label} LC lost structure")
        if shared_lc not in shared_structured:
            raise ValueError(
                f"shared-secret computed {label} LC lost structure"
            )
        expected = _shift_lc(
            rvk_structured[rvk_lc].flat_lc(),
            template.fixed_shift,
        )
        actual = shared_structured[shared_lc].flat_lc()
        if expected != actual or actual != recovered:
            raise ValueError(
                f"{template.digest}: computed {label} LC seam drifted"
            )
        previous = seam_by_rvk.setdefault(rvk_lc, shared_lc)
        if previous != shared_lc:
            raise ValueError(
                f"{template.digest}: computed {label} LC mapping "
                "conflicted"
            )

    if len(seam_by_rvk) != 1508:
        raise ValueError(
            f"{template.digest}: expected 1508 fixed LC seams, got "
            f"{len(seam_by_rvk)}"
        )
    return FixedRecovery(
        seams=tuple(sorted(seam_by_rvk.items())),
        structured_rvk=tuple(sorted(rvk_structured.items())),
        structured_shared=tuple(sorted(shared_structured.items())),
        computed_x_lc=computed_x_lc,
        computed_y_lc=computed_y_lc,
        flat_rvk_lc=flat_rvk_lc,
        flat_shared_lc=flat_shared_lc,
    )


@cache
def generated_research_files(out: Path = OUT) -> dict[Path, str]:
    outputs: dict[Path, str] = {}
    for template in TEMPLATES:
        recovery = recover(template)
        fixed = recover_fixed(template)
        sections = (
            _fixed_files(recovery, fixed, out),
            {
                out / f"{template.name}.lean":
                    _shared_main(recovery, fixed)
            },
        )
        for section in sections:
            overlap = set(outputs).intersection(section)
            if overlap:
                raise ValueError(
                    "duplicate SharedSecret semantic outputs: "
                    + ", ".join(str(path) for path in sorted(overlap))
                )
            outputs.update(section)
    expected = len(TEMPLATES) * 72
    if len(outputs) != expected:
        raise ValueError(
            f"expected {expected} SharedSecret semantic modules, got "
            f"{len(outputs)}"
        )
    return outputs


def generated_files(out: Path = OUT) -> dict[Path, str]:
    """Return only shared-secret families present in deployed inventory."""
    inventory = formal_json.read_template_inventory(INVENTORY)
    active = {
        template["template_key"] for template in inventory["templates"]
    }
    active_templates = tuple(
        template
        for template in TEMPLATES
        if f"decaf.shared_secret@{template.digest}" in active
    )
    if not active_templates:
        return {}
    if active_templates != TEMPLATES:
        raise ValueError(
            "partial legacy SharedSecret family remains deployed; "
            "regenerate one coherent final family"
        )
    return generated_research_files(out)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs = generated_files()
    if args.check:
        stale = [
            str(path)
            for path, source in outputs.items()
            if not path.is_file() or path.read_text() != source
        ]
        if stale:
            raise SystemExit(
                "stale SharedSecret semantic providers:\n"
                + "\n".join(stale)
            )
        return
    for path, source in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        if write_if_changed(path, source):
            print(f"wrote {path}")


if __name__ == "__main__":
    main()
