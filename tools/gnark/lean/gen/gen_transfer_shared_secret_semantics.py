def _unpack_rows(
    template: Template, hypothesis: str, wanted: set[int]
) -> str:
    parts = _relation_parts(
        _relation_source(template.name), template.row_count
    )
    part_names = ", ".join(f"p{index}" for index in range(len(parts)))
    lines = [
        f"  unfold {template.relation}.relation at {hypothesis}\n",
        f"  rcases {hypothesis} with ⟨{part_names}⟩\n",
    ]
    for part_index, rows in enumerate(parts):
        if not wanted.intersection(rows):
            continue
        pattern = ", ".join(
            f"r{row}" if row in wanted else "_" for row in rows
        )
        lines.extend(
            [
                f"  unfold {template.relation}.relationPart"
                f"{part_index} at p{part_index}\n",
                f"  rcases p{part_index} with ⟨{pattern}⟩\n",
            ]
        )
    return "".join(lines)


