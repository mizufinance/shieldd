def _clean(value: Lc) -> Lc:
    return {
        wire: coefficient % ORDER
        for wire, coefficient in value.items()
        if coefficient % ORDER
    }


def _add(left: Lc, right: Lc, coefficient: int = 1) -> Lc:
    result = dict(left)
    for wire, value in right.items():
        result[wire] = (
            result.get(wire, 0) + coefficient * value
        ) % ORDER
        if result[wire] == 0:
            del result[wire]
    return result


def _scale(value: Lc, coefficient: int) -> Lc:
    return _clean(
        {wire: coefficient * term for wire, term in value.items()}
    )


def _freeze(value: Lc) -> tuple[tuple[int, int], ...]:
    return tuple(sorted(_clean(value).items()))


def _singleton(side: Lc, label: str) -> int:
    if len(side) != 1:
        raise ValueError(f"{label}: expected singleton, got {side}")
    wire, coefficient = next(iter(side.items()))
    if wire == 0 or coefficient != 1:
        raise ValueError(
            f"{label}: expected coefficient-one witness, got {side}"
        )
    return wire


@cache
def _canonical_rows(digest: str) -> tuple[Row, ...]:
    path = CANONICAL / f"{digest}.sr1cs.gz"
    rows: list[Row] = []
    with gzip.open(path, "rt") as source:
        for line in source:
            if not line.lstrip().startswith("(constraint "):
                continue
            rows.append(
                tuple(
                    dtk.lc_clean(
                        {
                            int(wire): int(coefficient, 0)
                            for coefficient, wire in side
                        }
                    )
                    for side in dtk.parse_constraint(line)
                )
            )
    return tuple(rows)


@cache
def _relation_source(name: str) -> str:
    shards = sorted(
        RELATIONS.glob(f"{name}Defs*.lean"),
        key=lambda path: int(path.stem.removeprefix(name + "Defs")),
    )
    facade = RELATIONS / f"{name}.lean"
    if not shards or not facade.is_file():
        raise ValueError(f"{name}: missing exact normalized relation")
    indices = [
        int(path.stem.removeprefix(name + "Defs")) for path in shards
    ]
    if indices != list(range(len(indices))):
        raise ValueError(f"{name}: relation shards are not contiguous")
    return "\n".join(path.read_text() for path in (*shards, facade))


def _structured_lcs(source: str) -> dict[int, StructuredLc]:
    pattern = re.compile(
        r"def relationLc(\d+) \(rho : Nat -> F\) : F :=\n\s*"
        r"Shieldd\.GnarkFormal\.StructuredLC\.eval rho "
        r"\(\(\{ const := \((-?\d+) : F\), "
        r"runs := \[(.*?)\], residual := \[(.*?)\] \} : "
        r"Shieldd\.GnarkFormal\.StructuredLC F\)\)",
        re.S,
    )
    result: dict[int, StructuredLc] = {}
    for match in pattern.finditer(source):
        runs = tuple(
            (int(coefficient), int(start), int(stride), int(count))
            for coefficient, start, stride, count in re.findall(
                r"⟨\((-?\d+) : F\), (\d+), (\d+), (\d+)⟩",
                match.group(3),
            )
        )
        residual = tuple(
            (int(coefficient), int(wire))
            for coefficient, wire in re.findall(
                r"\(\((-?\d+) : F\), (\d+)\)", match.group(4)
            )
        )
        if (
            match.group(3).strip() and not runs
        ) or (
            match.group(4).strip() and not residual
        ):
            raise ValueError(
                f"relationLc{match.group(1)} has an unparseable "
                "StructuredLC"
            )
        result[int(match.group(1))] = StructuredLc(
            int(match.group(2)), runs, residual
        )
    return result


def _definition_body(source: str, name: str) -> str:
    match = re.search(
        rf"def {re.escape(name)} \(rho : Nat -> F\) : F :=\n"
        r"(.*?)(?=\n\ndef |\nend )",
        source,
        re.S,
    )
    if match is None:
        raise ValueError(f"missing normalized definition {name}")
    return match.group(1)


def _definition_closure(source: str, root: str) -> tuple[str, ...]:
    ordered: list[str] = []
    seen: set[str] = set()

    def visit(name: str) -> None:
        if name in seen:
            return
        seen.add(name)
        body = _definition_body(source, name)
        for dependency in re.findall(
            r"\b(relationLc[A-Za-z0-9]+) rho", body
        ):
            visit(dependency)
        ordered.append(name)

    visit(root)
    return tuple(reversed(ordered))


def _lc_names(source: str, row: int) -> tuple[int, ...]:
    return tuple(
        int(index)
        for index in re.findall(
            r"\brelationLc(\d+) rho", _row_body(source, row)
        )
    )


def _validate_registry(template: Template) -> None:
    registry = formal_json.read_template_registry(REGISTRY)
    matches = [
        entry
        for entry in registry.get("templates", [])
        if entry.get("proof_template_id")
        == f"decaf.shared_secret@{template.digest}"
    ]
    if len(matches) != 1:
        raise ValueError(
            f"{template.digest}: expected one exact registry entry"
        )
    entry = matches[0]
    expected = {
        "op": "decaf.shared_secret",
        "row_count": template.row_count,
        "local_wire_count": template.local_wire_count,
        "canonical_relation_sha256_hex": template.digest,
        "canonical_relation_file":
            f"proof-template-relations/{template.digest}.sr1cs.gz",
    }
    for field, value in expected.items():
        if entry.get(field) != value:
            raise ValueError(
                f"{template.digest}: registry {field} drifted"
            )


def _relation_parts(source: str, row_count: int) -> tuple[tuple[int, ...], ...]:
    parts: list[tuple[int, ...]] = []
    for match in re.finditer(
        r"def relationPart(\d+) \(rho : Nat -> F\) : Prop :=\n(.*?)"
        r"(?=\n\ndef relationPart|\n\ndef relation \()",
        source,
        re.S,
    ):
        index = int(match.group(1))
        if index != len(parts):
            raise ValueError(f"non-contiguous relation part {index}")
        parts.append(
            tuple(
                int(row)
                for row in re.findall(
                    r"\brelationRow(\d+) rho", match.group(2)
                )
            )
        )
    flattened = tuple(row for part in parts for row in part)
    if flattened != tuple(range(row_count)):
        raise ValueError("normalized relation parts do not own every row once")
    return tuple(parts)


def _shift_lc(value: Lc, shift: int) -> Lc:
    return {
        0 if wire == 0 else wire + shift: coefficient
        for wire, coefficient in value.items()
    }


def _validate_fixed_prefix(
    template: Template, rows: tuple[Row, ...]
) -> None:
    rvk_rows = _canonical_rows(RVK_DIGEST)
    if len(rvk_rows) != 1812:
        raise ValueError("exact RVK relation row count drifted")
    for local in range(1805):
        expected = tuple(
            _shift_lc(side, template.fixed_shift)
            for side in rvk_rows[local]
        )
        actual = rows[template.fixed_start + local]
        if actual != expected:
            raise ValueError(
                f"{template.digest}: fixed RVK row {local} drifted"
            )


def _substitute(value: Lc, mapping: dict[int, Lc]) -> tuple[Lc, list[tuple[int, int]]]:
    result: Lc = {}
    unknown: list[tuple[int, int]] = []
    for wire, coefficient in value.items():
        if wire not in mapping:
            unknown.append((wire, coefficient))
        else:
            result = _add(
                result, _scale(mapping[wire], coefficient)
            )
    return result, unknown


def _recover_ack_slice(
    rows: tuple[Row, ...], start: int, *, user: bool
) -> AckSlice:
    source = list(ack._canonical_rows())
    source_boundary = ack._recover_boundary(source)
    source_rungs = ack._recover_rungs(source, source_boundary)
    mapping: dict[int, Lc] = {0: {0: 1}}

    if user:
        materialization = rows[start + 252]
        select_x = rows[start + 253]
        select_y = rows[start + 254]
        if materialization[0] != {0: 1}:
            raise ValueError("user ACK materialization lost unit factor")
        base_x = select_x[1]
        base_y = _add(materialization[1], base_x, -1)
        row_map: list[int | None] = [
            *(start + index for index in range(252)),
            start + 253,
            None,
            *(start + index + 1 for index in range(254, ack.ROW_COUNT)),
        ]
        extra = start + 252
    else:
        select_x = rows[start + 252]
        select_y = rows[start + 253]
        base_x = select_x[1]
        base_y = _add(select_y[1], {0: 1})
        row_map = [start + index for index in range(ack.ROW_COUNT)]
        extra = None

    source_x = source[252][1]
    source_y_minus_one = source[253][1]
    for source_lc, target_lc, label in (
        (source_x, base_x, "base X"),
        (
            source_y_minus_one,
            _add(base_y, {0: ORDER - 1}),
            "base Y",
        ),
    ):
        boundary_terms = [
            (wire, coefficient)
            for wire, coefficient in source_lc.items()
            if wire != 0
        ]
        if len(boundary_terms) != 1:
            raise ValueError(f"ACK {label} source boundary drifted")
        wire, coefficient = boundary_terms[0]
        known = {0: source_lc.get(0, 0)}
        mapping[wire] = _scale(
            _add(target_lc, known, -1),
            pow(coefficient, -1, ORDER),
        )

    if user:
        source_delta_y = _singleton(source[253][2], "ACK first Y delta")
        mapping[source_delta_y] = dict(select_y[2])

    pairs = [
        (source_row, target_row)
        for source_row, target_row in enumerate(row_map)
        if target_row is not None
    ]
    changed = True
    while changed:
        changed = False
        for source_row, target_row in pairs:
            for source_lc, target_lc in zip(
                source[source_row], rows[target_row], strict=True
            ):
                known, unknown = _substitute(source_lc, mapping)
                if len(unknown) != 1:
                    continue
                wire, coefficient = unknown[0]
                candidate = _scale(
                    _add(target_lc, known, -1),
                    pow(coefficient, -1, ORDER),
                )
                if wire in mapping and mapping[wire] != candidate:
                    raise ValueError(
                        f"ACK wire {wire} substitution conflicted"
                    )
                if wire not in mapping:
                    mapping[wire] = candidate
                    changed = True

    expected_wires = set(range(ack.WIRE_COUNT))
    if set(mapping) != expected_wires:
        missing = sorted(expected_wires - set(mapping))
        raise ValueError(f"ACK substitution left wires {missing[:16]}")

    for source_row, target_row in pairs:
        for side, (source_lc, target_lc) in enumerate(
            zip(source[source_row], rows[target_row], strict=True)
        ):
            substituted, unknown = _substitute(source_lc, mapping)
            if unknown or substituted != target_lc:
                raise ValueError(
                    f"ACK row {source_row} side {side} substitution drifted"
                )

    if user:
        semantic = [
            _substitute(side, mapping)[0] for side in source[253]
        ]
        materialization = rows[start + 252]
        select_y = rows[start + 254]
        if semantic[0] != select_y[0] or semantic[2] != select_y[2]:
            raise ValueError("user ACK Y selector boundary drifted")
        # semanticB = extractedSelectorB + (materializedB-materializedC).
        if semantic[1] != _add(
            select_y[1],
            _add(materialization[1], materialization[2], -1),
        ):
            raise ValueError(
                "user ACK materialization no longer derives Y selector"
            )

    bit_wires = tuple(
        _singleton(mapping[index], f"ACK bit {index - 1}")
        for index in range(1, ack.BITS + 1)
    )
    scalar = _singleton(mapping[252], "ACK scalar")
    output_x: Lc = {}
    output_y: Lc = {}
    for rung in source_rungs:
        output_x = _add(output_x, mapping[rung.delta_x])
        output_y = _add(output_y, mapping[rung.delta_y])

    return AckSlice(
        start=start,
        scalar=scalar,
        bit_wires=bit_wires,
        base_x=_freeze(base_x),
        base_y=_freeze(base_y),
        wire_map=tuple(
            _freeze(mapping[index]) for index in range(ack.WIRE_COUNT)
        ),
        row_map=tuple(row_map),
        output_x=_freeze(output_x),
        output_y=_freeze(output_y),
        extra_materialization=extra,
    )


def _recover_window2_slice(template: Template, *, user: bool) -> AckSlice:
    tag = "UserWindow2" if user else "IssuerWindow2"
    matches = [
        body for body in window2_providers.BODIES
        if body.digest == template.digest and body.tag == tag
    ]
    if len(matches) != 1:
        raise ValueError(f"{template.digest}: missing exact {tag} body pin")
    body = matches[0]
    _, _, trace = window2_providers.recover(body)
    if body.scalar_lc is None or len(body.scalar_lc) != 1:
        raise ValueError(f"{template.digest}: {tag} scalar is not one wire")
    scalar, coefficient = body.scalar_lc[0]
    if scalar == 0 or coefficient != 1:
        raise ValueError(f"{template.digest}: {tag} scalar boundary drifted")
    return AckSlice(
        start=body.start_row,
        scalar=scalar,
        bit_wires=trace.bit_wires,
        base_x=_freeze(body.base.x_lc()),
        base_y=_freeze(body.base.y_lc()),
        wire_map=(),
        row_map=(),
        output_x=_freeze(body.output.x_lc()),
        output_y=_freeze(body.output.y_lc()),
        extra_materialization=None,
    )


def _validate_boolean_row(row: Row, flag: Lc, label: str) -> None:
    if row[2]:
        raise ValueError(f"{label}: Boolean output is not zero")
    if (
        flag not in (row[0], row[1])
        or _add(row[0], row[1]) != {0: 1}
    ):
        raise ValueError(f"{label}: Boolean factors drifted")


def _recover_boundaries(
    template: Template,
    rows: tuple[Row, ...],
    user: AckSlice,
    issuer: AckSlice,
) -> tuple[Lc, Lc, Lc, Lc, Lc, int, int]:
    eq0, eq1, eq2 = rows[
        template.equivalent_start : template.equivalent_start + 3
    ]
    computed_x = eq0[1]
    computed_y = eq1[1]
    published_y = eq0[0]
    published_x = eq1[0]
    product_x = _singleton(eq0[2], "equivalence product X")
    product_y = _singleton(eq1[2], "equivalence product Y")
    if eq2 != ({0: 1}, {product_x: 1}, {product_y: 1}):
        raise ValueError("equivalence cross-product equality drifted")

    sx, sy = rows[
        template.selector_start : template.selector_start + 2
    ]
    delta_x = _add(dict(issuer.output_x), dict(user.output_x), -1)
    delta_y = _add(dict(issuer.output_y), dict(user.output_y), -1)
    if sx[1] != delta_x or sy[1] != delta_y:
        raise ValueError("selector issuer/user endpoint substitution drifted")
    flag = sx[0]
    if sy[0] != flag:
        raise ValueError("selector X/Y flag expressions diverged")
    adjust_x = _singleton(sx[2], "selector X adjustment")
    adjust_y = _singleton(sy[2], "selector Y adjustment")
    return (
        flag,
        computed_x,
        computed_y,
        published_x,
        published_y,
        adjust_x,
        adjust_y,
    )


def _validate_ownership(
    row_count: int, owners: list[tuple[int, str]]
) -> tuple[str, ...]:
    counts = Counter(row for row, _ in owners)
    duplicates = sorted(row for row, count in counts.items() if count != 1)
    missing = sorted(set(range(row_count)) - set(counts))
    out_of_range = sorted(
        row for row in counts if row < 0 or row >= row_count
    )
    if (
        duplicates
        or missing
        or out_of_range
        or len(owners) != row_count
    ):
        raise ValueError(
            "shared-secret row ownership is not exact: "
            f"duplicates={duplicates[:16]}, missing={missing[:16]}, "
            f"out_of_range={out_of_range[:16]}"
        )
    ownership = [""] * row_count
    for row, owner in owners:
        ownership[row] = owner
    return tuple(ownership)


def _render_lc(value: Lc) -> str:
    terms: list[str] = []
    constant = value.get(0, 0)
    if constant:
        terms.append(f"({constant} : F)")
    for wire, coefficient in sorted(value.items()):
        if wire:
            terms.append(f"({coefficient} : F) * rho {wire}")
    return " + ".join(terms) if terms else "(0 : F)"


def _render_direct_lc(value: Lc) -> str:
    def coefficient(value: int) -> str:
        return "(-1 : F)" if value == ORDER - 1 else f"({value} : F)"

    terms: list[str] = []
    constant = value.get(0, 0)
    if constant:
        terms.append(coefficient(constant))
    for wire, value_coefficient in sorted(value.items()):
        if wire:
            terms.append(
                f"{coefficient(value_coefficient)} * rho {wire}"
            )
    return " + ".join(terms) if terms else "(0 : F)"


def _row_body(source: str, row: int) -> str:
    match = re.search(
        rf"def relationRow{row} \(rho : Nat -> F\) : Prop :=\n"
        r"(.*?)(?=\n\ndef |\nend )",
        source,
        re.S,
    )
    if match is None:
        raise ValueError(f"missing normalized relation row {row}")
    return match.group(1)


def _single_lc_name(source: str, row: int, label: str) -> str:
    names = re.findall(r"\b(relationLc[A-Za-z0-9]+) rho", _row_body(source, row))
    if len(names) != 1:
        raise ValueError(f"{label}: expected one named relation LC, got {names}")
    return names[0]


