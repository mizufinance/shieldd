"""Generate semantic providers for every normalized NoteReshape NB template.

The deployed NoteReshape net-balance operation has one shape parameter: the
number of 128-bit input/output amounts.  Its tail is the already-reviewed
251-bit fixed-base blinding ladder recovered by ``nb_recovery.py``.  This module
recovers each normalized template from its reviewed canonical registry relation,
checks the amount/range/conservation/ladder partition, and reuses that proof
construction over normalized local wires.

The public API is ``generated_nb_semantic_files``.  It returns deterministic
``Path -> Lean source`` entries and performs all fail-closed recovery before
emitting a byte.  The NoteReshape semantic orchestrator owns writing/checking
those files.
"""

