def camel(text: str) -> str:
    result: list[str] = []
    upper = True
    for char in text:
        if char in "._-":
            upper = True
        elif upper:
            result.append(char.upper())
            upper = False
        else:
            result.append(char)
    return "".join(result)


def default_template_name(key: str) -> str:
    op, digest = key.split("@", 1)
    return f"T{camel(op)}_{digest}"


Lc = dict[int, int]
Row = tuple[Lc, Lc, Lc]


def _parse_ir(template: NbTemplate) -> dict:
    path = IR_ROOT / f"{template.circuit}-deployed-slice-ir.json"
    ir = json.loads(path.read_text())
    matches = [segment for segment in ir["segments"] if segment["index"] == template.segment]
    if len(matches) != 1:
        raise ValueError(f"{template.circuit}: expected one segment {template.segment}")
    segment = matches[0]
    expected = {
        "op": "decaf.conservation_net_balance_commitment",
        "template_key": template.key,
        "constraint_count": template.constraint_count,
    }
    for field, value in expected.items():
        if segment.get(field) != value:
            raise ValueError(
                f"{template.circuit}:Seg{template.segment} {field} drift: "
                f"{segment.get(field)!r} != {value!r}"
            )
    if segment["end"] - segment["start"] != template.constraint_count:
        raise ValueError(f"{template.key}: non-exact representative row range")
    if len(segment["wire_seating"]) != template.constraint_count:
        raise ValueError(f"{template.key}: normalized wire-count pin drift")
    if len(set(segment["wire_seating"])) != len(segment["wire_seating"]):
        raise ValueError(f"{template.key}: non-injective normalized wire seating")
    if segment["wire_seating"][0] != 0:
        raise ValueError(f"{template.key}: local constant wire is not zero")
    return segment


def normalized_rows(template: NbTemplate) -> list[Row]:
    """Read the representative rows and alpha-rename them to normalized wires."""
    segment = _parse_ir(template)
    inverse = {global_wire: local for local, global_wire in enumerate(segment["wire_seating"])}
    pattern = re.compile(r"\(constraint \[(.*?)\] \[(.*?)\] \[(.*?)\]\)$")
    rows: list[Row] = []
    constraint_index = 0
    sr1cs = ARTIFACT_ROOT / template.circuit / f"{template.circuit}.sr1cs"
    with sr1cs.open() as source_file:
        for raw_line in source_file:
            line = raw_line.strip()
            if not line.startswith("(constraint "):
                continue
            if constraint_index >= segment["end"]:
                break
            if constraint_index >= segment["start"]:
                match = pattern.fullmatch(line)
                if match is None:
                    raise ValueError(
                        f"{template.key}: unparseable SR1CS row {constraint_index}"
                    )
                sides: list[Lc] = []
                for group in match.groups():
                    side: Lc = {}
                    for coeff_text, wire_text in re.findall(r"\(([-0-9]+) (\d+)\)", group):
                        global_wire = int(wire_text)
                        if global_wire not in inverse:
                            raise ValueError(
                                f"{template.key}: row references unseated wire {global_wire}"
                            )
                        wire = inverse[global_wire]
                        coeff = (side.get(wire, 0) + int(coeff_text)) % ORDER
                        if coeff:
                            side[wire] = coeff
                        else:
                            side.pop(wire, None)
                    sides.append(side)
                rows.append((sides[0], sides[1], sides[2]))
            constraint_index += 1
    if len(rows) != template.constraint_count:
        raise ValueError(
            f"{template.key}: expected {template.constraint_count} rows, got {len(rows)}"
        )
    return rows


def _singleton(side: Lc, label: str) -> int:
    if len(side) != 1:
        raise ValueError(f"{label}: expected singleton side, got {side}")
    wire, coefficient = next(iter(side.items()))
    if wire == 0 or coefficient != 1:
        raise ValueError(f"{label}: expected coefficient-one witness, got {side}")
    return wire


def _blind_accumulators(template: NbTemplate, rows: list[Row]) -> tuple[tuple[int, int], ...]:
    result = []
    cursor = template.blind_copy_row + 1
    for index in range(250):
        block_size = 5 if index < 149 else 8
        acc_x = _singleton(rows[cursor + block_size - 2][2], f"rung {index + 1} x")
        acc_y = _singleton(rows[cursor + block_size - 1][2], f"rung {index + 1} y")
        result.append((acc_x, acc_y))
        cursor += block_size
    if cursor != template.constraint_count:
        raise ValueError(
            f"{template.key}: ladder ends at row {cursor}, expected {template.constraint_count}"
        )
    if result[-1] != (template.constraint_count - 2, template.constraint_count - 1):
        raise ValueError(f"{template.key}: final accumulator wire pin drift")
    return tuple(result)


def recover(template: NbTemplate) -> dict:
    """Validate all structural pins consumed by the generalized proof."""
    rows = normalized_rows(template)
    for label, bit_base, bit_rows, rec_row, amount_wire in template.amount_blocks:
        if bit_rows[1] - bit_rows[0] + 1 != 128:
            raise ValueError(f"{template.key}:{label}: non-128-bit amount range")
        for offset, row in enumerate(range(bit_rows[0], bit_rows[1] + 1)):
            wire = bit_base + offset
            a, b, _ = rows[row]
            if wire not in a and wire not in b:
                raise ValueError(f"{template.key}:{label}: bit {wire} absent from row {row}")
        if rows[rec_row][2] != {amount_wire: 1}:
            raise ValueError(
                f"{template.key}:{label}: recomposition target drift at row {rec_row}"
            )

    expected_conservation = (
        {0: 1},
        {wire: 1 for wire in template.input_wires},
        {wire: 1 for wire in template.output_wires},
    )
    if rows[template.conservation_row] != expected_conservation:
        raise ValueError(
            f"{template.key}: conservation row drift: "
            f"{rows[template.conservation_row]} != {expected_conservation}"
        )

    blind_rows = (template.blind_bit_base, template.blind_bit_base + 250)
    for offset, row in enumerate(range(blind_rows[0], blind_rows[1] + 1)):
        wire = template.blind_bit_base + offset
        a, b, _ = rows[row]
        if wire not in a and wire not in b:
            raise ValueError(f"{template.key}: blind bit {wire} absent from row {row}")
    if rows[template.blind_copy_row][2] != {template.blind_wire: 1}:
        raise ValueError(f"{template.key}: blind recomposition target drift")

    accumulators = _blind_accumulators(template, rows)
    return {
        "rows": rows,
        "blind_accumulators": accumulators,
        "blind_rows": blind_rows,
    }


def _relation_source(template: NbTemplate) -> str:
    shards = sorted(
        RELATIONS_ROOT.glob(f"{template.relation_stem}Defs*.lean"),
        key=lambda path: int(path.stem.removeprefix(template.relation_stem + "Defs")),
    )
    indices = [
        int(path.stem.removeprefix(template.relation_stem + "Defs"))
        for path in shards
    ]
    if indices != list(range(len(indices))):
        raise ValueError(f"{template.key}: non-contiguous normalized relation shards")
    facade = RELATIONS_ROOT / f"{template.relation_stem}.lean"
    files = [*shards, facade]
    if not shards or not facade.is_file():
        raise ValueError(f"missing normalized relation source for {template.key}")
    bodies = []
    for path in files:
        lines = path.read_text().splitlines()
        try:
            start = next(index for index, line in enumerate(lines) if line.startswith("namespace "))
            end = max(index for index, line in enumerate(lines) if line.startswith("end "))
        except (StopIteration, ValueError) as error:
            raise ValueError(f"{path}: normalized relation module has no namespace") from error
        if end <= start:
            raise ValueError(f"{path}: invalid normalized relation namespace")
        bodies.append("\n".join(lines[start + 1:end]) + "\n")
    source = "\n\ndef generatedNbRelationShardBoundary : Prop := True\n\n".join(bodies)
    rows = {
        int(match.group(1))
        for match in re.finditer(r"def relationRow(\d+) \(rho : Nat -> F\)", source)
    }
    if rows != set(range(template.constraint_count)):
        raise ValueError(
            f"{template.key}: normalized Lean rows do not cover the relation exactly"
        )
    return source


@contextmanager
def _configured_nb(template: NbTemplate, seating: dict) -> Iterator[None]:
    """Temporarily seat the reviewed seg46 emitter on normalized local wires."""
    names = (
        "ROW_COUNT", "AMOUNT_BLOCKS", "BLIND_BIT_BASE", "BLIND_BINARY_ROWS",
        "BLIND_COPY_ROW", "BLIND_WIRE", "BLIND_ACCS", "OUT_X_WIRE",
        "OUT_Y_WIRE", "CONSERVATION_ROW", "IN0_WIRE", "IN1_WIRE",
        "OUT0_WIRE", "CONTRACTS_SOURCE",
    )
    saved = {name: getattr(nb, name) for name in names}
    saved_dtk_source = dtk.SOURCE_CONTRACTS
    saved_dtk_rows = dtk.ROW_COUNT
    virtual_source = RELATIONS_ROOT / (".nb-provider-" + template.digest)
    cache_key = (str(virtual_source.resolve()), 46)
    old_cache = dtk._SOURCE_CACHE.get(cache_key)
    old_parts = dtk._RELATION_PARTS_CACHE.get(
        (str(virtual_source.resolve()), 46, template.constraint_count)
    )
    try:
        nb.ROW_COUNT = template.constraint_count
        nb.AMOUNT_BLOCKS = template.amount_blocks
        nb.BLIND_BIT_BASE = template.blind_bit_base
        nb.BLIND_BINARY_ROWS = seating["blind_rows"]
        nb.BLIND_COPY_ROW = template.blind_copy_row
        nb.BLIND_WIRE = template.blind_wire
        nb.BLIND_ACCS = seating["blind_accumulators"]
        nb.OUT_X_WIRE, nb.OUT_Y_WIRE = seating["blind_accumulators"][-1]
        nb.CONSERVATION_ROW = template.conservation_row
        # The legacy emitter's custom top/conservation modules are not used,
        # but keep these globals valid for any helper-level invariant checks.
        nb.IN0_WIRE = template.input_wires[0]
        nb.IN1_WIRE = template.input_wires[min(1, len(template.input_wires) - 1)]
        nb.OUT0_WIRE = template.output_wires[0]
        nb.CONTRACTS_SOURCE = virtual_source
        dtk.SOURCE_CONTRACTS = virtual_source
        dtk.ROW_COUNT = template.constraint_count
        dtk._SOURCE_CACHE[cache_key] = _relation_source(template)
        dtk._RELATION_PARTS_CACHE.pop(
            (str(virtual_source.resolve()), 46, template.constraint_count), None
        )
        yield
    finally:
        for name, value in saved.items():
            setattr(nb, name, value)
        dtk.SOURCE_CONTRACTS = saved_dtk_source
        dtk.ROW_COUNT = saved_dtk_rows
        if old_cache is None:
            dtk._SOURCE_CACHE.pop(cache_key, None)
        else:
            dtk._SOURCE_CACHE[cache_key] = old_cache
        parts_key = (str(virtual_source.resolve()), 46, template.constraint_count)
        if old_parts is None:
            dtk._RELATION_PARTS_CACHE.pop(parts_key, None)
        else:
            dtk._RELATION_PARTS_CACHE[parts_key] = old_parts


def _sum(wires: tuple[int, ...]) -> str:
    if not wires:
        return "(0 : F)"
    return " + ".join(f"rho {wire}" for wire in wires)


