@dataclass(frozen=True)
class NbTemplate:
    key: str
    circuit: str
    segment: int
    inputs: int
    outputs: int
    constraint_count: int

    @property
    def digest(self) -> str:
        return self.key.split("@", 1)[1]

    @property
    def amount_count(self) -> int:
        return self.inputs + self.outputs

    @property
    def conservation_row(self) -> int:
        return self.amount_count * 129

    @property
    def blind_bit_base(self) -> int:
        return self.conservation_row + 1

    @property
    def blind_copy_row(self) -> int:
        return self.blind_bit_base + 251

    @property
    def blind_wire(self) -> int:
        return self.blind_copy_row

    @property
    def relation_stem(self) -> str:
        return "TDecafConservationNetBalanceCommitment_" + self.digest

    @property
    def amount_blocks(self) -> tuple[tuple[str, int, tuple[int, int], int, int], ...]:
        labels = [*(f"In{i}" for i in range(self.inputs)),
                  *(f"Out{i}" for i in range(self.outputs))]
        result = []
        for index, label in enumerate(labels):
            row = index * 129
            bit_base = row + 1
            result.append((label, bit_base, (row, row + 127), row + 128, row + 129))
        return tuple(result)

    @property
    def input_wires(self) -> tuple[int, ...]:
        return tuple(block[4] for block in self.amount_blocks[:self.inputs])

    @property
    def output_wires(self) -> tuple[int, ...]:
        return tuple(block[4] for block in self.amount_blocks[self.inputs:])


