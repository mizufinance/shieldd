def _rewrite(
    source: str, template: NbTemplate, module_prefix: str, namespace: str,
    relation: str,
) -> str:
    source = source.replace(
        "ShielddGnarkFormal.Deployed.Contracts.NoteReshape2x1.NbAdapterSeg46",
        module_prefix,
    )
    source = source.replace(
        "namespace Shieldd.GnarkFormal.Deployed.Contracts.NoteReshape2x1",
        f"namespace {namespace}",
    ).replace(
        "end Shieldd.GnarkFormal.Deployed.Contracts.NoteReshape2x1",
        f"end {namespace}",
    )
    source = source.replace("Seg46.F", "F")
    source = source.replace("Seg46.", relation + ".")
    source = source.replace("seg46", "nb")
    source = re.sub(r"\b31661\b", str(template.blind_bit_base), source)
    return source


def _emit_base(
    template: NbTemplate, namespace: str, relation_module: str,
) -> str:
    lines = [
        f"import {relation_module}",
        "import ShielddGnarkFormal.Deployed.PrimeOrderCertificate",
        "",
        "set_option maxRecDepth 1000000",
        "set_option maxHeartbeats 20000000",
        "",
        f"namespace {namespace}",
        "",
        f"def Order : Nat := {ORDER}",
        "abbrev F := ZMod Order",
        "",
        "instance nbFactPrime : Fact (Nat.Prime Order) :=",
        "  ⟨Shieldd.GnarkFormal.Deployed.decaf377ScalarFieldPrime⟩",
        "",
    ]
    for label, bit_base, _, _, _ in template.amount_blocks:
        lines += [
            f"def nb{label}Bits (rho : Nat -> F) : List.Vector F 128 :=",
            f"  List.Vector.ofFn (fun i : Fin 128 => rho ({bit_base} + i.val))",
            "",
            f"theorem nb{label}Bits_get (rho : Nat -> F) (i : Nat) (hi : i < 128) :",
            f"    (nb{label}Bits rho)[i]! = rho ({bit_base} + i) := by",
            "  rw [getElem!_pos _ i (by simpa using hi)]",
            "  conv_lhs => rw [List.Vector.getElem_def]",
            f"  simp only [nb{label}Bits, List.Vector.toList_ofFn, List.getElem_ofFn]",
            "",
        ]
    lines += [
        "def nbBlindBits (rho : Nat -> F) : List.Vector F 251 :=",
        f"  List.Vector.ofFn (fun i : Fin 251 => rho ({template.blind_bit_base} + i.val))",
        "",
        "theorem nbBlindBits_get (rho : Nat -> F) (i : Nat) (hi : i < 251) :",
        f"    (nbBlindBits rho)[i]! = rho ({template.blind_bit_base} + i) := by",
        "  rw [getElem!_pos _ i (by simpa using hi)]",
        "  conv_lhs => rw [List.Vector.getElem_def]",
        "  simp only [nbBlindBits, List.Vector.toList_ofFn, List.getElem_ofFn]",
        "",
        f"end {namespace}",
        "",
    ]
    return "\n".join(lines)


def _emit_conservation(template: NbTemplate) -> str:
    cfg = SimpleNamespace(seg=46)
    lines = [
        "import PLACEHOLDER_BASE",
        "import Mathlib.Tactic.LinearCombination",
        "",
        "set_option maxRecDepth 1000000",
        "set_option maxHeartbeats 20000000",
        "set_option linter.unusedVariables false",
        "",
        "namespace PLACEHOLDER_NAMESPACE",
        "",
        "theorem nb_conservation (rho : Nat -> F) (h : PLACEHOLDER_REL.relation rho) :",
        f"    {_sum(template.input_wires)} = {_sum(template.output_wires)} := by",
    ]
    dtk.emit_unpack(lines, cfg, {template.conservation_row})
    dtk.emit_row_unfold(lines, cfg, template.conservation_row)
    lines += [
        f"  linear_combination r{template.conservation_row}",
        "",
        "end PLACEHOLDER_NAMESPACE",
        "",
    ]
    return "\n".join(lines)


