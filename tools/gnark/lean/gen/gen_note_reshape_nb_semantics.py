def _render_template(
    template: NbTemplate, out: Path, template_name_fn: Callable[[str], str],
) -> dict[Path, str]:
    seating = recover(template)
    name, module_prefix, namespaces = _support_names(template, template_name_fn)
    namespace, relation = namespaces.split("|", 1)
    relation_module = relation.replace("Shieldd.GnarkFormal", "ShielddGnarkFormal")

    with _configured_nb(template, seating):
        blind = nb.emit_blind_modules({
            "rows": seating["rows"],
            "blind": nb.blind_rungs(seating["rows"]),
        })
        blind.pop("NbAdapterSeg46BlindEndpoint")
        binary = nb.emit_to_binary_modules()
        conservation = _emit_conservation(template)

    modules = {**blind, **binary}
    outputs: dict[Path, str] = {}
    outputs[out / f"{name}NbBase.lean"] = GENERATED_HEADER + _emit_base(
        template, namespace, relation_module
    )
    for old_name, source in modules.items():
        suffix = old_name.removeprefix("NbAdapterSeg46")
        rewritten = _rewrite(source, template, module_prefix, namespace, relation)
        outputs[out / f"{name}Nb{suffix}.lean"] = GENERATED_HEADER + rewritten

    conservation = conservation.replace("PLACEHOLDER_BASE", module_prefix + "Base")
    conservation = conservation.replace("PLACEHOLDER_NAMESPACE", namespace)
    conservation = conservation.replace("PLACEHOLDER_REL", relation)
    conservation = _rewrite(
        conservation, template, module_prefix, namespace, relation
    )
    outputs[out / f"{name}NbConserv.lean"] = GENERATED_HEADER + conservation
    outputs[out / f"{name}.lean"] = GENERATED_HEADER + _emit_provider(
        template, name, module_prefix, namespace, relation
    )
    return outputs


def generated_nb_semantic_files(
    out: Path = DEFAULT_OUT,
    template_name_fn: Callable[[str], str] = default_template_name,
) -> dict[Path, str]:
    """Return all generalized NB support/provider sources, failing closed."""
    outputs: dict[Path, str] = {}
    for template in NB_TEMPLATES:
        rendered = _render_template(template, out, template_name_fn)
        overlap = set(outputs).intersection(rendered)
        if overlap:
            raise ValueError(f"duplicate NB semantic outputs: {sorted(overlap)}")
        outputs.update(rendered)
    expected_providers = {
        out / (template_name_fn(template.key) + ".lean") for template in NB_TEMPLATES
    }
    if not expected_providers.issubset(outputs):
        raise ValueError("NB provider output set is incomplete")
    forbidden = ("fun _ h => h", "spec (rho : Nat -> F) : Prop :=\n  relation rho", "axiom ", "native_decide")
    for path, source in outputs.items():
        for marker in forbidden:
            if marker in source:
                raise ValueError(f"{path}: forbidden semantic marker {marker!r}")
    return outputs
