#!/usr/bin/env python3
"""Emit the consolidate2x1 deployed capstone module.

Reads the coverage manifest, fails closed unless every class is proven and
every instance names an inst{N}_bound theorem, then emits Capstone.lean:
`relationAll` / `specAll` (one conjunct per proven instance, ordered by
segment index) and the composition theorem `consolidate2x1_deployed_sound`.

The claim that `relationAll` covers every compiled `.sr1cs` row is NOT made
here — that is the Rust `shieldd-constraint-coverage` partition gate. This
module composes the per-segment soundness theorems over one global valuation.
"""

import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[3].parent
MANIFEST = (
    REPO
    / "crates/core/component/shielded-pool/formal/consolidate2x1-coverage-manifest.json"
)
OUT = (
    Path(__file__).resolve().parents[1]
    / "ShielddGnarkFormal/Deployed/Contracts/Consolidate2x1/Capstone.lean"
)

THEOREM_PREFIX = "Shieldd.GnarkFormal.Deployed.Contracts.Consolidate2x1.inst"


def main() -> None:
    manifest = json.loads(MANIFEST.read_text())
    segs = []
    for cls in manifest["classes"]:
        assert cls["status"] == "proven", f"class not proven: {cls['class_key']}"
        for inst in cls["instances"]:
            n = inst["segment_index"]
            expected = f"{THEOREM_PREFIX}{n}_bound"
            assert inst["lean_theorem"] == expected, (
                f"seg {n}: lean_theorem {inst['lean_theorem']!r} != {expected!r}"
            )
            segs.append(n)
    assert len(segs) == len(set(segs)), "duplicate segment index"
    segs.sort()

    conj_rel = " ∧\n  ".join(f"Seg{n}.contract.relation rho" for n in segs)
    conj_spec = " ∧\n  ".join(f"Seg{n}.contract.spec rho" for n in segs)
    hyps = " ".join(f"h{n}" for n in segs)
    uses = ",\n    ".join(f"inst{n}_bound.2.2 rho h{n}" for n in segs)

    # Per-segment projection lemmas out of the composed spec conjunction.
    # k-th conjunct (0-based i) is reached by i `.2`s then `.1`; the final
    # conjunct is reached by i `.2`s alone. The trailing `(… :)` ascription
    # forces unification through the `specAll` def.
    last = len(segs) - 1
    projections = "\n\n".join(
        f"""theorem specOf{n} (rho : Nat → DeployedF) (h : relationAll rho) :
    Seg{n}.contract.spec rho :=
  ((consolidate2x1_deployed_sound rho h){"".join(".2" for _ in range(i))}{"" if i == last else ".1"} :)"""
        for i, n in enumerate(segs)
    )

    OUT.write_text(f"""import ShielddGnarkFormal.Deployed.Contracts.Consolidate2x1.Bounds

set_option maxRecDepth 100000
set_option maxHeartbeats 4000000

/-! Deployed capstone for consolidate2x1: one theorem composing every proven
per-segment deployed soundness bound over a single global wire valuation.
Row coverage (that these {len(segs)} relations partition the compiled `.sr1cs`)
is enforced by `shieldd-constraint-coverage`, not re-proved here.
GENERATED by gen/gen_capstone.py — do not edit by hand. -/

namespace Shieldd.GnarkFormal.Deployed.Contracts.Consolidate2x1

open Specs (DeployedF)

/-- Conjunction of all {len(segs)} proven deployed segment relations. -/
def relationAll (rho : Nat → DeployedF) : Prop :=
  {conj_rel}

/-- Conjunction of the corresponding deployed segment specs. -/
def specAll (rho : Nat → DeployedF) : Prop :=
  {conj_spec}

theorem consolidate2x1_deployed_sound :
    ∀ rho, relationAll rho → specAll rho := by
  intro rho h
  obtain ⟨{', '.join(f'h{n}' for n in segs)}⟩ := h
  exact ⟨{uses}⟩

{projections}

end Shieldd.GnarkFormal.Deployed.Contracts.Consolidate2x1
""")
    _ = hyps
    print(f"wrote {OUT} ({len(segs)} conjuncts)")


if __name__ == "__main__":
    main()
