#!/usr/bin/env python3
"""Emit deployed glue-segment bridges (assert.eq / decaf.assert_equivalent).

Each glue class is a gnark constant-folded 1-3 row slice. Its spec is the
algebraic equality it enforces, oriented output-first, trivially derivable from
the relation. Three structural patterns are recognised; an unrecognised file is
a hard error (no silent miscoverage):

  A. single equality `A = B`            -> spec `B = A`        (output rows, i0=i1)
  B. `∃ v0 v1, A0=v0 ∧ A1=v1 ∧ v0=v1`   -> spec `A0 = A1`      (assert_equivalent)
  C. `∃ v0, X = v0` (no cross-link)     -> spec `True`         (redundant row)

Reads the committed Extracted/Deployed glue defs; writes one Lean file with a
section per class. Reproducible; the cargo obligation table pins each class's
constants, and a Lean build proves every theorem axiom-clean.
"""
import pathlib, re, sys

HERE = pathlib.Path(__file__).resolve().parent
LEAN = HERE.parent
EXTRACTED = LEAN / "ShielddGnarkFormal/Extracted/Deployed"
OUT = LEAN / "ShielddGnarkFormal/Deployed/GlueBridges.lean"

# class file stem -> (bridge namespace leaf, coverage class_key for the manifest)
GLUE = {
    "AssertEq1_06c76c": "AssertEq06c76c",
    "AssertEq1_3c90b3": "AssertEq3c90b3",
    "AssertEq1_745c86": "AssertEq745c86",
    "AssertEq1_798349": "AssertEq798349",
    "AssertEq1_944014": "AssertEq944014",
    "AssertEq1_fcdce0": "AssertEqFcdce0",
    "DecafAssertEquivalent3_33ce4e": "AssertEquivalent33ce4e",
    "DecafAssertEquivalent3_cddeba": "AssertEquivalentCddeba",
}


def parse(stem):
    text = (EXTRACTED / f"{stem}.lean").read_text()
    ns = re.search(r"^namespace (\S+)", text, re.M).group(1)
    m = re.search(r"def relation (.+?) : Prop :=\n(.*?)\n\nend ", text, re.S)
    if not m:
        sys.exit(f"{stem}: cannot locate `def relation ... : Prop := ... end`")
    binders = m.group(1).strip()
    body = m.group(2).strip()
    exists_vars = []
    em = re.match(r"∃ (.+?) : F,\s*(.*)", body, re.S)
    if em:
        exists_vars = em.group(1).split()
        body = em.group(2).strip()
    # split conjuncts on top-level ` ∧`
    conjuncts = [c.strip() for c in re.split(r"\s∧\s", body)]
    return ns, binders, exists_vars, conjuncts


def split_eq(conj):
    # each conjunct is `L = R` with exactly one top-level ` = `
    parts = conj.split(" = ")
    if len(parts) != 2:
        sys.exit(f"conjunct is not a single equality: {conj!r}")
    return parts[0].strip(), parts[1].strip()


def emit(stem, leaf):
    ns, binders, ex, conj = parse(stem)
    head = (
        f"namespace Shieldd.GnarkFormal.Deployed.{leaf}\n"
        f"open {ns}\n"
        f"variable [Fact (Nat.Prime Order)]\n\n"
    )
    if not ex and len(conj) == 1:
        # pattern A: single equality A = B -> spec B = A
        a, b = split_eq(conj[0])
        thm = (
            f"theorem circuit_sound {binders} (h : relation "
            f"{binder_names(binders)}) :\n    {b} = {a} := by\n"
            f"  simpa only [relation, one_mul] using h.symm\n"
        )
    elif ex and len(conj) >= 3:
        # pattern B: assert_equivalent A0=v0 ∧ A1=v1 ∧ v0=v1 -> spec A0 = A1
        a0, _ = split_eq(conj[0])
        a1, _ = split_eq(conj[1])
        pat = ", ".join(ex) + ", h0, h1, h2"
        thm = (
            f"theorem circuit_sound {binders} (h : relation "
            f"{binder_names(binders)}) :\n    {a0} = {a1} := by\n"
            f"  obtain ⟨{pat}⟩ := h\n"
            f"  simp only [one_mul] at h0 h1 h2 ⊢\n"
            f"  rw [h0, h1]\n  exact h2\n"
        )
    elif ex:
        # pattern C: lone existential, no cross-link -> redundant row, spec True
        thm = (
            f"theorem circuit_sound {binders} (_ : relation "
            f"{binder_names(binders)}) : True := trivial\n"
        )
    else:
        sys.exit(f"{stem}: unrecognised relation shape ({len(conj)} conjuncts)")
    return head + thm + f"\nend Shieldd.GnarkFormal.Deployed.{leaf}\n"


def binder_names(binders):
    # binder text is `(i0 i1 : F) (o0 : F)`; collect the variable names in order
    names = []
    for grp in re.findall(r"\(([^:]+):", binders):
        names.extend(grp.split())
    return " ".join(names)


def main():
    imports = "".join(
        f"import ShielddGnarkFormal.Extracted.Deployed.{stem}\n" for stem in GLUE
    )
    header = (
        imports
        + "\n/-! Deployed glue-segment bridges (assert.eq / decaf.assert_equivalent).\n"
        "Each theorem discharges one constant-folded deployed slice against the\n"
        "algebraic equality it enforces. Auto-generated by gen_glue_bridges.py;\n"
        "do not edit by hand. -/\n\n"
        "set_option linter.unusedVariables false\n"
        "set_option maxRecDepth 100000\n"
        "set_option maxHeartbeats 1000000\n\n"
    )
    sections = "\n".join(emit(stem, leaf) for stem, leaf in GLUE.items())
    OUT.write_text(header + sections)
    print(f"wrote {OUT.relative_to(LEAN)} ({len(GLUE)} glue bridges)")


if __name__ == "__main__":
    main()
