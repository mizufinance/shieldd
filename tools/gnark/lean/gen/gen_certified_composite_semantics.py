def _embedded_compress_files(
    family: compress.Family,
    source: str,
    parts: list[list[int]],
) -> dict[Path, str]:
    rows = compress.relation_rows(
        source,
        family.row_offset,
        compress.ROW_COUNT,
    )
    mapping = compress._wire_mapping(family)
    hyps = compress.reviewed.parse_bridge_hyps()
    compress.reviewed.validate_bridge_hyps(hyps)
    hyp_chunks = compress.reviewed.chunks(hyps, compress.BRIDGE_CHUNK_SIZE)
    stem = family.semantic_stem
    outputs = {
        OUT / f"{stem}Chunks.lean":
            compress._chunks(family, rows, mapping),
        OUT / f"{stem}Base.lean":
            compress._base(family, rows, parts, mapping),
    }
    for index, chunk in enumerate(hyp_chunks):
        outputs[OUT / f"{stem}Rows{index}.lean"] = compress._row_chunk(
            family,
            index,
            chunk,
            parts,
        )
    outputs[OUT / f"{stem}.lean"] = compress._head(
        family,
        hyps,
        parts,
    )
    expected = 3 + len(hyp_chunks)
    if len(outputs) != expected:
        raise ValueError(
            f"{family.key}: expected {expected} embedded compress files, "
            f"generated {len(outputs)}"
        )
    return outputs


