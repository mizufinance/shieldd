def _render_poseidon_part(
    family: compress.Family,
    block: PoseidonBlock,
    block_index: int,
    part: int,
    canonical_rows: list[recovery.Row],
    raw_rows: list[recovery.Row],
    lc_names: dict[int, tuple[str, ...]],
) -> str:
    name = family.name
    prefix = f"block{block_index}"
    relation = f"Shieldd.GnarkFormal.Deployed.Templates.Relations.{name}"
    trace = (
        "Shieldd.GnarkFormal.Deployed.Templates.Semantics."
        "TransferPoseidon2Trace"
    )
    global_start = block.rows.start + part * 5
    row_indices = list(range(global_start, global_start + 5))
    output_chain = [next(iter(canonical_rows[row][2])) for row in row_indices]
    if output_chain[-1] != block.outputs[part]:
        raise ValueError(f"{name} {prefix} part {part}: recovered output drifted")
    raw_input = raw_rows[row_indices[0]][0]
    if (
        raw_rows[row_indices[0]][1] != raw_input
        or raw_rows[row_indices[-1]][1] != raw_input
        or _reduced_lc(raw_input) != dict(block.inputs[part])
    ):
        raise ValueError(f"{name} {prefix} part {part}: signed input LC drifted")
    hypotheses = " ".join(
        f"(h{row} : {relation}.relationRow{row} rho)" for row in row_indices
    )
    lines = [
        f"theorem {prefix}Part{part} (rho : Nat → F) {hypotheses} :",
        f"    rho {output_chain[-1]} = Shieldd.GnarkFormal.Poseidon2Bridge.p17",
        f"      ({prefix}RoundInput{part} rho) := by",
    ]
    for row in row_indices:
        lines.append(f"  unfold {relation}.relationRow{row} at h{row}")
        names = lc_names.get(row, ())
        if names:
            lines.append(
                "  simp only ["
                + ", ".join(f"{relation}.{item}" for item in names)
                + f"] at h{row}"
            )
    lines.append(
        _input_cast_proof(
            f"{prefix}RoundInput{part}",
            f"h{prefix}Input{part}",
            block.inputs[part],
            raw_input,
        )
    )
    lines.extend(
        [
            f"  apply {trace}.p17_from_rows",
            f"      ({prefix}RoundInput{part} rho)",
            "      " + " ".join(f"(rho {wire})" for wire in output_chain),
            f"  · rw [h{prefix}Input{part}]; linear_combination h{row_indices[0]}",
            f"  · linear_combination h{row_indices[1]}",
            f"  · linear_combination h{row_indices[2]}",
            f"  · linear_combination h{row_indices[3]}",
            f"  · rw [h{prefix}Input{part}]; linear_combination h{row_indices[4]}",
        ]
    )
    return "\n".join(lines)


def _render_poseidon_block_gate(
    family: compress.Family,
    block: PoseidonBlock,
    block_index: int,
    gate: int,
) -> str:
    name = family.name
    prefix = f"block{block_index}"
    relation = f"Shieldd.GnarkFormal.Deployed.Templates.Relations.{name}"
    block_ns = (
        f"Shieldd.GnarkFormal.Deployed.Templates.Semantics."
        f"{name}Poseidon.Block{block_index}"
    )
    namespace = f"{block_ns}.Gate{gate}"
    trace = (
        "Shieldd.GnarkFormal.Deployed.Templates.Semantics."
        "TransferPoseidon2Trace"
    )
    parts = block.gate_parts[gate]
    wanted = {
        row
        for part in parts
        for row in range(block.rows.start + part * 5, block.rows.start + part * 5 + 5)
    }
    relation_parts = _relation_parts(family)
    canonical_rows = recovery.rows(family.key.split("@")[-1])
    raw_rows = recovery.raw_rows(family.key.split("@")[-1])
    lc_names = _relation_lc_names(name)
    part_theorems = "\n\n".join(
        _render_poseidon_part(
            family,
            block,
            block_index,
            part,
            canonical_rows,
            raw_rows,
            lc_names,
        )
        for part in parts
    )
    previous_binder = ""
    if gate:
        previous_binder = (
            f"\n    (hPrev : {trace}.state{gate - 1} {prefix}Domain "
            f"({prefix}Input0 rho) ({prefix}Input1 rho) = "
            f"{prefix}Endpoint{gate - 1} rho)"
        )
    proof = [_unpack_selected_relation_rows(relation, relation_parts, wanted)]
    for part in parts:
        start = block.rows.start + part * 5
        proof.append(
            f"  have hp{part} := {prefix}Part{part} rho "
            + " ".join(f"h{row}" for row in range(start, start + 5))
        )
    rounds = poseidon_rounds(2)
    if gate == 0:
        variable_lanes = (1,) if block.fixed_input1_powers is not None else (1, 2)
        proof.extend(
            [
                f"  have hd : ({block.domain_powers[-1]} : F) =",
                "      Shieldd.GnarkFormal.Poseidon2Bridge.p17",
                f"        ((vec![{prefix}Domain, {prefix}Input0 rho, {prefix}Input1 rho])[0] +",
                f"          {trace}.roundConstants0[0]) := by",
                f"    simpa [{prefix}Domain, {trace}.roundConstants0] using {prefix}DomainP17",
            ]
        )
        lane_facts = ["hd"]
        for lane, part in zip(variable_lanes, parts, strict=True):
            fact = f"hLane{lane}"
            lane_facts.append(fact)
            proof.extend(
                [
                    f"  have {fact} : rho {block.outputs[part]} =",
                    "      Shieldd.GnarkFormal.Poseidon2Bridge.p17",
                    f"        ((vec![{prefix}Domain, {prefix}Input0 rho, {prefix}Input1 rho])[{lane}] +",
                    f"          {trace}.roundConstants0[{lane}]) := by",
                    f"    rw [{prefix}RoundInput{part}_eq_initial_arg] at hp{part}",
                    f"    simpa [{trace}.roundConstants0] using hp{part}",
                ]
            )
        if block.fixed_input1_powers is not None:
            lane_facts.append("hInput1")
            proof.extend(
                [
                    f"  have hInput1 : ({block.fixed_input1_powers[-1]} : F) =",
                    "      Shieldd.GnarkFormal.Poseidon2Bridge.p17",
                    f"        ((vec![{prefix}Domain, {prefix}Input0 rho, {prefix}Input1 rho])[2] +",
                    f"          {trace}.roundConstants0[2]) := by",
                    f"    simpa [{prefix}Input1, {trace}.roundConstants0] using {prefix}Input1P17",
                ]
            )
        outputs = [
            f"({block.domain_powers[-1]} : F)",
            f"(rho {block.outputs[parts[0]]})",
            (
                f"(rho {block.outputs[parts[1]]})"
                if block.fixed_input1_powers is None
                else f"({block.fixed_input1_powers[-1]} : F)"
            ),
        ]
        raw_lanes = ",\n        ".join(
            "Shieldd.GnarkFormal.Deployed.Poseidon2Link.row3 "
            + " ".join(f"({coefficient} : F)" for coefficient in row)
            + " "
            + " ".join(outputs)
            for row in recovery.MDS
        )
        proof.extend(
            [
                "  let raw : List.Vector F 3 := vec![",
                f"      {raw_lanes}]",
                f"  have hRaw : {trace}.state0 {prefix}Domain "
                f"({prefix}Input0 rho) ({prefix}Input1 rho) = raw := by",
                f"    unfold {trace}.state0 raw",
                "    exact Shieldd.GnarkFormal.Deployed.Poseidon2Link.fr_eq3",
                f"      (vec![{prefix}Domain, {prefix}Input0 rho, {prefix}Input1 rho])",
                f"      {trace}.roundConstants0",
                "      " + " ".join(outputs),
                "      " + " ".join(lane_facts),
                f"  have hCurrent : {trace}.state0 {prefix}Domain "
                f"({prefix}Input0 rho) ({prefix}Input1 rho) = {prefix}Endpoint0 rho := by",
                "    rw [hRaw]",
                "    unfold raw",
            ]
        )
    else:
        lanes = range(3) if rounds[gate][0] == "fr3" else range(1)
        for lane, part in zip(lanes, parts, strict=True):
            proof.extend(
                [
                    f"  have ha{lane} : rho {block.outputs[part]} =",
                    "      Shieldd.GnarkFormal.Poseidon2Bridge.p17",
                    f"        (({prefix}Endpoint{gate - 1} rho)[{lane}] +",
                    f"          ({rounds[gate][1][lane]} : F)) := by",
                    f"    rw [hp{part}, {prefix}RoundInput{part}_eq_arg]",
                ]
            )
        theorem = "fr_eq3" if rounds[gate][0] == "fr3" else "pr_eq3"
        proof.extend(
            [
                f"  have hCurrent : {trace}.state{gate} {prefix}Domain "
                f"({prefix}Input0 rho) ({prefix}Input1 rho) = "
                f"{prefix}Endpoint{gate} rho := by",
                f"    unfold {trace}.state{gate}",
                "    rw [hPrev]",
                f"    rw [Shieldd.GnarkFormal.Deployed.Poseidon2Link.{theorem}",
                f"      ({prefix}Endpoint{gate - 1} rho) {trace}.roundConstants{gate}",
                "      " + " ".join(f"(rho {block.outputs[part]})" for part in parts),
                "      " + " ".join(f"ha{lane}" for lane in lanes) + "]",
            ]
        )

    casts, lane_casts = _block_gate_casts(block, gate)
    proof.extend(casts)
    simp_items = [
        f"{prefix}Endpoint{gate}",
        "Shieldd.GnarkFormal.Deployed.Poseidon2Link.row3",
    ]
    if gate:
        simp_items.extend(
            [
                f"{trace}.roundConstants{gate}",
                f"{prefix}Endpoint{gate - 1}",
            ]
        )
    proof.extend(
        [
            "    apply List.Vector.eq",
            f"    simp [{', '.join(simp_items)}]",
        ]
    )
    if any(lane_casts):
        if not all(lane_casts):
            raise ValueError(
                f"{name} {prefix}: gate {gate} has mixed cast-free lanes"
            )
        proof.append("    constructor")
        for lane, names in enumerate(lane_casts):
            indent = "    · " if lane == 0 else "      · "
            if lane == 1:
                proof.append("    · constructor")
            proof.append(f"{indent}ring_nf")
            proof.append(f"{' ' * (len(indent) - 2)}  rw [{', '.join(names)}]")
    proof.append("  exact hCurrent")

    return f"""{GENERATED_HEADER}import ShielddGnarkFormal.Deployed.Templates.Semantics.{name}PoseidonBlock{block_index}Base
import ShielddGnarkFormal.Deployed.Templates.Relations.{name}
import ShielddGnarkFormal.Deployed.Poseidon2Link
import Mathlib.Tactic.LinearCombination
import Mathlib.Tactic.Ring

set_option maxRecDepth 1000000
set_option maxHeartbeats 10000000

namespace {namespace}

open {block_ns}
attribute [-instance] ZMod.instField
open scoped Shieldd.GnarkFormal.ChoiceFreeZMod

{part_theorems}

theorem sound (rho : Nat → F)
    (h : {relation}.relation rho){previous_binder} :
    {trace}.state{gate} {prefix}Domain ({prefix}Input0 rho)
      ({prefix}Input1 rho) = {prefix}Endpoint{gate} rho := by
{chr(10).join(proof)}

end {namespace}
"""


