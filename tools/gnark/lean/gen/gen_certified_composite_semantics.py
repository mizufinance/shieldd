def _encryption_entries(payload: dict, key_field: str) -> list[dict]:
    entries = payload.get("templates")
    if not isinstance(entries, list):
        raise ValueError("encryption template roster is not an array")
    return [entry for entry in entries if isinstance(entry, dict) and
            str(entry.get(key_field, "")).startswith("gadget.poseidon_encryption.")]


def _validate_deployment_roster(registry: dict, inventory: dict, ir: dict) -> None:
    expected = {deployment.key for deployment in DEPLOYMENTS}
    registry_entries = _encryption_entries(registry, "proof_template_id")
    inventory_entries = _encryption_entries(inventory, "template_key")
    if {entry.get("proof_template_id") for entry in registry_entries} != expected:
        raise ValueError("encryption registry key roster drifted")
    if {entry.get("template_key") for entry in inventory_entries} != expected:
        raise ValueError("encryption inventory key roster drifted")
    registry_by_key = {entry["proof_template_id"]: entry for entry in registry_entries}
    inventory_by_key = {entry["template_key"]: entry for entry in inventory_entries}
    for deployment in DEPLOYMENTS:
        digest = deployment.key.split("@", 1)[1]
        reg = registry_by_key[deployment.key]
        for field, value in (("op", deployment.op), ("row_count", deployment.rows),
                             ("local_wire_count", deployment.wires),
                             ("canonical_relation_sha256_hex", digest),
                             ("canonical_relation_file", f"proof-template-relations/{digest}.sr1cs.gz")):
            if reg.get(field) != value:
                raise ValueError(f"{deployment.key}: registry {field} drifted")
        inv = inventory_by_key[deployment.key]
        expected_instances = [{"circuit": "transfer", "segment_index": segment,
                               "constraint_count": deployment.rows,
                               "constant_vector_sha256_hex": deployment.vector,
                               "class_key": deployment.class_key}
                              for segment in deployment.segments]
        if (inv.get("op") != deployment.op or
                inv.get("normalized_relation_sha256_hex") != digest or
                inv.get("constraint_count") != deployment.rows or
                inv.get("local_wire_count") != deployment.wires or
                inv.get("circuits") != ["transfer"] or
                inv.get("distinct_constant_vectors") != 1 or
                inv.get("instances") != expected_instances or
                inv.get("representative") != {"circuit": "transfer", "segment_index": deployment.segments[0]}):
            raise ValueError(f"{deployment.key}: inventory deployment drifted")
        matches = [segment for segment in ir.get("segments", [])
                   if segment.get("proof_template_id") == deployment.key]
        if [segment.get("index") for segment in matches] != list(deployment.segments):
            raise ValueError(f"{deployment.key}: IR segment roster drifted")
        for segment in matches:
            template = compress.SegmentTemplate.parse(segment)
            seating = template.canonical_wire_seating
            if (segment.get("op") != deployment.op or
                    segment.get("constraint_count") != deployment.rows or
                    segment.get("deployed_normalized_relation_sha256_hex") != digest or
                    len(seating) != deployment.wires or seating[0] != 0 or
                    len(set(seating)) != len(seating)):
                raise ValueError(f"{deployment.key}: IR template witness drifted")


