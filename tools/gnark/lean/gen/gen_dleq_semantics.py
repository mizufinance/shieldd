#!/usr/bin/env python3
"""Generate exact semantics for the deployed Transfer DLEQ template.

The normalized DLEQ relation contains six native canonical-field
decompositions, two joint double-base scalar ladders, five embedded Decaf
compression gadgets, one rate-7 Poseidon transcript, and the regulated
challenge comparison.  This generator fails closed on every recovered
boundary and emits proofs against the exact normalized relation; no wire
transport assumption survives into Lean.
"""

from __future__ import annotations

import argparse
import re
from functools import cache
from pathlib import Path

import composite_recovery as recovery
import dtk_recovery as dtk
from write_if_changed import write_if_changed


ROOT = Path(__file__).resolve().parents[4]
LEAN = ROOT / "tools/gnark/lean"
FORMAL = LEAN / "ShielddGnarkFormal"
RELATIONS = FORMAL / "Deployed/Templates/Relations"
OUT = FORMAL / "Deployed/Templates/Semantics"

DIGEST = recovery.DLEQ_DIGEST
NAME = f"TGadgetDleq_{DIGEST}"
RELATION = (
    "Shieldd.GnarkFormal.Deployed.Templates.Relations." + NAME
)
RELATION_MODULE = RELATION.replace(
    "Shieldd.GnarkFormal", "ShielddGnarkFormal"
)
NAMESPACE = (
    "Shieldd.GnarkFormal.Deployed.Templates.Semantics." + NAME
)
MODULE_PREFIX = (
    "ShielddGnarkFormal.Deployed.Templates.Semantics." + NAME
)
VIRTUAL_COMPUTED_CHALLENGE = 20000

GENERATED_HEADER = """/-
GENERATED by gen/gen_dleq_semantics.py — do not edit by hand.
-/
"""


@cache
def _relation_source() -> str:
    shards = sorted(
        RELATIONS.glob(f"{NAME}Defs*.lean"),
        key=lambda path: int(path.stem.removeprefix(NAME + "Defs")),
    )
    facade = RELATIONS / f"{NAME}.lean"
    if not shards or not facade.is_file():
        raise ValueError("DLEQ exact normalized relation is missing")
    indices = [
        int(path.stem.removeprefix(NAME + "Defs")) for path in shards
    ]
    if indices != list(range(len(indices))):
        raise ValueError("DLEQ relation shards are not contiguous")
    source = "\n".join(path.read_text() for path in (*shards, facade))
    rows = {
        int(value)
        for value in re.findall(r"\bdef relationRow(\d+) ", source)
    }
    if rows != set(range(17834)):
        raise ValueError("DLEQ normalized row definitions drifted")
    return source


def _relation_parts(source: str) -> tuple[tuple[int, ...], ...]:
    result: list[tuple[int, ...]] = []
    for match in re.finditer(
        r"def relationPart(\d+) \(rho : Nat -> F\) : Prop :=\n"
        r"(.*?)(?=\n\ndef relationPart|\n\ndef relation \()",
        source,
        re.S,
    ):
        index = int(match.group(1))
        if index != len(result):
            raise ValueError(f"DLEQ relation part {index} is non-contiguous")
        result.append(
            tuple(
                int(row)
                for row in re.findall(
                    r"\brelationRow(\d+) rho", match.group(2)
                )
            )
        )
    if [row for part in result for row in part] != list(range(17834)):
        raise ValueError("DLEQ relation parts do not cover rows exactly")
    return tuple(result)


def _relation_rows(source: str) -> dict[int, str]:
    result = {
        int(match.group(1)): match.group(2)
        for match in re.finditer(
            r"def relationRow(\d+) \(rho : Nat -> F\) : Prop :=\n"
            r"(.*?)(?=\n\ndef |\nend )",
            source,
            re.S,
        )
    }
    if set(result) != set(range(17834)):
        raise ValueError("DLEQ relation row bodies drifted")
    return result


def _lc(value: tuple[tuple[int, int], ...]) -> str:
    terms: list[str] = []
    for wire, coefficient in value:
        if wire == 0:
            terms.append(f"({coefficient} : F)")
        else:
            terms.append(f"({coefficient} : F) * rho {wire}")
    return " + ".join(terms) if terms else "(0 : F)"


def _computed_challenge_lc() -> tuple[tuple[int, int], ...]:
    rows = recovery.rows(DIGEST)
    value = recovery._canonical_block(rows, 16822, 14286)
    frozen = tuple(sorted(value.items()))
    expected_wires = tuple(range(13911, 13947, 5))
    if tuple(wire for wire, _ in frozen) != expected_wires:
        raise ValueError("DLEQ computed challenge endpoint drifted")
    return frozen


def _canonical_base() -> str:
    definitions: list[str] = []
    for index, base in enumerate(
        (11, 351, 4984, 5323, 13947, 14286), start=1
    ):
        definitions.extend(
            [
                f"def canon{index}Bits (rho : Nat → F) : "
                "List.Vector "
                "Shieldd.GnarkFormal.Extracted.CanonicalFqBits.F 253 :=\n"
                f"  List.Vector.ofFn "
                f"(fun i : Fin 253 => rho ({base} + i.val))",
                f"theorem canon{index}Bits_get "
                "(rho : Nat → F) (i : Nat) (hi : i < 253) :\n"
                f"    (canon{index}Bits rho)[i]! = "
                f"rho ({base} + i) := by\n"
                "  rw [getElem!_pos _ i (by simpa using hi)]\n"
                "  conv_lhs => rw [List.Vector.getElem_def]\n"
                f"  simp only [canon{index}Bits, "
                "List.Vector.toList_ofFn, List.getElem_ofFn]",
            ]
        )
    return f"""{GENERATED_HEADER}import {RELATION_MODULE}
import ShielddGnarkFormal.Deployed.PrimeOrder
import ShielddGnarkFormal.Extracted.CanonicalFqBits

set_option maxRecDepth 1000000
set_option maxHeartbeats 20000000

namespace {NAMESPACE}.Canonical

abbrev F := {RELATION}.F

local instance : Fact (Nat.Prime {RELATION}.Order) :=
  ⟨Shieldd.GnarkFormal.Deployed.decaf377ScalarFieldPrime⟩

def computedChallenge (rho : Nat → F) : F :=
  {_lc(_computed_challenge_lc())}

{chr(10).join(definitions)}

end {NAMESPACE}.Canonical
"""


def _rewrite_canonical(
    source: str, index: int, computed_challenge: str
) -> str:
    old_namespace = (
        "Shieldd.GnarkFormal.Deployed.Contracts.NoteReshape2x1"
    )
    old_module = (
        "ShielddGnarkFormal.Deployed.Contracts.NoteReshape2x1"
    )
    component = f"{NAME}Canon{index}"
    source = source.replace(
        f"{old_module}.DtkAdapterSeg6Canon1",
        f"{MODULE_PREFIX}Canon{index}",
    )
    source = source.replace(
        f"{old_module}.DtkAdapterSeg6Base",
        f"{MODULE_PREFIX}CanonBase",
    )
    source = source.replace(
        f"{old_module}.CompressAdapterCommon",
        "ShielddGnarkFormal.Deployed.Templates.Semantics."
        "BinaryRecomposition",
    )
    source = source.replace(
        f"{old_module}.Seg6", RELATION_MODULE
    )
    source = source.replace(
        f"namespace {old_namespace}",
        f"namespace {NAMESPACE}.Canonical",
    ).replace(
        f"end {old_namespace}",
        f"end {NAMESPACE}.Canonical",
    )
    source = source.replace("Seg6.F", "F")
    source = source.replace("Seg6.", RELATION + ".")
    source = source.replace(
        "DtkAdapterSeg6Canon1", component
    )
    source = source.replace("seg6Canon1", f"canon{index}")
    source = re.sub(
        rf"\brho {VIRTUAL_COMPUTED_CHALLENGE}\b",
        computed_challenge,
        source,
    )
    forbidden = (
        "NoteReshape2x1",
        "DtkAdapter",
        "Seg6.",
        "seg6Canon",
        f"rho {VIRTUAL_COMPUTED_CHALLENGE}",
    )
    leaked = [marker for marker in forbidden if marker in source]
    if leaked:
        raise ValueError(
            f"DLEQ canonical provider leaked transport names: {leaked}"
        )
    if not source.startswith(GENERATED_HEADER):
        source = GENERATED_HEADER + source
    return source


def _canonical_outputs(out: Path) -> dict[Path, str]:
    exact_source = _relation_source()
    exact_parts = _relation_parts(exact_source)
    exact_rows = _relation_rows(exact_source)
    cfg = dtk.Instance(
        seg=6,
        internal_base=dtk.BASE_INTERNAL,
        div_x=1,
        div_y=2,
        following_seg=7,
        wire_seating=tuple(range(VIRTUAL_COMPUTED_CHALLENGE + 1)),
    )
    blocks = (
        dtk.CanonicalBlock("Canon1", 264, 11, 8, 261, 262),
        dtk.CanonicalBlock("Canon1", 604, 351, 514, 767, 768),
        dtk.CanonicalBlock("Canon1", 264, 4984, 5313, 5566, 5567),
        dtk.CanonicalBlock("Canon1", 604, 5323, 5819, 6072, 6073),
        dtk.CanonicalBlock("Canon1", 604, 13947, 16316, 16569, 16570),
        dtk.CanonicalBlock(
            "Canon1",
            VIRTUAL_COMPUTED_CHALLENGE,
            14286,
            16822,
            17075,
            17076,
        ),
    )
    old_source = dtk.source
    old_relation_parts = dtk.relation_parts
    old_relation_rows = dtk.relation_rows
    old_row_count = dtk.ROW_COUNT
    old_source_cache = dict(dtk._SOURCE_CACHE)
    old_parts_cache = dict(dtk._RELATION_PARTS_CACHE)
    computed = f"computedChallenge rho"
    try:
        dtk.source = (
            lambda seg: exact_source if seg == cfg.seg
            else old_source(seg)
        )
        dtk.relation_parts = (
            lambda seg: [list(part) for part in exact_parts]
            if seg == cfg.seg
            else old_relation_parts(seg)
        )
        dtk.relation_rows = (
            lambda seg: dict(exact_rows)
            if seg == cfg.seg
            else old_relation_rows(seg)
        )
        dtk.ROW_COUNT = 17834
        dtk._SOURCE_CACHE.clear()
        dtk._RELATION_PARTS_CACHE.clear()
        rendered: dict[str, str] = {}
        for index, block in enumerate(blocks, start=1):
            component = "DtkAdapterSeg6Canon1"
            rendered[f"Canon{index}Rec"] = dtk.emit_canon_recover(
                cfg, block, None
            )
            rendered[f"Canon{index}Binary"] = dtk.emit_canon_binary(
                cfg, block, f"{component}Rec"
            )
            rendered[f"Canon{index}TrueDefs"] = (
                dtk.emit_canon_true_defs(
                    cfg, block, exact_rows, f"{component}Binary"
                )
            )
            previous_true = f"{component}TrueDefs"
            for chunk_index, _ in enumerate(dtk.canon_chunks()):
                key = f"Canon{index}TrueChunk{chunk_index}"
                rendered[key] = dtk.emit_canon_true_chunk(
                    cfg,
                    block,
                    exact_rows,
                    previous_true,
                    chunk_index,
                )
                previous_true = f"{component}TrueChunk{chunk_index}"
            rendered[f"Canon{index}True"] = (
                dtk.emit_canon_true_thread(
                    cfg, block, previous_true
                )
            )
            previous_compare = f"{component}True"
            for chunk_index, _ in enumerate(dtk.canon_chunks()):
                key = f"Canon{index}CompareChunk{chunk_index}"
                rendered[key] = dtk.emit_canon_compare_chunk(
                    cfg,
                    block,
                    exact_rows,
                    previous_compare,
                    chunk_index,
                )
                previous_compare = (
                    f"{component}CompareChunk{chunk_index}"
                )
            rendered[f"Canon{index}Compare"] = (
                dtk.emit_canon_compare(
                    cfg, block, previous_compare
                )
            )
            rendered[f"Canon{index}Chain"] = dtk.emit_canon_chain(
                cfg, block, f"{component}Compare"
            )
            rendered[f"Canon{index}"] = dtk.emit_canon_block(
                cfg,
                block=block,
                previous=f"{component}Chain",
            )
    finally:
        dtk.source = old_source
        dtk.relation_parts = old_relation_parts
        dtk.relation_rows = old_relation_rows
        dtk.ROW_COUNT = old_row_count
        dtk._SOURCE_CACHE.clear()
        dtk._SOURCE_CACHE.update(old_source_cache)
        dtk._RELATION_PARTS_CACHE.clear()
        dtk._RELATION_PARTS_CACHE.update(old_parts_cache)
        dtk.wire_inverse.cache_clear()

    outputs = {out / f"{NAME}CanonBase.lean": _canonical_base()}
    for suffix, source in rendered.items():
        index = int(re.match(r"Canon(\d+)", suffix).group(1))
        outputs[out / f"{NAME}{suffix}.lean"] = _rewrite_canonical(
            source, index, computed
        )
    return outputs


@cache
def generated_files(out: Path = OUT) -> dict[Path, str]:
    # Running recovery here makes generation fail before materialization if
    # any DLEQ boundary or exact row ownership changes.
    recovery.recover_dleq()
    outputs = _canonical_outputs(out)
    if len(outputs) != 235:
        raise ValueError(
            f"expected 235 DLEQ canonical modules, got {len(outputs)}"
        )
    return outputs


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs = generated_files()
    if args.check:
        stale = [
            str(path)
            for path, source in outputs.items()
            if not path.is_file() or path.read_text() != source
        ]
        if stale:
            raise SystemExit(
                "stale DLEQ semantic providers:\n"
                + "\n".join(stale)
            )
        return
    for path, source in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        if write_if_changed(path, source):
            print(f"wrote {path}")


if __name__ == "__main__":
    main()
