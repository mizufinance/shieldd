def render(config: Config) -> str:
    roles = discover(config)
    source = TEMPLATE.read_text(encoding="utf-8")
    replacements = {
        "@@MODULE@@": config.module,
        "@@FAMILY@@": config.family,
        "@@DIV_SEG@@": str(roles.div_compress["index"]),
        "@@DIV_TEMPLATE@@": DIV_TEMPLATE,
        "@@TRANSMISSION_SEG@@": str(
            roles.transmission_compress["index"]
        ),
        "@@TRANSMISSION_TEMPLATE@@": TRANSMISSION_TEMPLATE,
        "@@ENCODING_SEAMS@@": render_encoding_seams(config, roles),
        "@@CANONICAL_FACTS@@": render_facts(config, roles),
    }
    for marker, value in replacements.items():
        if marker not in source:
            raise ValueError(
                f"{config.circuit}: canonical template is missing {marker}"
            )
        source = source.replace(marker, value)
    if "@@" in source:
        raise ValueError(
            f"{config.circuit}: unresolved canonical template marker"
        )
    expected_markers = (
        "authIvkReducedNonzero_of_exact",
        "sharedTransmissionComputedNonIdentity_of_exact",
        "transmissionKeyNonIdentity",
        "Decaf377Assumptions.onCurve_of_compress",
    )
    if any(marker not in source for marker in expected_markers):
        raise ValueError(f"{config.circuit}: canonical closure drifted")
    if "DecafAssertOnCurveSeg" in source:
        raise ValueError(
            f"{config.circuit}: claimed-balance on-curve fact leaked into "
            "the canonical address proof"
        )
    return GENERATED_HEADER + source


def check_generated(path: Path, expected: str) -> None:
    if not path.is_file() or path.read_text(encoding="utf-8") != expected:
        raise SystemExit(f"generated file is stale: {path}")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "circuits",
        nargs="*",
        choices=[config.circuit for config in CONFIGS],
    )
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    selected = set(args.circuits) if args.circuits else {
        config.circuit for config in CONFIGS
    }
    for config in CONFIGS:
        if config.circuit not in selected:
            continue
        expected = render(config)
        if args.check:
            check_generated(config.output, expected)
        elif write_if_changed(config.output, expected):
            print(config.output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
