from __future__ import annotations

import hashlib
import tempfile
import unittest
from pathlib import Path
from unittest import mock

import gen_note_reshape_1x8_statement_seating as statement


class NoteReshape1x8StatementSeatingTests(unittest.TestCase):
    def test_discovers_authenticated_statement_seam(self) -> None:
        roles = statement.discover()

        self.assertEqual(
            (roles.statement["index"], roles.assertion["index"]),
            (79, 80),
        )
        self.assertEqual(
            (
                roles.statement["proof_template_id"],
                roles.assertion["proof_template_id"],
            ),
            (statement.HASH_TEMPLATE, statement.ASSERT_TEMPLATE),
        )
        self.assertEqual(
            {
                roles.statement_seating[local]
                for local in (
                    *statement.FIRST_A_LOCALS,
                    *statement.FIRST_B_LOCALS,
                    *statement.SECOND_LOCALS,
                    *statement.THIRD_LOCALS,
                )
            },
            set(roles.statement["wire_roles"]["input"]),
        )
        self.assertEqual(
            {
                roles.statement_seating[local]
                for local in statement.HASH_OUTPUT_LOCALS
            },
            set(roles.statement["wire_roles"]["output"]),
        )

    def test_outputs_are_exact_and_have_no_retired_segment_imports(self) -> None:
        rendered = statement.outputs()

        self.assertEqual(
            {path.name for path in rendered},
            {
                "NoteReshape1x8StatementSeatingFirstA.lean",
                "NoteReshape1x8StatementSeatingFirstB.lean",
                "NoteReshape1x8StatementSeatingSecond.lean",
                "NoteReshape1x8StatementSeatingThird.lean",
                "NoteReshape1x8StatementSeatingOutput.lean",
            },
        )
        combined = "\n".join(rendered.values())
        for retired in ("Seg57", "Seg58", "Seg59"):
            self.assertNotIn(retired, combined)
        self.assertIn(
            "theorem hw7 : Seg79.wireSeating 7 = 32820 "
            ":= by decide +kernel",
            combined,
        )
        self.assertIn(
            "theorem hw1000 : Seg79.wireSeating 1000 = 5 "
            ":= by decide +kernel",
            combined,
        )
        self.assertIn(
            "theorem hw1 : Seg80.wireSeating 1 = 40601 "
            ":= by decide +kernel",
            combined,
        )
        self.assertIn(
            "theorem hw9 : Seg80.wireSeating 9 = 1 "
            ":= by decide +kernel",
            combined,
        )
        self.assertEqual(
            combined.count(
                "GENERATED by "
                "gen_note_reshape_1x8_statement_seating.py — do not edit."
            ),
            5,
        )

    def test_exact_check_rejects_generated_theorem_mutation(self) -> None:
        expected = next(iter(statement.outputs().values()))
        mutated = expected.replace(
            "theorem hw1", "theorem hw1_mutated", 1
        )
        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory) / "Seating.lean"
            path.write_text(mutated)
            with self.assertRaisesRegex(
                SystemExit, "generated file is stale"
            ):
                statement.check_generated(path, expected)

    def test_reviewed_consumers_are_complete_and_digest_pinned(self) -> None:
        self.assertEqual(
            set(statement.REVIEWED_CONSUMER_DIGESTS),
            {
                "NoteReshape1x8StatementFirst.lean",
                "NoteReshape1x8StatementSecond.lean",
                "NoteReshape1x8StatementThird.lean",
                "NoteReshape1x8StatementOutput.lean",
                "NoteReshape1x8TranscriptSeams.lean",
            },
        )
        for filename, expected in (
            statement.REVIEWED_CONSUMER_DIGESTS.items()
        ):
            actual = hashlib.sha256(
                (statement.DEPLOYED / filename).read_bytes()
            ).hexdigest()
            self.assertEqual(actual, expected)
        statement.validate_consumers()

    def test_reviewed_consumer_mutation_is_rejected(self) -> None:
        roles = statement.discover()
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            for filename in statement.REVIEWED_CONSUMER_DIGESTS:
                source = statement.DEPLOYED / filename
                (root / filename).write_bytes(source.read_bytes())
            target = root / "NoteReshape1x8StatementFirst.lean"
            target.write_text(
                target.read_text().replace(
                    "theorem hash", "theorem hash_mutated", 1
                )
            )
            with mock.patch.object(statement, "DEPLOYED", root):
                with self.assertRaisesRegex(ValueError, "digest drifted"):
                    statement.validate_consumers(roles)


if __name__ == "__main__":
    unittest.main()
