func runExportPoseidonACL2(args []string) error {
	fs := flag.NewFlagSet("export-poseidon-acl2", flag.ContinueOnError)
	outPath := fs.String("out", "", "output ACL2 Poseidon377 spec book")
	if err := fs.Parse(args); err != nil {
		return err
	}
	if *outPath == "" {
		return fmt.Errorf("--out is required")
	}
	if err := os.MkdirAll(filepath.Dir(*outPath), 0o755); err != nil {
		return fmt.Errorf("create output dir: %w", err)
	}

	vectors, err := primitives.LoadPrototypeVectors()
	if err != nil {
		return fmt.Errorf("load prototype vectors: %w", err)
	}

	file, err := os.Create(*outPath)
	if err != nil {
		return fmt.Errorf("create poseidon ACL2 spec: %w", err)
	}
	defer file.Close()
	writer := bufio.NewWriter(file)
	if err := writePoseidonACL2(writer, vectors.Poseidon377); err != nil {
		return err
	}
	if err := writer.Flush(); err != nil {
		return err
	}
	fmt.Fprintf(os.Stderr, "wrote %s\n", *outPath)
	return nil
}

func writePoseidonACL2(w io.Writer, vectors primitives.PoseidonVectors) error {
	rates := []primitives.PoseidonRateVectors{
		vectors.Rate1,
		vectors.Rate2,
		vectors.Rate3,
		vectors.Rate4,
		vectors.Rate5,
		vectors.Rate6,
		vectors.Rate7,
	}
	for i, rate := range rates {
		if got, want := rate.Rate, i+1; got != want {
			return fmt.Errorf("poseidon rate slot %d has rate %d", i+1, got)
		}
		if rate.Alpha != 17 {
			return fmt.Errorf("poseidon rate %d alpha %d != 17", rate.Rate, rate.Alpha)
		}
		if rate.FullRounds != 8 || rate.PartialRounds != 31 {
			return fmt.Errorf("poseidon rate %d rounds full=%d partial=%d", rate.Rate, rate.FullRounds, rate.PartialRounds)
		}
		if rate.Width != rate.Rate+1 {
			return fmt.Errorf("poseidon rate %d width %d != rate+1", rate.Rate, rate.Width)
		}
		if len(rate.MDS) != rate.Width*rate.Width {
			return fmt.Errorf("poseidon rate %d mds length %d != width^2", rate.Rate, len(rate.MDS))
		}
		if len(rate.ARC) != rate.Width*(rate.FullRounds+rate.PartialRounds) {
			return fmt.Errorf("poseidon rate %d arc length %d != width*rounds", rate.Rate, len(rate.ARC))
		}
	}

	hash2Out, err := primitives.Poseidon377Hash2Native(
		primitives.MustBigInt(vectors.IVKDomain),
		[2]*big.Int{big.NewInt(7), big.NewInt(11)},
	)
	if err != nil {
		return err
	}
	hash3Out, err := primitives.Poseidon377Hash3Native(
		primitives.MustBigInt(vectors.NullifierDomain),
		[3]*big.Int{big.NewInt(3), big.NewInt(5), big.NewInt(9)},
	)
	if err != nil {
		return err
	}

	lines := []string{
		"; Generated by gnarkctl export-poseidon-acl2.",
		"; Poseidon377 parameters and executable spec are derived from phase05_vectors.json.",
		"; Do not edit by hand.",
		"",
		"(in-package \"R1CS\")",
		"",
		"(include-book \"kestrel/prime-fields/prime-fields\" :dir :system)",
		"",
		"(defconst *poseidon377-prime*",
		"  8444461749428370424248824938781546531375899335154063827935233455917409239041)",
		"",
		"(defund poseidon377-pow17 (x)",
		"  (let* ((x2 (pfield::mul x x *poseidon377-prime*))",
		"         (x4 (pfield::mul x2 x2 *poseidon377-prime*))",
		"         (x8 (pfield::mul x4 x4 *poseidon377-prime*))",
		"         (x16 (pfield::mul x8 x8 *poseidon377-prime*)))",
		"    (pfield::mul x16 x *poseidon377-prime*)))",
		"",
		"(defund poseidon377-add-constants (st constants)",
		"  (if (endp st)",
		"      nil",
		"    (cons (pfield::add (car st) (car constants) *poseidon377-prime*)",
		"          (poseidon377-add-constants (cdr st) (cdr constants)))))",
		"",
		"(defund poseidon377-sbox-full (st)",
		"  (if (endp st)",
		"      nil",
		"    (cons (poseidon377-pow17 (car st))",
		"          (poseidon377-sbox-full (cdr st)))))",
		"",
		"(defund poseidon377-sbox-partial (st)",
		"  (if (endp st)",
		"      nil",
		"    (cons (poseidon377-pow17 (car st)) (cdr st))))",
		"",
		"(defund poseidon377-dot (row st)",
		"  (if (endp row)",
		"      0",
		"    (pfield::add (pfield::mul (car row) (car st) *poseidon377-prime*)",
		"                 (poseidon377-dot (cdr row) (cdr st))",
		"                 *poseidon377-prime*)))",
		"",
		"(defund poseidon377-mix (mds st)",
		"  (if (endp mds)",
		"      nil",
		"    (cons (poseidon377-dot (car mds) st)",
		"          (poseidon377-mix (cdr mds) st))))",
		"",
		"(defund poseidon377-take (n xs)",
		"  (declare (xargs :measure (nfix n)))",
		"  (if (zp n)",
		"      nil",
		"    (cons (car xs) (poseidon377-take (1- n) (cdr xs)))))",
		"",
		"(defund poseidon377-drop (n xs)",
		"  (declare (xargs :measure (nfix n)))",
		"  (if (zp n)",
		"      xs",
		"    (poseidon377-drop (1- n) (cdr xs))))",
		"",
		"(defund poseidon377-full-round-step (st arc mds)",
		"  (let* ((width (len st))",
		"         (round-constants (poseidon377-take width arc))",
		"         (rest-arc (poseidon377-drop width arc))",
		"         (state1 (poseidon377-add-constants st round-constants))",
		"         (state2 (poseidon377-sbox-full state1))",
		"         (state3 (poseidon377-mix mds state2)))",
		"    (cons state3 rest-arc)))",
		"",
		"(defund poseidon377-partial-round-step (st arc mds)",
		"  (let* ((width (len st))",
		"         (round-constants (poseidon377-take width arc))",
		"         (rest-arc (poseidon377-drop width arc))",
		"         (state1 (poseidon377-add-constants st round-constants))",
		"         (state2 (poseidon377-sbox-partial state1))",
		"         (state3 (poseidon377-mix mds state2)))",
		"    (cons state3 rest-arc)))",
		"",
		"(defund poseidon377-full-rounds (n st arc mds)",
		"  (declare (xargs :measure (nfix n)))",
		"  (if (zp n)",
		"      (cons st arc)",
		"    (let ((step (poseidon377-full-round-step st arc mds)))",
		"      (poseidon377-full-rounds (1- n) (car step) (cdr step) mds))))",
		"",
		"(defund poseidon377-partial-rounds (n st arc mds)",
		"  (declare (xargs :measure (nfix n)))",
		"  (if (zp n)",
		"      (cons st arc)",
		"    (let ((step (poseidon377-partial-round-step st arc mds)))",
		"      (poseidon377-partial-rounds (1- n) (car step) (cdr step) mds))))",
		"",
		"(defund poseidon377-permute (full-half partial st arc mds)",
		"  (let* ((first (poseidon377-full-rounds full-half st arc mds))",
		"         (middle (poseidon377-partial-rounds partial (car first) (cdr first) mds))",
		"         (last (poseidon377-full-rounds full-half (car middle) (cdr middle) mds)))",
		"    (car last)))",
		"",
	}
	for _, line := range lines {
		if _, err := fmt.Fprintln(w, line); err != nil {
			return err
		}
	}

	for _, rate := range rates {
		if err := writePoseidonRateConstants(w, rate); err != nil {
			return err
		}
	}

	for _, rate := range rates {
		if err := writePoseidonHashFunction(w, rate.Rate); err != nil {
			return err
		}
		if err := writePoseidonAxeHashFunction(w, rate); err != nil {
			return err
		}
		if err := writePoseidonR1CSAxeHashFunction(w, rate); err != nil {
			return err
		}
	}

	vectorLines := []string{
		"(assert-event",
		fmt.Sprintf(" (equal (poseidon377-hash7 %s %s)", vectors.Hash7Domain, acl2Args(vectors.Hash7Inputs)),
		fmt.Sprintf("        %s))", vectors.Hash7Output),
		"",
		"(assert-event",
		fmt.Sprintf(" (equal (poseidon377-hash7-axe %s %s)", vectors.Hash7Domain, acl2Args(vectors.Hash7Inputs)),
		fmt.Sprintf("        %s))", vectors.Hash7Output),
		"",
		"(assert-event",
		fmt.Sprintf(" (equal (poseidon377-hash7-r1cs-axe %s %s)", vectors.Hash7Domain, acl2Args(vectors.Hash7Inputs)),
		fmt.Sprintf("        %s))", vectors.Hash7Output),
		"",
		"(assert-event",
		fmt.Sprintf(" (equal (poseidon377-hash2 %s 7 11)", vectors.IVKDomain),
		fmt.Sprintf("        %s))", hash2Out.String()),
		"",
		"(assert-event",
		fmt.Sprintf(" (equal (poseidon377-hash2-axe %s 7 11)", vectors.IVKDomain),
		fmt.Sprintf("        %s))", hash2Out.String()),
		"",
		"(assert-event",
		fmt.Sprintf(" (equal (poseidon377-hash2-r1cs-axe %s 7 11)", vectors.IVKDomain),
		fmt.Sprintf("        %s))", hash2Out.String()),
		"",
		"(assert-event",
		fmt.Sprintf(" (equal (poseidon377-hash3 %s 3 5 9)", vectors.NullifierDomain),
		fmt.Sprintf("        %s))", hash3Out.String()),
		"",
		"(assert-event",
		fmt.Sprintf(" (equal (poseidon377-hash3-axe %s 3 5 9)", vectors.NullifierDomain),
		fmt.Sprintf("        %s))", hash3Out.String()),
		"",
		"(assert-event",
		fmt.Sprintf(" (equal (poseidon377-hash3-r1cs-axe %s 3 5 9)", vectors.NullifierDomain),
		fmt.Sprintf("        %s))", hash3Out.String()),
		"",
	}
	for _, line := range vectorLines {
		if _, err := fmt.Fprintln(w, line); err != nil {
			return err
		}
	}
	return nil
}

func writePoseidonRateConstants(w io.Writer, rate primitives.PoseidonRateVectors) error {
	if _, err := fmt.Fprintf(w, "(defconst *poseidon377-rate-%d-mds*\n  '", rate.Rate); err != nil {
		return err
	}
	if err := writeACL2Matrix(w, rate.MDS, rate.Width, "   "); err != nil {
		return err
	}
	if _, err := fmt.Fprintln(w, ")"); err != nil {
		return err
	}
	if _, err := fmt.Fprintln(w); err != nil {
		return err
	}

	if _, err := fmt.Fprintf(w, "(defconst *poseidon377-rate-%d-arc*\n  '", rate.Rate); err != nil {
		return err
	}
	if err := writeACL2List(w, rate.ARC, "   "); err != nil {
		return err
	}
	if _, err := fmt.Fprintln(w, ")"); err != nil {
		return err
	}
	_, err := fmt.Fprintln(w)
	return err
}

func writePoseidonHashFunction(w io.Writer, rate int) error {
	params := make([]string, 0, rate+1)
	params = append(params, "domain")
	st := make([]string, 0, rate+1)
	st = append(st, "domain")
	for i := 0; i < rate; i++ {
		name := fmt.Sprintf("in%d", i)
		params = append(params, name)
		st = append(st, name)
	}
	_, err := fmt.Fprintf(
		w,
		"(defund poseidon377-hash%d (%s)\n  (cadr (poseidon377-permute 4 31 (list %s) *poseidon377-rate-%d-arc* *poseidon377-rate-%d-mds*)))\n\n",
		rate,
		joinSpace(params),
		joinSpace(st),
		rate,
		rate,
	)
	return err
}

func writePoseidonAxeHashFunction(w io.Writer, rate primitives.PoseidonRateVectors) error {
	params := make([]string, 0, rate.Rate+1)
	params = append(params, "domain")
	state := make([]string, 0, rate.Width)
	state = append(state, "domain")
	for i := 0; i < rate.Rate; i++ {
		name := fmt.Sprintf("in%d", i)
		params = append(params, name)
		state = append(state, name)
	}

	if _, err := fmt.Fprintf(w, "(defund poseidon377-hash%d-axe (%s)\n  (let* (\n", rate.Rate, joinSpace(params)); err != nil {
		return err
	}

	boundNames := make([]string, 0, (rate.FullRounds+rate.PartialRounds)*rate.Width*3)
	totalRounds := rate.FullRounds + rate.PartialRounds
	fullHalf := rate.FullRounds / 2
	for round := 0; round < totalRounds; round++ {
		isFull := round < fullHalf || round >= fullHalf+rate.PartialRounds
		sbox := make([]string, rate.Width)
		for i := 0; i < rate.Width; i++ {
			addName := fmt.Sprintf("r%d-a%d", round, i)
			boundNames = append(boundNames, addName)
			constant := rate.ARC[round*rate.Width+i]
			if _, err := fmt.Fprintf(w, "         (%s (pfield::add %s %s *poseidon377-prime*))\n", addName, state[i], constant); err != nil {
				return err
			}
			if isFull || i == 0 {
				powName := fmt.Sprintf("r%d-s%d", round, i)
				boundNames = append(boundNames, powName)
				if _, err := fmt.Fprintf(w, "         (%s (poseidon377-pow17 %s))\n", powName, addName); err != nil {
					return err
				}
				sbox[i] = powName
			} else {
				sbox[i] = addName
			}
		}

		next := make([]string, rate.Width)
		for row := 0; row < rate.Width; row++ {
			mixName := fmt.Sprintf("r%d-m%d", round, row)
			boundNames = append(boundNames, mixName)
			terms := make([]string, 0, rate.Width)
			for col := 0; col < rate.Width; col++ {
				terms = append(terms, fieldMulConst(rate.MDS[row*rate.Width+col], sbox[col]))
			}
			if _, err := fmt.Fprintf(w, "         (%s %s)\n", mixName, fieldAddExpr(terms)); err != nil {
				return err
			}
			next[row] = mixName
		}
		state = next
	}

	if _, err := fmt.Fprintln(w, "         )"); err != nil {
		return err
	}
	if err := writeIgnorableDecl(w, boundNames); err != nil {
		return err
	}
	_, err := fmt.Fprintf(w, "    %s))\n\n", state[1])
	return err
}

type acl2LinearExpr struct {
	constant *big.Int
	coeffs   map[string]*big.Int
}

func newACL2LinearExpr() acl2LinearExpr {
	return acl2LinearExpr{
		constant: new(big.Int),
		coeffs:   map[string]*big.Int{},
	}
}

func acl2LinearVar(name string) acl2LinearExpr {
	expr := newACL2LinearExpr()
	expr.coeffs[name] = big.NewInt(1)
	return expr
}

func (e acl2LinearExpr) clone() acl2LinearExpr {
	out := newACL2LinearExpr()
	out.constant.Set(e.constant)
	for name, coeff := range e.coeffs {
		out.coeffs[name] = new(big.Int).Set(coeff)
	}
	return out
}

func (e acl2LinearExpr) addConstant(value *big.Int, modulus *big.Int) acl2LinearExpr {
	out := e.clone()
	out.constant.Add(out.constant, value)
	out.constant.Mod(out.constant, modulus)
	return out
}

func (e acl2LinearExpr) scale(value *big.Int, modulus *big.Int) acl2LinearExpr {
	out := newACL2LinearExpr()
	out.constant.Mul(e.constant, value)
	out.constant.Mod(out.constant, modulus)
	for name, coeff := range e.coeffs {
		scaled := new(big.Int).Mul(coeff, value)
		scaled.Mod(scaled, modulus)
		if scaled.Sign() != 0 {
			out.coeffs[name] = scaled
		}
	}
	return out
}

func addACL2LinearExprs(modulus *big.Int, exprs ...acl2LinearExpr) acl2LinearExpr {
	out := newACL2LinearExpr()
	for _, expr := range exprs {
		out.constant.Add(out.constant, expr.constant)
		out.constant.Mod(out.constant, modulus)
		for name, coeff := range expr.coeffs {
			current, ok := out.coeffs[name]
			if !ok {
				current = new(big.Int)
				out.coeffs[name] = current
			}
			current.Add(current, coeff)
			current.Mod(current, modulus)
			if current.Sign() == 0 {
				delete(out.coeffs, name)
			}
		}
	}
	return out
}

func writePoseidonR1CSAxeHashFunction(w io.Writer, rate primitives.PoseidonRateVectors) error {
	modulus := new(big.Int).Set(primitives.ScalarField())
	params := make([]string, 0, rate.Rate+1)
	params = append(params, "domain")
	state := make([]acl2LinearExpr, 0, rate.Width)
	state = append(state, acl2LinearVar("domain"))
	basisOrder := []string{"domain"}
	for i := 0; i < rate.Rate; i++ {
		name := fmt.Sprintf("in%d", i)
		params = append(params, name)
		state = append(state, acl2LinearVar(name))
		basisOrder = append(basisOrder, name)
	}

	if _, err := fmt.Fprintf(w, "(defund poseidon377-hash%d-r1cs-axe (%s)\n  (let* (\n", rate.Rate, joinSpace(params)); err != nil {
		return err
	}

	boundNames := make([]string, 0, (rate.FullRounds+rate.PartialRounds)*rate.Width)
	totalRounds := rate.FullRounds + rate.PartialRounds
	fullHalf := rate.FullRounds / 2
	for round := 0; round < totalRounds; round++ {
		isFull := round < fullHalf || round >= fullHalf+rate.PartialRounds
		sboxState := make([]acl2LinearExpr, rate.Width)
		for i := 0; i < rate.Width; i++ {
			withConstant := state[i].addConstant(primitives.MustBigInt(rate.ARC[round*rate.Width+i]), modulus)
			if isFull || i == 0 {
				name := fmt.Sprintf("r%d-x%d", round, i)
				boundNames = append(boundNames, name)
				if _, err := fmt.Fprintf(w, "         (%s (poseidon377-pow17 %s))\n", name, acl2LinearExprString(withConstant, basisOrder)); err != nil {
					return err
				}
				basisOrder = append(basisOrder, name)
				sboxState[i] = acl2LinearVar(name)
			} else {
				sboxState[i] = withConstant
			}
		}

		next := make([]acl2LinearExpr, rate.Width)
		for row := 0; row < rate.Width; row++ {
			terms := make([]acl2LinearExpr, 0, rate.Width)
			for col := 0; col < rate.Width; col++ {
				terms = append(terms, sboxState[col].scale(primitives.MustBigInt(rate.MDS[row*rate.Width+col]), modulus))
			}
			next[row] = addACL2LinearExprs(modulus, terms...)
		}
		state = next
	}

	if _, err := fmt.Fprintln(w, "         )"); err != nil {
		return err
	}
	if err := writeIgnorableDecl(w, boundNames); err != nil {
		return err
	}
	_, err := fmt.Fprintf(w, "    %s))\n\n", acl2LinearExprString(state[1], basisOrder))
	return err
}

func acl2LinearExprString(expr acl2LinearExpr, basisOrder []string) string {
	terms := make([]string, 0, len(expr.coeffs))
	seen := map[string]bool{}
	for _, name := range basisOrder {
		if coeff, ok := expr.coeffs[name]; ok {
			terms = append(terms, fieldMulConst(coeff.String(), name))
			seen[name] = true
		}
	}
	if len(seen) != len(expr.coeffs) {
		extra := make([]string, 0, len(expr.coeffs)-len(seen))
		for name := range expr.coeffs {
			if !seen[name] {
				extra = append(extra, name)
			}
		}
		sort.Strings(extra)
		for _, name := range extra {
			terms = append(terms, fieldMulConst(expr.coeffs[name].String(), name))
		}
	}
	for i, j := 0, len(terms)-1; i < j; i, j = i+1, j-1 {
		terms[i], terms[j] = terms[j], terms[i]
	}
	if expr.constant.Sign() == 0 {
		return fieldAddExpr(terms)
	}
	if len(terms) == 0 {
		return expr.constant.String()
	}
	return fmt.Sprintf("(pfield::add %s %s *poseidon377-prime*)", expr.constant.String(), fieldAddExpr(terms))
}

func writeIgnorableDecl(w io.Writer, names []string) error {
	if _, err := fmt.Fprintln(w, "    (declare (ignorable"); err != nil {
		return err
	}
	for i, name := range names {
		if i%6 == 0 {
			if _, err := fmt.Fprint(w, "              "); err != nil {
				return err
			}
		}
		if _, err := fmt.Fprintf(w, "%s", name); err != nil {
			return err
		}
		if i == len(names)-1 {
			if _, err := fmt.Fprintln(w, "))"); err != nil {
				return err
			}
			return nil
		}
		if _, err := fmt.Fprint(w, " "); err != nil {
			return err
		}
		if i%6 == 5 {
			if _, err := fmt.Fprintln(w); err != nil {
				return err
			}
		}
	}
	_, err := fmt.Fprintln(w, "))")
	return err
}

func fieldMulConst(constant, variable string) string {
	switch constant {
	case "0":
		return "0"
	case "1":
		return variable
	default:
		return fmt.Sprintf("(pfield::mul %s %s *poseidon377-prime*)", constant, variable)
	}
}

func fieldAddExpr(terms []string) string {
	switch len(terms) {
	case 0:
		return "0"
	case 1:
		return terms[0]
	default:
		return fmt.Sprintf("(pfield::add %s %s *poseidon377-prime*)", terms[0], fieldAddExpr(terms[1:]))
	}
}

func writeACL2Matrix(w io.Writer, values []string, width int, indent string) error {
	if _, err := fmt.Fprint(w, "("); err != nil {
		return err
	}
	for row := 0; row < width; row++ {
		if row > 0 {
			if _, err := fmt.Fprintf(w, "\n%s", indent); err != nil {
				return err
			}
		}
		if err := writeACL2List(w, values[row*width:(row+1)*width], indent+" "); err != nil {
			return err
		}
	}
	_, err := fmt.Fprint(w, ")")
	return err
}

func writeACL2List(w io.Writer, values []string, indent string) error {
	if _, err := fmt.Fprint(w, "("); err != nil {
		return err
	}
	lineLen := 1
	for i, value := range values {
		sep := " "
		if i == 0 {
			sep = ""
		}
		if lineLen+len(sep)+len(value) > 100 {
			if _, err := fmt.Fprintf(w, "\n%s", indent); err != nil {
				return err
			}
			lineLen = len(indent)
			sep = ""
		}
		if _, err := fmt.Fprintf(w, "%s%s", sep, value); err != nil {
			return err
		}
		lineLen += len(sep) + len(value)
	}
	_, err := fmt.Fprint(w, ")")
	return err
}

func acl2Args(values []string) string {
	return joinSpace(values)
}

func joinSpace(values []string) string {
	if len(values) == 0 {
		return ""
	}
	out := values[0]
	for _, value := range values[1:] {
		out += " " + value
	}
	return out
}
