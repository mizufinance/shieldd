// runExportPoseidonLean emits the protocol-owned Lean Poseidon377 modules from
// phase05_vectors.json. Mirrors export-poseidon-acl2.
func runExportPoseidonLean(args []string) error {
	fs := flag.NewFlagSet("export-poseidon-lean", flag.ContinueOnError)
	outPath := fs.String("out", "", "output Lean Poseidon377 vectors module")
	fixedOutDir := fs.String("fixed-out-dir", "", "output directory for fixed-rate Lean modules")
	if err := fs.Parse(args); err != nil {
		return err
	}
	if *outPath == "" || *fixedOutDir == "" {
		return fmt.Errorf("--out and --fixed-out-dir are required")
	}
	if err := os.MkdirAll(filepath.Dir(*outPath), 0o755); err != nil {
		return fmt.Errorf("create output dir: %w", err)
	}
	if err := os.MkdirAll(*fixedOutDir, 0o755); err != nil {
		return fmt.Errorf("create fixed-rate output dir: %w", err)
	}

	vectors, err := primitives.LoadPrototypeVectors()
	if err != nil {
		return fmt.Errorf("load prototype vectors: %w", err)
	}

	file, err := os.Create(*outPath)
	if err != nil {
		return fmt.Errorf("create poseidon Lean vectors: %w", err)
	}
	defer file.Close()
	writer := bufio.NewWriter(file)
	if err := writePoseidonLean(writer, vectors.Poseidon377); err != nil {
		return err
	}
	if err := writer.Flush(); err != nil {
		return err
	}
	fmt.Fprintf(os.Stderr, "wrote %s\n", *outPath)

	fixedRates := []primitives.PoseidonRateVectors{
		vectors.Poseidon377.Rate1,
		vectors.Poseidon377.Rate2,
		vectors.Poseidon377.Rate3,
		vectors.Poseidon377.Rate4,
		vectors.Poseidon377.Rate5,
		vectors.Poseidon377.Rate6,
		vectors.Poseidon377.Rate7,
	}
	for _, rate := range fixedRates {
		path := filepath.Join(*fixedOutDir, fmt.Sprintf("Fixed%d.lean", rate.Rate))
		if err := writePoseidonLeanFile(path, func(w io.Writer) error {
			return writePoseidonLeanFixed(w, rate)
		}); err != nil {
			return err
		}
		fmt.Fprintf(os.Stderr, "wrote %s\n", path)
	}
	return nil
}

func writePoseidonLeanFile(path string, write func(io.Writer) error) error {
	file, err := os.Create(path)
	if err != nil {
		return fmt.Errorf("create Poseidon Lean module %s: %w", path, err)
	}
	writer := bufio.NewWriter(file)
	if err := write(writer); err != nil {
		file.Close()
		return err
	}
	if err := writer.Flush(); err != nil {
		file.Close()
		return err
	}
	return file.Close()
}

func writePoseidonLean(w io.Writer, vectors primitives.PoseidonVectors) error {
	rates := []primitives.PoseidonRateVectors{
		vectors.Rate1, vectors.Rate2, vectors.Rate3, vectors.Rate4,
		vectors.Rate5, vectors.Rate6, vectors.Rate7,
	}
	for i, rate := range rates {
		if got, want := rate.Rate, i+1; got != want {
			return fmt.Errorf("poseidon rate slot %d has rate %d", i+1, got)
		}
		if rate.Alpha != 17 {
			return fmt.Errorf("poseidon rate %d alpha %d != 17", rate.Rate, rate.Alpha)
		}
		if rate.FullRounds != 8 || rate.PartialRounds != 31 {
			return fmt.Errorf("poseidon rate %d rounds full=%d partial=%d", rate.Rate, rate.FullRounds, rate.PartialRounds)
		}
		if rate.Width != rate.Rate+1 {
			return fmt.Errorf("poseidon rate %d width %d != rate+1", rate.Rate, rate.Width)
		}
		if len(rate.MDS) != rate.Width*rate.Width {
			return fmt.Errorf("poseidon rate %d mds length %d != width^2", rate.Rate, len(rate.MDS))
		}
		if len(rate.ARC) != rate.Width*(rate.FullRounds+rate.PartialRounds) {
			return fmt.Errorf("poseidon rate %d arc length %d != width*rounds", rate.Rate, len(rate.ARC))
		}
	}

	hash2Out, err := primitives.Poseidon377Hash2Native(
		primitives.MustBigInt(vectors.IVKDomain),
		[2]*big.Int{big.NewInt(7), big.NewInt(11)},
	)
	if err != nil {
		return err
	}
	hash3Out, err := primitives.Poseidon377Hash3Native(
		primitives.MustBigInt(vectors.NullifierDomain),
		[3]*big.Int{big.NewInt(3), big.NewInt(5), big.NewInt(9)},
	)
	if err != nil {
		return err
	}
	hash5Out, err := primitives.Poseidon377Hash5Native(
		primitives.MustBigInt(vectors.IMTLeafDomain),
		[5]*big.Int{
			big.NewInt(2), big.NewInt(3), big.NewInt(5),
			big.NewInt(7), big.NewInt(11),
		},
	)
	if err != nil {
		return err
	}

	header := []string{
		"import ShielddGnarkFormal.Poseidon377.Sponge",
		"",
		"/-! Generated by `gnarkctl export-poseidon-lean` from phase05_vectors.json.",
		"    Poseidon377 round constants, MDS matrices, protocol domain separators,",
		"    and pinned test vectors. Do not edit by hand. -/",
		"",
		"namespace Shieldd.GnarkFormal.Poseidon377",
		"",
	}
	for _, line := range header {
		if _, err := fmt.Fprintln(w, line); err != nil {
			return err
		}
	}

	for _, rate := range rates {
		if err := writePoseidonLeanRateConstants(w, rate); err != nil {
			return err
		}
	}

	domains := []struct {
		name  string
		value string
	}{
		{"nullifierDomain", vectors.NullifierDomain},
		{"ivkDomain", vectors.IVKDomain},
		{"imtLeafDomain", vectors.IMTLeafDomain},
		{"hash7Domain", vectors.Hash7Domain},
	}
	for _, d := range domains {
		if _, err := fmt.Fprintf(w, "def %s : F := (%s : F)\n\n", d.name, d.value); err != nil {
			return err
		}
	}

	// Pinned parity vectors evaluated in-kernel at build time.
	guards := []string{
		"-- Parity with gnark/Go ground truth is checked in shieldd-formal.",
		fmt.Sprintf("#guard (hash2 ivkDomain 7 11).val == %s", hash2Out.String()),
		fmt.Sprintf("#guard (hash3 nullifierDomain 3 5 9).val == %s", hash3Out.String()),
		fmt.Sprintf("#guard (hash5 imtLeafDomain 2 3 5 7 11).val == %s", hash5Out.String()),
		fmt.Sprintf("#guard (hash7 hash7Domain %s).val == %s",
			strings.Join(vectors.Hash7Inputs, " "), vectors.Hash7Output),
		"",
		"end Shieldd.GnarkFormal.Poseidon377",
	}
	for _, line := range guards {
		if _, err := fmt.Fprintln(w, line); err != nil {
			return err
		}
	}
	return nil
}

func writePoseidonLeanFixed(w io.Writer, rate primitives.PoseidonRateVectors) error {
	if rate.Alpha != 17 || rate.FullRounds != 8 || rate.PartialRounds != 31 {
		return fmt.Errorf("unsupported Poseidon rate %d schedule", rate.Rate)
	}
	if rate.Width != rate.Rate+1 ||
		len(rate.MDS) != rate.Width*rate.Width ||
		len(rate.ARC) != rate.Width*(rate.FullRounds+rate.PartialRounds) {
		return fmt.Errorf("invalid Poseidon rate %d dimensions", rate.Rate)
	}

	width := rate.Width
	rowName := fmt.Sprintf("row%d", width)
	fullName := fmt.Sprintf("fr%d", width)
	partialName := fmt.Sprintf("pr%d", width)
	lines := []string{
		"import ShielddGnarkFormal.Poseidon377.Basic",
		"import ProvenZk.Ext.Vector",
		"",
		fmt.Sprintf("/-! Generated canonical rate-%d Poseidon377 hash. Do not edit by hand. -/", rate.Rate),
		"",
		fmt.Sprintf("namespace Shieldd.GnarkFormal.Poseidon377.Fixed%d", rate.Rate),
		"",
		"abbrev F := Poseidon377.F",
		"",
		"/-- `x^17` exactly as the extracted S-box gate chain computes it. -/",
		"def p17 (a : F) : F :=",
		"  let a2 := a * a",
		"  let a4 := a2 * a2",
		"  let a8 := a4 * a4",
		"  let a16 := a8 * a8",
		"  a16 * a",
		"",
	}
	for _, line := range lines {
		if _, err := fmt.Fprintln(w, line); err != nil {
			return err
		}
	}

	usesRowHelper := width >= 7
	if usesRowHelper {
		coefficients := make([]string, width)
		inputs := make([]string, width)
		products := make([]string, width)
		for i := 0; i < width; i++ {
			coefficients[i] = fmt.Sprintf("c%d", i)
			inputs[i] = fmt.Sprintf("x%d", i)
			products[i] = fmt.Sprintf("c%d * x%d", i, i)
		}
		if _, err := fmt.Fprintf(w,
			"/-- Left-associated MDS row matching the extracted gate tree. -/\ndef %s (%s %s : F) : F :=\n  %s\n\n",
			rowName, strings.Join(coefficients, " "), strings.Join(inputs, " "),
			strings.Join(products, " + ")); err != nil {
			return err
		}
	}

	if err := writePoseidonLeanRound(w, rate, true, usesRowHelper); err != nil {
		return err
	}
	if err := writePoseidonLeanRound(w, rate, false, usesRowHelper); err != nil {
		return err
	}

	params := []string{"Domain"}
	initial := []string{"Domain"}
	for i := 0; i < rate.Rate; i++ {
		name := fmt.Sprintf("In%d", i)
		params = append(params, name)
		initial = append(initial, name)
	}
	if _, err := fmt.Fprintf(w,
		"/-- The composed 39-round permutation, returning sponge coordinate 1. -/\ndef hash (%s : F) : F :=\n",
		strings.Join(params, " ")); err != nil {
		return err
	}
	for round := 0; round < rate.FullRounds+rate.PartialRounds; round++ {
		roundName := partialName
		if round < rate.FullRounds/2 || round >= rate.FullRounds/2+rate.PartialRounds {
			roundName = fullName
		}
		state := fmt.Sprintf("gate_%d", round-1)
		if round == 0 {
			state = fmt.Sprintf("vec![%s]", strings.Join(initial, ", "))
		}
		constants := rate.ARC[round*width : (round+1)*width]
		rendered := make([]string, width)
		for i, value := range constants {
			rendered[i] = fmt.Sprintf("(%s:F)", value)
		}
		if _, err := fmt.Fprintf(w, "  let gate_%d := %s %s vec![%s]\n",
			round, roundName, state, strings.Join(rendered, ", ")); err != nil {
			return err
		}
	}
	if _, err := fmt.Fprintf(w, "  gate_%d[1]\n\nend Shieldd.GnarkFormal.Poseidon377.Fixed%d\n",
		rate.FullRounds+rate.PartialRounds-1, rate.Rate); err != nil {
		return err
	}
	return nil
}

func writePoseidonLeanRound(
	w io.Writer,
	rate primitives.PoseidonRateVectors,
	full bool,
	usesRowHelper bool,
) error {
	width := rate.Width
	name := fmt.Sprintf("pr%d", width)
	kind := "Partial"
	if full {
		name = fmt.Sprintf("fr%d", width)
		kind = "Full"
	}
	if _, err := fmt.Fprintf(w,
		"/-- %s round: add constants, apply the S-box, then MDS. -/\ndef %s (st cs : List.Vector F %d) : List.Vector F %d :=\n",
		kind, name, width, width); err != nil {
		return err
	}
	for i := 0; i < width; i++ {
		value := fmt.Sprintf("st[%d] + cs[%d]", i, i)
		if full || i == 0 {
			value = "p17 (" + value + ")"
		}
		if _, err := fmt.Fprintf(w, "  let s%d := %s\n", i, value); err != nil {
			return err
		}
	}
	if _, err := fmt.Fprintln(w, "  vec!["); err != nil {
		return err
	}
	inputs := make([]string, width)
	for i := range inputs {
		inputs[i] = fmt.Sprintf("s%d", i)
	}
	for row := 0; row < width; row++ {
		terms := make([]string, width)
		for col := 0; col < width; col++ {
			terms[col] = fmt.Sprintf("(%s:F) * s%d", rate.MDS[row*width+col], col)
		}
		expression := strings.Join(terms, " + ")
		if usesRowHelper {
			coefficients := make([]string, width)
			for col := 0; col < width; col++ {
				coefficients[col] = fmt.Sprintf("(%s:F)", rate.MDS[row*width+col])
			}
			expression = fmt.Sprintf("row%d %s %s",
				width, strings.Join(coefficients, " "), strings.Join(inputs, " "))
		}
		suffix := ","
		if row == width-1 {
			suffix = "]"
		}
		if _, err := fmt.Fprintf(w, "    %s%s\n", expression, suffix); err != nil {
			return err
		}
	}
	_, err := fmt.Fprintln(w)
	return err
}

func writePoseidonLeanRateConstants(w io.Writer, rate primitives.PoseidonRateVectors) error {
	if _, err := fmt.Fprintf(w, "def rate%dArc : List F :=\n  %s\n\n", rate.Rate, leanFList(rate.ARC)); err != nil {
		return err
	}
	if _, err := fmt.Fprintf(w, "def rate%dMds : List (List F) :=\n  [", rate.Rate); err != nil {
		return err
	}
	for row := 0; row < rate.Width; row++ {
		prefix := "\n   "
		if row == 0 {
			prefix = ""
		}
		rowVals := rate.MDS[row*rate.Width : (row+1)*rate.Width]
		if _, err := fmt.Fprintf(w, "%s%s", prefix, leanFList(rowVals)); err != nil {
			return err
		}
		if row != rate.Width-1 {
			if _, err := fmt.Fprint(w, ","); err != nil {
				return err
			}
		}
	}
	_, err := fmt.Fprint(w, "]\n\n")
	return err
}

// leanFList renders decimal field elements as a Lean `List F` literal.
func leanFList(values []string) string {
	out := make([]byte, 0, len(values)*32)
	out = append(out, '[')
	for i, v := range values {
		if i != 0 {
			out = append(out, ',', ' ')
		}
		out = append(out, '(')
		out = append(out, v...)
		out = append(out, " : F)"...)
	}
	out = append(out, ']')
	return string(out)
}
