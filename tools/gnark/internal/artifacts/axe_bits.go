type AxeSymbolRun struct {
	Start string
	End   string
	Count int
}

var (
	booleanConstraintPattern = regexp.MustCompile(`\(make-r1cs-constraint\s+:a '\(\(1 ([A-Z0-9-]+)\)\)\s+:b '\(\(1 1\) \(-1 ([A-Z0-9-]+)\)\)\s+:c '\(\(0 1\)\)\)`)
	internalSymbolPattern    = regexp.MustCompile(`^INTERNAL-([0-9]+)$`)
)

// ExtractBooleanBitInputsFromAxeLisp returns wires constrained by b*(1-b)=0.
func ExtractBooleanBitInputsFromAxeLisp(data []byte) ([]string, error) {
	matches := booleanConstraintPattern.FindAllSubmatch(data, -1)
	out := make([]string, 0, len(matches))
	seen := map[string]struct{}{}
	for _, match := range matches {
		a := string(match[1])
		b := string(match[2])
		if a != b {
			return nil, fmt.Errorf("malformed boolean constraint: :a %s != :b %s", a, b)
		}
		if _, ok := seen[a]; ok {
			return nil, fmt.Errorf("duplicate boolean bit input %s", a)
		}
		seen[a] = struct{}{}
		out = append(out, a)
	}
	return out, nil
}

func SelectRuns(symbols []string, keep func(AxeSymbolRun) bool) ([]string, []AxeSymbolRun, error) {
	runs, err := ContiguousInternalRuns(symbols)
	if err != nil {
		return nil, nil, err
	}
	keepSet := map[string]struct{}{}
	keptRuns := make([]AxeSymbolRun, 0, len(runs))
	for _, run := range runs {
		if !keep(run) {
			continue
		}
		start, err := internalSymbolNumber(run.Start)
		if err != nil {
			return nil, nil, err
		}
		end, err := internalSymbolNumber(run.End)
		if err != nil {
			return nil, nil, err
		}
		for n := start; n <= end; n++ {
			keepSet[fmt.Sprintf("INTERNAL-%d", n)] = struct{}{}
		}
		keptRuns = append(keptRuns, run)
	}
	out := make([]string, 0, len(symbols))
	for _, symbol := range symbols {
		if _, ok := keepSet[symbol]; ok {
			out = append(out, symbol)
		}
	}
	return out, keptRuns, nil
}

func ContiguousInternalRuns(symbols []string) ([]AxeSymbolRun, error) {
	if len(symbols) == 0 {
		return nil, nil
	}
	values := make([]int, len(symbols))
	for i, symbol := range symbols {
		n, err := internalSymbolNumber(symbol)
		if err != nil {
			return nil, err
		}
		values[i] = n
	}
	sort.Ints(values)

	runs := make([]AxeSymbolRun, 0, 2)
	start := values[0]
	prev := values[0]
	for _, value := range values[1:] {
		if value == prev+1 {
			prev = value
			continue
		}
		runs = append(runs, internalRun(start, prev))
		start = value
		prev = value
	}
	runs = append(runs, internalRun(start, prev))
	return runs, nil
}

func WriteAxeLispBitInputs(path, label string, symbols []string, runs []AxeSymbolRun) error {
	file, err := os.Create(path)
	if err != nil {
		return fmt.Errorf("create bit-input lisp file: %w", err)
	}
	defer file.Close()
	writer := bufio.NewWriter(file)
	if err := writeAxeLispBitInputs(writer, label, symbols, runs); err != nil {
		return err
	}
	return writer.Flush()
}

func writeAxeLispBitInputs(writer io.Writer, label string, symbols []string, runs []AxeSymbolRun) error {
	prefix := acl2ConstPrefix(label)
	if _, err := fmt.Fprintln(writer, "; Generated by gnarkctl extract-bit-inputs."); err != nil {
		return err
	}
	if _, err := fmt.Fprintln(writer, "; Derived from b*(1-b)=0 constraints in the checked-in Axe Lisp export."); err != nil {
		return err
	}
	if _, err := fmt.Fprintln(writer, "; Do not edit by hand."); err != nil {
		return err
	}
	if _, err := fmt.Fprintln(writer); err != nil {
		return err
	}
	if _, err := fmt.Fprintln(writer, "(in-package \"R1CS\")"); err != nil {
		return err
	}
	if _, err := fmt.Fprintln(writer); err != nil {
		return err
	}

	if _, err := fmt.Fprintf(writer, "(defconst *%s-bit-inputs*\n  '", prefix); err != nil {
		return err
	}
	if err := writeSymbolList(writer, symbols, "   "); err != nil {
		return err
	}
	if _, err := fmt.Fprintln(writer, ")"); err != nil {
		return err
	}
	if _, err := fmt.Fprintln(writer); err != nil {
		return err
	}

	if _, err := fmt.Fprintf(writer, "(defconst *%s-bit-input-runs*\n  '(", prefix); err != nil {
		return err
	}
	for i, run := range runs {
		if i > 0 {
			if _, err := fmt.Fprint(writer, "\n    "); err != nil {
				return err
			}
		}
		if _, err := fmt.Fprintf(writer, "(:start %s :end %s :count %d)", run.Start, run.End, run.Count); err != nil {
			return err
		}
	}
	if _, err := fmt.Fprintln(writer, "))"); err != nil {
		return err
	}
	return nil
}

func writeSymbolList(writer io.Writer, symbols []string, indent string) error {
	if len(symbols) == 0 {
		_, err := fmt.Fprint(writer, "()")
		return err
	}
	if _, err := fmt.Fprint(writer, "("); err != nil {
		return err
	}
	lineLen := 1
	for i, symbol := range symbols {
		sep := " "
		if i == 0 {
			sep = ""
		}
		if lineLen+len(sep)+len(symbol) > 78 {
			if _, err := fmt.Fprintf(writer, "\n%s", indent); err != nil {
				return err
			}
			lineLen = len(indent)
			sep = ""
		}
		if _, err := fmt.Fprintf(writer, "%s%s", sep, symbol); err != nil {
			return err
		}
		lineLen += len(sep) + len(symbol)
	}
	_, err := fmt.Fprint(writer, ")")
	return err
}

func internalRun(start, end int) AxeSymbolRun {
	return AxeSymbolRun{
		Start: fmt.Sprintf("INTERNAL-%d", start),
		End:   fmt.Sprintf("INTERNAL-%d", end),
		Count: end - start + 1,
	}
}

func internalSymbolNumber(symbol string) (int, error) {
	match := internalSymbolPattern.FindStringSubmatch(symbol)
	if match == nil {
		return 0, fmt.Errorf("boolean bit input %s is not an INTERNAL-* symbol", symbol)
	}
	n, err := strconv.Atoi(match[1])
	if err != nil {
		return 0, fmt.Errorf("parse %s: %w", symbol, err)
	}
	return n, nil
}

func FormatAxeBitInputsReport(symbols []string, runs []AxeSymbolRun) string {
	var out bytes.Buffer
	fmt.Fprintf(&out, "bit_inputs=%d\n", len(symbols))
	for i, run := range runs {
		fmt.Fprintf(&out, "run_%d=%s..%s count=%d\n", i+1, run.Start, run.End, run.Count)
	}
	return strings.TrimRight(out.String(), "\n")
}
