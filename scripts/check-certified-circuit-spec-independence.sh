#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
source "$ROOT/scripts/lib/fail-closed-rg.sh"
PROTOCOL_ROOT="$ROOT/tools/gnark/lean/ShielddGnarkFormal/Protocol"
GENERATOR_DIR="$ROOT/tools/gnark/lean/gen"
PIN="$ROOT/tools/gnark/lean/certified-protocol-semantics.sha256"

MODE="${1:-}"
semantic_digest_args=()
case "$MODE" in
  candidate)
    semantic_digest_args=(--skip-semantic-digest)
    ;;
  strict) ;;
  *)
    echo "usage: $(basename "$0") [candidate|strict]" >&2
    exit 2
    ;;
esac

fail() {
  echo "certified-circuit specification independence: $*" >&2
  exit 1
}

[[ -f "$PIN" ]] || fail "missing semantic digest pin"
python3 "$ROOT/scripts/gen_fv_specification_matrix.py" --check \
  || fail "the generated reviewed evidence matrix is stale"
python3 "$ROOT/scripts/check-fv-specification-completeness.py" \
  "${semantic_digest_args[@]}" \
  || fail "the native/specification/circuit predicate matrix or semantic digest is not closed"

reject_rg_matches "protocol import independence" \
  -n '^import ShielddGnarkFormal\.(Deployed|Generated|Extracted)' "$PROTOCOL_ROOT" \
  || fail "an independent protocol module imports circuit-owned modules or the search failed"
python3 "$ROOT/tools/gnark/lean/gen/check_lean_import_closure.py" \
  --lean-dir "$ROOT/tools/gnark/lean" \
  --root ShielddGnarkFormal.Protocol.NoteReshape.Semantics \
  --root ShielddGnarkFormal.Protocol.NoteReshape.Concrete \
  --root ShielddGnarkFormal.Protocol.NoteReshape.CircuitFacts \
  --root ShielddGnarkFormal.Protocol.NoteReshape.Refinement \
  --root ShielddGnarkFormal.Protocol.NoteReshape.Security \
  --root ShielddGnarkFormal.Protocol.Transfer.Semantics \
  --root ShielddGnarkFormal.Protocol.Transfer.Concrete \
  --root ShielddGnarkFormal.Protocol.Transfer.CircuitFacts \
  --root ShielddGnarkFormal.Protocol.Transfer.Refinement \
  --root ShielddGnarkFormal.Protocol.Transfer.Security \
  --root ShielddGnarkFormal.Protocol.ShieldedIcs20Withdrawal.Semantics \
  --root ShielddGnarkFormal.Protocol.ShieldedIcs20Withdrawal.Concrete \
  --root ShielddGnarkFormal.Protocol.ShieldedIcs20Withdrawal.CircuitFacts \
  --root ShielddGnarkFormal.Protocol.ShieldedIcs20Withdrawal.Refinement \
  --root ShielddGnarkFormal.Protocol.ShieldedIcs20Withdrawal.Security \
  --forbid-regex '(^|\\.)(Deployed|Generated|Extracted)(\\.|$)|Bridge$|Canonical$|Poseidon(1|2|3|4|5|6|7)Spec$' \
  || fail "a protocol semantics import closure reaches a circuit-owned module"
reject_rg_matches "protocol representation independence" \
  -ni '(wireSeating|wire[ -]index|manifest|sr1cs|constraint trace)' \
  "$PROTOCOL_ROOT" \
  || fail "protocol semantics mentions a circuit-owned representation or the search failed"
reject_rg_matches "generator ownership boundary" \
  -n --glob '*.py' \
  'Protocol/' \
  "$GENERATOR_DIR" \
  || fail "a proof generator names a handwritten protocol output path or the search failed"
reject_rg_matches "handwritten protocol ownership marker" \
  -n '(GENERATED by|do not edit)' "$PROTOCOL_ROOT" \
  || fail "a handwritten protocol module is marked as generator-owned or the search failed"
reject_rg_matches "generated statement boundary" \
  -n --glob '*.py' '(Statement\.lean|StatementSpec|Statement \()' \
  "$GENERATOR_DIR" "$ROOT/scripts" \
  || fail "generated family contracts must expose exact CircuitFacts, not protocol statements, or the search failed"

check_consumed_fields() {
  local refinement="$1"
  shift
  local field
  for field in "$@"; do
    rg -n "facts\\.$field" "$refinement" >/dev/null \
      || fail "$refinement does not consume CircuitFacts.$field"
  done
}

check_consumed_fields \
  "$PROTOCOL_ROOT/NoteReshape/Refinement.lean" \
  shape padding randomizersCanonical dummySlotIndicesCanonical \
  canonicalAddress inputsBound membership authorizationKeys outputsBound \
  valueConserved statementBound
check_consumed_fields \
  "$PROTOCOL_ROOT/Transfer/Refinement.lean" \
  canonicalSender requiredSpend optionalSpend receiverOutput changeOutput \
  assetRegistry senderCompliance receiverCompliance complianceTranscript \
  balanceComputedAndCompressed statementBinding
check_consumed_fields \
  "$PROTOCOL_ROOT/ShieldedIcs20Withdrawal/Refinement.lean" \
  canonicalSender requiredSpend optionalSpend changeOutput assetRegistry \
  senderCompliance conservation statementBinding

echo "certified-circuit specification independence ok"
