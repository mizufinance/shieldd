#!/usr/bin/env python3
"""Generate quad-path-1-proof.lisp from the gadget-quad-path-1 R1CS export.

Depth-1 VerifyQuadPath: one quad-Merkle layer = position decode + 4 Selects +
one Poseidon377Hash4(Domain). Domain is threaded as a wire (not the shipped
literal 0) so gnark does not constant-fold the lane-0 S-box, keeping the hash
sub-block structurally identical to the proved standalone `gadget-poseidon-hash4`
(71 S-boxes). The verify-r1cs target reuses `poseidon377-hash4-r1cs-axe` verbatim:

  ROOT = poseidon377-hash4-r1cs-axe(DOMAIN, child0, child1, child2, child3)

The 4 children are the arithmetic Selects, each `child_k = build_lincomb(wire part
of the round-0 input-lane-k S-box :a)` — derived from the export so the lane
chain's E matches the spec arg syntactically (the Axe rule-list has no pfield::add
reassociation; a mismatched add order makes the chain miss and the 71-round hash
expand). The leading 17 select/decode constraints define the select-product wires
(INTERNAL-14..19); they need NO rewrite rules — verify-r1cs's :subst discharges
them. Per-layer position-correctness (children equal the right sibling arrangement
for the position bits) is the separate bool-select/iszero glue, not this gadget row.

Chain convention identical to gen-hash4-proof.py (reverse-engineered from
poseidon2-proof.lisp): multiplicative coeffs signed-normalized, additive round
constants raw/positive, lincomb constant-first then wires reverse-export-order.
"""
import re

PRIME = 8444461749428370424248824938781546531375899335154063827935233455917409239041
HALF = PRIME // 2
EXPORT = "generated/gadget-quad-path-1-r1cs.lisp"
OUT = "quad-path-1-proof.lisp"
P = "*poseidon377-prime*"
N_SELECT = 17  # leading position-decode + select-product constraints


def signed(k):
    k = int(k)
    return k - PRIME if k > HALF else k


def parse_vec(s):
    pairs = re.findall(r"\(\s*(-?\d+)\s+([A-Za-z0-9\-]+)\s*\)", s)
    return [(int(c), w) for c, w in pairs]


def term_of_pair(coeff, wire):
    if wire == "1":
        return str(int(coeff))
    if coeff == 1:
        return wire
    return f"(pfield::mul {signed(coeff)} {wire} {P})"


def build_lincomb(vec):
    const = [p for p in vec if p[1] == "1"]
    wires = [p for p in vec if p[1] != "1"]
    elems = [term_of_pair(c, w) for c, w in const]
    for c, w in reversed(wires):
        elems.append(term_of_pair(c, w))
    if not elems:
        return "0"
    term = elems[-1]
    for e in reversed(elems[:-1]):
        term = f"(pfield::add {e} {term} {P})"
    return term


def main():
    text = open(EXPORT).read()
    body = text.split("*GADGET-QUAD-PATH-1-constraints*", 1)[1]
    blocks = re.findall(
        r":a\s*'\((.*?)\)\)\s*:b\s*'\((.*?)\)\)\s*:c\s*'\((.*?)\)\)",
        body, re.S)
    cons = [(parse_vec("(" + a + ")"),
             parse_vec("(" + b + ")"),
             parse_vec("(" + c + ")")) for a, b, c in blocks]

    out_con = cons[-1]
    sbox_cons = cons[N_SELECT:-1]
    assert len(sbox_cons) % 5 == 0, len(sbox_cons)
    n_sbox = len(sbox_cons) // 5

    chains = []
    for i in range(n_sbox):
        c0, c1, c2, c3, c4 = sbox_cons[5 * i:5 * i + 5]
        E = build_lincomb(c0[0])
        chains.append((i, E,
                       c0[2][0][1], c1[2][0][1], c2[2][0][1],
                       c3[2][0][1], c4[2][0][1]))

    # children = in0..in3 args of poseidon377-hash4-r1cs-axe. Each round-0 input
    # lane's S-box :a vector is (RC_ink, <child wires>); the spec computes that
    # lane as (add RC_ink in_k), so child_k must be the wire-only part of that
    # vector in build_lincomb's exact nesting (reverse export order) — otherwise
    # the lane chain's LHS will not match the spec arg syntactically (the Axe
    # rule-list carries no pfield::add reassociation), the chain fails to fire,
    # and the whole 71-round hash expands. Round-0 lanes are S-boxes 0..4 in
    # export order: domain, in0, in1, in2, in3 -> children are chains 1..4.
    def child_of_lane(lane):  # lane 0..3 -> S-box index lane+1
        c0 = sbox_cons[5 * (lane + 1)]
        wires = [pr for pr in c0[0] if pr[1] != "1"]
        return build_lincomb(wires)
    child0 = child_of_lane(0)
    child1 = child_of_lane(1)
    child2 = child_of_lane(2)
    child3 = child_of_lane(3)

    with open(OUT, "w") as f:
        w = f.write
        w("; Semantic Axe proof target for the compiled gnark depth-1 VerifyQuadPath gadget.\n")
        w("; Generated by gen-quad-path-1-proof.py from gadget-quad-path-1-r1cs; do not edit by hand.\n")
        w("; ROOT = poseidon377-hash4-r1cs-axe(0, child0..child3) over the 373-constraint\n")
        w("; export (17 select/decode + 71 S-boxes + 1 output).\n\n")
        w('(in-package "R1CS")\n\n')
        w('(include-book "generated/gadget-quad-path-1-r1cs")\n')
        w('(include-book "generated/poseidon377-spec")\n')
        w('(include-book "kestrel/prime-fields/top" :dir :system)\n\n')

        w("; BEGIN COEFFICIENT NORMALIZERS\n")
        w("(defthmd qp1-mul-constant-normalize-to-signed\n")
        w("  (implies (and (syntaxp (quotep k))\n")
        w("                (integerp k)\n")
        w("                (< (/ *poseidon377-prime* 2) k)\n")
        w("                (< k *poseidon377-prime*))\n")
        w("           (equal (pfield::mul k x *poseidon377-prime*)\n")
        w("                  (pfield::mul (+ k (- *poseidon377-prime*)) x *poseidon377-prime*)))\n")
        w("  :hints ((\"Goal\" :use (:instance pfield::mul-of-+-same-arg1-arg2\n")
        w("                                  (p *poseidon377-prime*)\n")
        w("                                  (x (+ k (- *poseidon377-prime*)))\n")
        w("                                  (y x)))))\n")
        w("(defun qp1-coeff-normalization-rules ()\n")
        w("  (declare (xargs :guard t))\n")
        w("  '(qp1-mul-constant-normalize-to-signed))\n")
        w("; END COEFFICIENT NORMALIZERS\n\n")

        for (i, E, w1, w2, w3, w4, w5) in chains:
            w(f"(defthm qp1-pow17-chain-{i}\n")
            w("  (implies (and\n")
            w(f"                (equal (pfield::mul {E} {E} {P}) {w1})\n")
            w(f"                (equal (pfield::mul {w1} {w1} {P}) {w2})\n")
            w(f"                (equal (pfield::mul {w2} {w2} {P}) {w3})\n")
            w(f"                (equal (pfield::mul {w3} {w3} {P}) {w4})\n")
            w(f"                (equal (pfield::mul {w4} {E} {P}) {w5})\n")
            w("                )\n")
            w(f"           (equal (poseidon377-pow17 {E})\n")
            w(f"                  {w5}))\n")
            w("  :hints ((\"Goal\" :in-theory (theory 'minimal-theory)\n")
            w("                  :expand ((:free (x) (poseidon377-pow17 x))))))\n\n")

        Eout = build_lincomb(out_con[1])
        w("(defthm qp1-final-output-root-left\n")
        w("  (implies\n")
        w(f"   (equal\n    {Eout}\n    ROOT)\n")
        w("   (equal\n")
        w(f"    (equal\n     ROOT\n     {Eout})\n")
        w("    t)))\n\n")

        w('(include-book "kestrel/axe/r1cs/top" :dir :system)\n\n')
        w("(local\n")
        w(" (lift-r1cs *gadget-quad-path-1-proof-lifted*\n")
        w("            *GADGET-QUAD-PATH-1-vars*\n")
        w("            *GADGET-QUAD-PATH-1-constraints*\n")
        w("            *GADGET-QUAD-PATH-1-prime*\n")
        w('            :package "R1CS"))\n\n')

        w("(verify-r1cs\n")
        w(" *gadget-quad-path-1-proof-lifted*\n")
        w(f" (equal ROOT (poseidon377-hash4-r1cs-axe DOMAIN\n")
        w(f"                {child0}\n")
        w(f"                {child1}\n")
        w(f"                {child2}\n")
        w(f"                {child3}))\n")
        w(" *GADGET-QUAD-PATH-1-prime*\n")
        w(" :tactic '(:seq (:rep :rewrite) :subst)\n")
        w(" :rule-lists '((poseidon377-hash4-r1cs-axe)\n")
        w("               ((qp1-coeff-normalization-rules)\n")
        for (i, *_rest) in chains:
            w(f"                qp1-pow17-chain-{i}\n")
        w("                qp1-final-output-root-left\n")
        w("                pfield::add-of-0-arg1 pfield::add-of-0-arg2\n")
        w("                pfield::mul-of-1-arg1 pfield::mul-of-1-arg2 acl2::equal-same))\n")
        w(" :var-ordering (append (reverse (nthcdr 7 *GADGET-QUAD-PATH-1-vars*))\n")
        w("                       (list 'DOMAIN 'LEAFHASH 'POSITION 'PATH-0-0 'PATH-0-1 'PATH-0-2 'ROOT))\n")
        w(" :print :brief)\n")

    print(f"wrote {OUT}: {n_sbox} pow17 chains (depth-1), final-output helper, verify-r1cs")


if __name__ == "__main__":
    main()
