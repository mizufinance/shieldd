#!/usr/bin/env python3
"""Generate hash4-proof.lisp from the gadget-poseidon-hash4 R1CS export.

Mirrors the hand-authored poseidon2-proof.lisp: emits one pow17-chain rewrite
rule per Poseidon S-box (5-constraint square chain), a final-output commutativity
helper, and the lift-r1cs / verify-r1cs forms targeting poseidon377-hash4-r1cs-axe.

The pow17-chain input expression must match the Axe rewriter's normal form:
  - coefficient k normalized signed: k-p when k > p/2
  - term (coeff wire): bare `wire` when coeff==1, else (mul k_signed wire p)
  - lincomb assembled constant-first, then wire-terms in REVERSE export order,
    right-folded with (add A B p).
This convention was reverse-engineered from poseidon2-proof.lisp against its export.
"""
import re
import sys

PRIME = 8444461749428370424248824938781546531375899335154063827935233455917409239041
HALF = PRIME // 2
EXPORT = "generated/gadget-poseidon-hash4-r1cs.lisp"
OUT = "hash4-proof.lisp"
P = "*poseidon377-prime*"


def signed(k):
    k = int(k)
    return k - PRIME if k > HALF else k


def parse_vec(s):
    """Parse  ((c1 w1) (c2 w2) ...) -> list of (coeff:int, wire:str)."""
    pairs = re.findall(r"\(\s*(-?\d+)\s+([A-Za-z0-9\-]+)\s*\)", s)
    return [(int(c), w) for c, w in pairs]


def term_of_pair(coeff, wire):
    if wire == "1":
        # Additive round constant: keep the raw (positive) field value to match
        # the spec exactly. No rewrite rule bridges a sign-flipped additive
        # constant -- only multiplicative coeffs get signed-normalized below.
        return str(int(coeff))
    if coeff == 1:
        return wire
    return f"(pfield::mul {signed(coeff)} {wire} {P})"


def build_lincomb(vec):
    """vec: list of (coeff, wire). Returns the normal-form prime-field term."""
    const = [p for p in vec if p[1] == "1"]
    wires = [p for p in vec if p[1] != "1"]
    elems = []
    for c, w in const:
        elems.append(term_of_pair(c, w))
    for c, w in reversed(wires):
        elems.append(term_of_pair(c, w))
    if not elems:
        return "0"
    term = elems[-1]
    for e in reversed(elems[:-1]):
        term = f"(pfield::add {e} {term} {P})"
    return term


def main():
    text = open(EXPORT).read()
    body = text.split("*GADGET-POSEIDON-HASH4-constraints*", 1)[1]
    blocks = re.findall(
        r":a\s*'\((.*?)\)\)\s*:b\s*'\((.*?)\)\)\s*:c\s*'\((.*?)\)\)",
        body, re.S)
    cons = []
    for a, b, c in blocks:
        cons.append((parse_vec("(" + a + ")"),
                     parse_vec("(" + b + ")"),
                     parse_vec("(" + c + ")")))
    # last constraint is the output assertion: a=((1 1)) b=lincomb c=((1 OUT))
    out_con = cons[-1]
    sbox_cons = cons[:-1]
    assert len(sbox_cons) % 5 == 0, len(sbox_cons)
    n_sbox = len(sbox_cons) // 5

    chains = []
    for i in range(n_sbox):
        c0, c1, c2, c3, c4 = sbox_cons[5 * i:5 * i + 5]
        E = build_lincomb(c0[0])
        w1 = c0[2][0][1]
        w2 = c1[2][0][1]
        w3 = c2[2][0][1]
        w4 = c3[2][0][1]
        w5 = c4[2][0][1]
        chains.append((i, E, w1, w2, w3, w4, w5))

    with open(OUT, "w") as f:
        w = f.write
        w("; Semantic Axe proof target for the compiled gnark Poseidon377 Hash4 gadget.\n")
        w("; Generated by gen-hash4-proof.py from gadget-poseidon-hash4-r1cs; do not edit by hand.\n")
        w("; Mirrors poseidon2-proof.lisp: per-S-box pow17 chains + verify-r1cs to\n")
        w("; poseidon377-hash4-r1cs-axe over the 356-constraint export.\n\n")
        w('(in-package "R1CS")\n\n')
        w('(include-book "generated/gadget-poseidon-hash4-r1cs")\n')
        w('(include-book "generated/poseidon377-spec")\n')
        w('(include-book "kestrel/prime-fields/top" :dir :system)\n\n')

        # coefficient normalizer (shared shape with poseidon2)
        w("; BEGIN HASH4 COEFFICIENT NORMALIZERS\n")
        w("(defthmd hash4-mul-constant-normalize-to-signed\n")
        w("  (implies (and (syntaxp (quotep k))\n")
        w("                (integerp k)\n")
        w("                (< (/ *poseidon377-prime* 2) k)\n")
        w("                (< k *poseidon377-prime*))\n")
        w("           (equal (pfield::mul k x *poseidon377-prime*)\n")
        w("                  (pfield::mul (+ k (- *poseidon377-prime*)) x *poseidon377-prime*)))\n")
        w("  :hints ((\"Goal\" :use (:instance pfield::mul-of-+-same-arg1-arg2\n")
        w("                                  (p *poseidon377-prime*)\n")
        w("                                  (x (+ k (- *poseidon377-prime*)))\n")
        w("                                  (y x)))))\n")
        w("(defun hash4-coeff-normalization-rules ()\n")
        w("  (declare (xargs :guard t))\n")
        w("  '(hash4-mul-constant-normalize-to-signed))\n")
        w("; END HASH4 COEFFICIENT NORMALIZERS\n\n")

        for (i, E, w1, w2, w3, w4, w5) in chains:
            w(f"(defthm hash4-pow17-chain-{i}\n")
            w("  (implies (and\n")
            w(f"                (equal (pfield::mul {E} {E} {P}) {w1})\n")
            w(f"                (equal (pfield::mul {w1} {w1} {P}) {w2})\n")
            w(f"                (equal (pfield::mul {w2} {w2} {P}) {w3})\n")
            w(f"                (equal (pfield::mul {w3} {w3} {P}) {w4})\n")
            w(f"                (equal (pfield::mul {w4} {E} {P}) {w5})\n")
            w("                )\n")
            w(f"           (equal (poseidon377-pow17 {E})\n")
            w(f"                  {w5}))\n")
            w("  :hints ((\"Goal\" :in-theory (theory 'minimal-theory)\n")
            w("                  :expand ((:free (x) (poseidon377-pow17 x))))))\n\n")

        # final output commutativity helper
        Eout = build_lincomb(out_con[1])
        w("(defthm hash4-final-output-out-left\n")
        w("  (implies\n")
        w(f"   (equal\n    {Eout}\n    OUT)\n")
        w("   (equal\n")
        w(f"    (equal\n     OUT\n     {Eout})\n")
        w("    t)))\n\n")

        # lift + verify
        w('(include-book "kestrel/axe/r1cs/top" :dir :system)\n\n')
        w("(local\n")
        w(" (lift-r1cs *gadget-poseidon-hash4-proof-lifted*\n")
        w("            *GADGET-POSEIDON-HASH4-vars*\n")
        w("            *GADGET-POSEIDON-HASH4-constraints*\n")
        w("            *GADGET-POSEIDON-HASH4-prime*\n")
        w('            :package "R1CS"))\n\n')

        w("(verify-r1cs\n")
        w(" *gadget-poseidon-hash4-proof-lifted*\n")
        w(" (equal OUT (poseidon377-hash4-r1cs-axe DOMAIN IN0 IN1 IN2 IN3))\n")
        w(" *GADGET-POSEIDON-HASH4-prime*\n")
        w(" :tactic '(:seq (:rep :rewrite) :subst)\n")
        w(" :rule-lists '((poseidon377-hash4-r1cs-axe)\n")
        w("               ((hash4-coeff-normalization-rules)\n")
        for (i, *_rest) in chains:
            w(f"                hash4-pow17-chain-{i}\n")
        w("                hash4-final-output-out-left\n")
        w("                pfield::mul-of-1-arg1 pfield::mul-of-1-arg2 acl2::equal-same))\n")
        w(" :var-ordering (append (reverse (nthcdr 6 *GADGET-POSEIDON-HASH4-vars*))\n")
        w("                       (list 'DOMAIN 'IN0 'IN1 'IN2 'IN3 'OUT))\n")
        w(" :print :brief)\n")

    print(f"wrote {OUT}: {n_sbox} pow17 chains, final-output helper, verify-r1cs")


if __name__ == "__main__":
    main()
