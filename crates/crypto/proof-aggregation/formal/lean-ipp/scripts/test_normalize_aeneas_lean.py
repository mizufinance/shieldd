from __future__ import annotations

import json
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SCRIPT = Path(__file__).with_name("normalize_aeneas_lean.py")
GENERATED = ROOT / "Ipp" / "Extracted" / "ArkworksFqMulGenerated.lean"


def raw(body: str) -> str:
    return "-- THIS FILE WAS AUTOMATICALLY GENERATED BY AENEAS\nimport Aeneas\n" + body


class NormalizerTests(unittest.TestCase):
    def run_normalize(self, source: str, *extra: str):
        directory = Path(tempfile.mkdtemp(prefix="normalize-aeneas-test-"))
        source_path = directory / "raw.lean"
        output_path = directory / "normalized.lean"
        source_path.write_text(source, encoding="utf-8")
        command = [sys.executable, str(SCRIPT), "--input", str(source_path), "--output", str(output_path)]
        for item in extra:
            command += ["--extra-import", item]
        completed = subprocess.run(command, capture_output=True, text=True)
        return completed, output_path

    def test_every_rewrite_rule_and_extra_import(self):
        source = raw(
            """\
@[irreducible, global_simps, simp]
def f (x : Std.U64) (y : Std.U128) (b : Std.U8) :
    Array Std.U64 4 := by
  let a : Array Std.U128 2 := Array.make 2
  let c : Array Std.U8 8 := Array.repeat b 8
  let z := UScalar.cast .U128 x
  let q := UScalar.cast UScalarTy.U64 y
  let r := UScalar.cast .Usize x
  let _ := Array.index_usize a 0
  let _ := Array.update a 0 x
  let _ := Array.to_slice a
  let _ := Std.U64.ofNat 1
  let _ := Std.U128.ofNat 2
  #u64 3
"""
        )
        completed, output = self.run_normalize(source, "Ipp.Extracted.Foo")
        self.assertEqual(completed.returncode, 0, completed.stderr)
        result = output.read_text(encoding="utf-8")
        expected = [
            "import Ipp.Extracted.AeneasRuntime\nimport Ipp.Extracted.Foo",
            "@[irreducible, simp]",
            "MacCampaign.Array MacCampaign.U64 4",
            "MacCampaign.Array MacCampaign.U128 2",
            "MacCampaign.Array UInt8 8",
            "MacCampaign.Array.make 2",
            "MacCampaign.Array.replicate b 8",
            "MacCampaign.castU128 x",
            "MacCampaign.castU64 y",
            "MacCampaign.u64ToUsize x",
            "MacCampaign.Array.index_usize",
            "MacCampaign.Array.update",
            "MacCampaign.Array.to_slice",
            "MacCampaign.U64.ofNat 1",
            "MacCampaign.U128.ofNat 2",
            "#u64 3",
        ]
        for spelling in expected:
            self.assertIn(spelling, result)

    def test_unknown_newer_builtin_fails_closed(self):
        for body in ("def x : Std.U256 := by sorry\n", "def x : UScalarTy.U256 := by sorry\n"):
            completed, _ = self.run_normalize(raw(body))
            self.assertNotEqual(completed.returncode, 0, completed.stdout + completed.stderr)

    def test_signed_runtime_tokens_fail_closed(self):
        for token in (
            "Std.I64",
            "IScalarTy.I64",
            "IScalar",
            "UScalar.hcast",
            "IScalar.hcast",
            "#i64",
            "core.num.I64.",
        ):
            completed, _ = self.run_normalize(raw(f"def x := {token}foo\n"))
            self.assertNotEqual(completed.returncode, 0, token)

    def test_wrapping_rules_use_verified_mac_campaign_targets(self):
        completed, output = self.run_normalize(raw("""\
def f (x y : MacCampaign.U64) (a b : MacCampaign.U128) := by
  let p := core.num.U64.wrapping_mul x y
  let q := core.num.U128.wrapping_sub a b
  exact (p, q)
"""))
        self.assertEqual(completed.returncode, 0, completed.stderr)
        result = output.read_text(encoding="utf-8")
        self.assertIn("MacCampaign.wrappingMul64 x y", result)
        self.assertIn("MacCampaign.wrappingSub128 a b", result)

    def test_unmapped_wrapping_builtin_fails_closed(self):
        completed, _ = self.run_normalize(raw(
            "def x (value : MacCampaign.U64) := core.num.U64.wrapping_rotate value\n"
        ))
        self.assertNotEqual(completed.returncode, 0, completed.stdout + completed.stderr)

    def test_forbidden_builtin_in_comment_is_not_rewritten_or_rejected(self):
        completed, output = self.run_normalize(raw("-- Std.U256 and Array.repeat are documentation\n"))
        self.assertEqual(completed.returncode, 0, completed.stderr)
        self.assertIn("-- Std.U256 and Array.repeat are documentation", output.read_text(encoding="utf-8"))

    def test_idempotence_and_check(self):
        completed, first = self.run_normalize(raw("def x : Array Std.U64 1 := Array.make 1\n"))
        self.assertEqual(completed.returncode, 0, completed.stderr)
        with tempfile.TemporaryDirectory() as directory:
            directory = Path(directory)
            second = directory / "second.lean"
            subprocess.run([sys.executable, str(SCRIPT), "--input", str(first), "--output", str(second)], check=True)
            self.assertEqual(first.read_bytes(), second.read_bytes())
            checked = subprocess.run([sys.executable, str(SCRIPT), "--check", str(first)], capture_output=True, text=True)
            self.assertEqual(checked.returncode, 0, checked.stderr)

    def test_matches_actual_mac_campaign_spellings(self):
        actual = GENERATED.read_text(encoding="utf-8")
        completed, output = self.run_normalize(raw("""\
def f (r a : Array Std.U64 6) (x : Std.U64) := by
  let y := UScalar.cast .U128 x
  let z := Array.index_usize r 0
  exact Array.update a 0 x
"""))
        self.assertEqual(completed.returncode, 0, completed.stderr)
        result = output.read_text(encoding="utf-8")
        for spelling in (
            "MacCampaign.castU128",
            "MacCampaign.Array.index_usize",
        ):
            self.assertIn(spelling, actual)
            self.assertIn(spelling, result)
        self.assertIn("MacCampaign.Array", actual)
        self.assertIn("MacCampaign.Array MacCampaign.U64", result)
        self.assertIn("MacCampaign.Array.update", result)

    def test_provenance_contains_hash_and_revision(self):
        completed, output = self.run_normalize(raw("def x : Std.U64 := #u64 1\n"))
        self.assertEqual(completed.returncode, 0, completed.stderr)
        provenance = json.loads(output.with_name(output.name + ".provenance.json").read_text())
        self.assertEqual(len(provenance["raw_lean_sha256"]), 64)
        self.assertEqual(provenance["normalizer_revision"], "normalize-aeneas-lean-v2")


if __name__ == "__main__":
    unittest.main()
