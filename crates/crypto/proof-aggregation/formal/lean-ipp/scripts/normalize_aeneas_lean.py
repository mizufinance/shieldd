@dataclass(frozen=True)
class Declaration:
    name: str
    text: str


@dataclass(frozen=True)
class NormalizationResult:
    content: bytes
    raw_sha256: tuple[str, ...]
    normalized_sha256: str
    declarations: tuple[str, ...]

    def metadata(self) -> dict[str, object]:
        return {
            "raw_sha256": list(self.raw_sha256),
            "normalized_sha256": self.normalized_sha256,
            "normalizer_revision": NORMALIZER_REVISION,
        }


def sha256_bytes(content: bytes) -> str:
    return hashlib.sha256(content).hexdigest()


def _code_spans(text: str) -> Iterable[tuple[int, int]]:
    """Yield spans containing Lean code rather than comments or strings."""
    i = 0
    start = 0
    state = "code"
    block_depth = 0
    while i < len(text):
        if state == "code":
            if text.startswith("--", i):
                if start < i:
                    yield start, i
                state = "line_comment"
                i += 2
                start = i
            elif text.startswith("/-", i):
                if start < i:
                    yield start, i
                state = "block_comment"
                block_depth = 1
                i += 2
                start = i
            elif text[i] == '"':
                if start < i:
                    yield start, i
                state = "string"
                i += 1
                start = i
            else:
                i += 1
        elif state == "line_comment":
            if text[i] == "\n":
                state = "code"
                start = i
            i += 1
        elif state == "block_comment":
            if text.startswith("/-", i):
                block_depth += 1
                i += 2
            elif text.startswith("-/", i):
                block_depth -= 1
                i += 2
                if block_depth == 0:
                    state = "code"
                    start = i
            else:
                i += 1
        else:
            if text[i] == "\\":
                i += 2
            elif text[i] == '"':
                state = "code"
                i += 1
                start = i
            else:
                i += 1
    if state == "code" and start < len(text):
        yield start, len(text)


def _replace_code(text: str, replacements: Sequence[tuple[re.Pattern[str], str]]) -> str:
    pieces: list[str] = []
    cursor = 0
    for start, end in _code_spans(text):
        pieces.append(text[cursor:start])
        code = text[start:end]
        for pattern, replacement in replacements:
            code = pattern.sub(replacement, code)
        pieces.append(code)
        cursor = end
    pieces.append(text[cursor:])
    return "".join(pieces)


def _remove_global_simps(text: str) -> str:
    pieces: list[str] = []
    cursor = 0
    for start, end in _code_spans(text):
        pieces.append(text[cursor:start])
        code = text[start:end]

        def clean(match: re.Match[str]) -> str:
            members = [
                member.strip()
                for member in match.group(1).split(",")
                if member.strip() != "global_simps"
            ]
            return "[" + ", ".join(members) + "]"

        code = re.sub(r"\[([^\[\]]*\bglobal_simps\b[^\[\]]*)\]", clean, code)
        pieces.append(code)
        cursor = end
    pieces.append(text[cursor:])
    return "".join(pieces)


def _attribute_end(text: str, start: int) -> int:
    depth = 0
    in_string = False
    escaped = False
    for index in range(start + 1, len(text)):
        character = text[index]
        if in_string:
            if escaped:
                escaped = False
            elif character == "\\":
                escaped = True
            elif character == '"':
                in_string = False
            continue
        if character == '"':
            in_string = True
        elif character == "[":
            depth += 1
        elif character == "]":
            depth -= 1
            if depth == 0:
                return index + 1
    raise ValueError("unterminated declaration attribute")


def _split_attribute_members(content: str) -> list[str]:
    members: list[str] = []
    start = 0
    square_depth = 0
    paren_depth = 0
    in_string = False
    escaped = False
    for index, character in enumerate(content):
        if in_string:
            if escaped:
                escaped = False
            elif character == "\\":
                escaped = True
            elif character == '"':
                in_string = False
            continue
        if character == '"':
            in_string = True
        elif character == "[":
            square_depth += 1
        elif character == "]":
            square_depth -= 1
        elif character == "(":
            paren_depth += 1
        elif character == ")":
            paren_depth -= 1
        elif character == "," and square_depth == 0 and paren_depth == 0:
            members.append(content[start:index].strip())
            start = index + 1
    members.append(content[start:].strip())
    return [member for member in members if member]


def _strip_aeneas_attributes(text: str) -> str:
    removable = {
        "discriminant",
        "global_simps",
        "rust_loop",
        "rust_loop_body",
        "rust_trait",
        "rust_type",
    }
    pieces: list[str] = []
    cursor = 0
    while True:
        start = text.find("@[", cursor)
        if start < 0:
            pieces.append(text[cursor:])
            break
        if not any(code_start <= start < code_end for code_start, code_end in _code_spans(text)):
            pieces.append(text[cursor : start + 2])
            cursor = start + 2
            continue
        end = _attribute_end(text, start)
        members = _split_attribute_members(text[start + 2 : end - 1])
        unknown = [
            member
            for member in members
            if re.match(r"rust_[A-Za-z0-9_]+", member)
            and member.split(maxsplit=1)[0] not in removable
        ]
        if unknown:
            raise ValueError(
                "normalization failed closed; unsupported Aeneas attribute(s): "
                + ", ".join(unknown)
            )
        retained = [
            member
            for member in members
            if member.split(maxsplit=1)[0] not in removable
        ]
        pieces.append(text[cursor:start])
        if retained:
            pieces.append("@[" + ", ".join(retained) + "]")
        cursor = end
    return "".join(pieces)


def _strip_slice_array_make_ascriptions(text: str) -> str:
    """Drop fixed-array ascriptions on temporary slices emitted by Aeneas."""
    code = bytearray(len(text))
    for start, end in _code_spans(text):
        code[start:end] = b"\x01" * (end - start)

    removals: list[tuple[int, int]] = []
    pattern = re.compile(r"\bStd\.Array\.to_slice\s*\(")
    for match in pattern.finditer(text):
        if not code[match.start()]:
            continue
        opening = text.find("(", match.start(), match.end())
        stack = ["("]
        colon = None
        closing = None
        for index in range(opening + 1, len(text)):
            if not code[index]:
                continue
            char = text[index]
            if char in "([{":
                stack.append(char)
            elif char in ")]}":
                expected = {")": "(", "]": "[", "}": "{"}[char]
                if not stack or stack[-1] != expected:
                    raise ValueError(
                        "normalization failed closed; unbalanced temporary array"
                    )
                stack.pop()
                if not stack:
                    closing = index
                    break
            elif char == ":" and len(stack) == 1:
                if colon is not None:
                    raise ValueError(
                        "normalization failed closed; ambiguous temporary array ascription"
                    )
                colon = index
        if closing is None:
            raise ValueError(
                "normalization failed closed; unterminated Std.Array.to_slice call"
            )
        expression = text[opening + 1 : closing]
        if not re.match(r"\s*Array\.make\b", expression):
            continue
        if colon is None:
            continue
        ascription = text[colon + 1 : closing]
        if not re.match(r"\s*Array\b", ascription):
            continue
        removals.append((colon, closing))

    for start, end in reversed(removals):
        text = text[:start].rstrip() + text[end:]
    return text


def _transform_tokens(text: str, *, fixed_arrays: bool | None = None) -> str:
    if fixed_arrays is None:
        fixed_arrays = "s3_07_arkworks_" in text
    replacements = [
        (
            re.compile(
                r"(?<![\w.])UScalar\.cast\s+(?:\.U128|UScalarTy\.U128)\s+"
                r"([A-Za-z_][\w'.]*)"
            ),
            r"MacCampaign.castU128 \1",
        ),
        (
            re.compile(
                r"(?<![\w.])UScalar\.cast\s+(?:\.U64|UScalarTy\.U64)\s+"
                r"([A-Za-z_][\w'.]*)"
            ),
            r"MacCampaign.castU64 \1",
        ),
        (
            re.compile(
                r"(?<![\w.])UScalar\.cast\s+(?:\.U8|UScalarTy\.U8)\s+"
                r"([A-Za-z_][\w'.]*)"
            ),
            r"MacCampaign.castU8 \1",
        ),
        (
            re.compile(
                r"(?<![\w.])UScalar\.cast\s+(?:\.Usize|UScalarTy\.Usize)\s+"
                r"([A-Za-z_][\w'.]*)"
            ),
            r"MacCampaign.castUsize \1",
        ),
        (re.compile(r"(?<![\w.])Array\s+Std\.U64\b"), "MacCampaign.Array MacCampaign.U64"),
        (re.compile(r"(?<![\w.])Array\s+Std\.U128\b"), "MacCampaign.Array MacCampaign.U128"),
        (re.compile(r"(?<![\w.])Array\s+Std\.U8\b"), "MacCampaign.Array UInt8"),
        (re.compile(r"(?<![\w.])Array\s+Std\.I8\b"), "MacCampaign.Array Int"),
        (re.compile(r"\bStd\.U64\.ofNat\b"), "MacCampaign.U64.ofNat"),
        (re.compile(r"\bStd\.U128\.ofNat\b"), "MacCampaign.U128.ofNat"),
        (re.compile(r"\bStd\.U64\b"), "MacCampaign.U64"),
        (re.compile(r"\bStd\.U128\b"), "MacCampaign.U128"),
        (re.compile(r"\bStd\.U8\b"), "UInt8"),
        (re.compile(r"\bStd\.I8\b"), "Int"),
        (re.compile(r"(\(-?\d+\)|\d+)#i8\b"), r"\1"),
        (re.compile(r"\bcore\.num\.U64\.wrapping_mul\b"), "MacCampaign.wrappingMul64"),
        (re.compile(r"\bcore\.num\.U128\.wrapping_sub\b"), "MacCampaign.wrappingSub128"),
        (re.compile(r"@\[(?:rust_loop_body|rust_loop)\]\s*"), ""),
    ]
    if fixed_arrays:
        replacements += [
            (
                re.compile(r"(?<![\w.])Array\.index_usize\b"),
                "MacCampaign.Array.index_usize",
            ),
            (re.compile(r"(?<![\w.])Array\.update\b"), "MacCampaign.Array.update"),
            (re.compile(r"(?<![\w.])Array\.make\b"), "MacCampaign.Array.make"),
            (
                re.compile(r"(?<![\w.])Array\.repeat\b"),
                "MacCampaign.Array.replicate",
            ),
            (re.compile(r"\bStd\.Array\.to_slice\b"), "MacCampaign.Array.to_slice"),
            (re.compile(r"(?<![\w.])Array\.to_slice\b"), "MacCampaign.Array.to_slice"),
        ]
    result = GENERATED_DOC.sub("", _strip_aeneas_attributes(text))
    result = _replace_code(result, replacements)
    if not fixed_arrays:
        result = _strip_slice_array_make_ascriptions(result)
    result = _remove_global_simps(result).replace("\r\n", "\n")
    return "\n".join(line.rstrip(" \t") for line in result.split("\n"))


def _fail_closed(text: str) -> None:
    code = "\n".join(text[start:end] for start, end in _code_spans(text))
    residual = [
        needle
        for needle in FORBIDDEN
        if needle not in {"Array.index_usize", "Array.update", "Array.repeat"} and needle in code
    ]
    residual += [
        name
        for name in ("Array.index_usize", "Array.update", "Array.repeat")
        if re.search(rf"(?<![.\w]){re.escape(name)}\b", code)
    ]
    # These forms are implemented by the shared executable runtime. Keep the
    # list exact: accepting the namespace as a whole would hide new builtins.
    unknown_audit = code.replace("UScalar.cast .U32", "")
    for supported in (
        "core.num.Usize.ilog2",
        "core.num.Usize.is_power_of_two",
        "core.num.Usize.pow",
    ):
        unknown_audit = unknown_audit.replace(supported, "")
    unknown = re.findall(
        r"\bStd\.U(?:\d+)\b|\bUScalarTy\.U\d+\b|\bUScalar\.cast\b|"
        r"\bcore\.num\.U(?:64|128)\.wrapping_[A-Za-z0-9_]+\b|"
        r"\bcore\.num\.[A-Za-z0-9_.]+",
        unknown_audit,
    )
    if residual or unknown:
        details = ", ".join(dict.fromkeys(residual + unknown))
        raise ValueError(f"normalization failed closed; unsupported residual(s): {details}")


def _raw_namespace_body(text: str, source: Path) -> str:
    if sum(bool(BANNER.match(line)) for line in text.splitlines()) != 1:
        raise ValueError(f"{source}: expected exactly one Aeneas-generated banner")
    if sum(line.strip() == "import Aeneas" for line in text.splitlines()) != 1:
        raise ValueError(f"{source}: expected exactly one bare `import Aeneas`")
    start_marker = f"namespace {NAMESPACE}"
    end_marker = f"end {NAMESPACE}"
    if text.count(start_marker) != 1 or text.count(end_marker) != 1:
        raise ValueError(f"{source}: expected one `{start_marker}` / `{end_marker}` pair")
    body = text.split(start_marker, 1)[1].rsplit(end_marker, 1)[0]
    return GENERATED_DOC.sub("", body).strip() + "\n"


def _parse_declarations(body: str, source: Path) -> list[Declaration]:
    matches = list(DECLARATION.finditer(body))
    if not matches:
        if body.strip():
            raise ValueError(f"{source}: namespace contains no recognized declarations")
        return []
    prefix = body[: matches[0].start()]
    if prefix.strip():
        raise ValueError(f"{source}: unrecognized text before first declaration: {prefix[:80]!r}")
    declarations: list[Declaration] = []
    for index, match in enumerate(matches):
        end = matches[index + 1].start() if index + 1 < len(matches) else len(body)
        text = body[match.start():end].strip() + "\n"
        declarations.append(Declaration(match.group("name"), text))
    return declarations


def _module_path(module: str, lean_root: Path) -> Path:
    if "=" in module:
        _, raw_path = module.split("=", 1)
        return Path(raw_path)
    parts = module.split(".")
    if not parts or parts[0] != "Ipp":
        raise ValueError(f"reuse module must be under Ipp or use MODULE=PATH: {module}")
    return lean_root.joinpath(*parts).with_suffix(".lean")


def _module_name(module: str) -> str:
    return module.split("=", 1)[0]


def _names_from_module(module: str, lean_root: Path) -> set[str]:
    path = _module_path(module, lean_root)
    text = path.read_text(encoding="utf-8")
    start_marker = f"namespace {NAMESPACE}"
    end_marker = f"end {NAMESPACE}"
    if text.count(start_marker) != 1 or text.count(end_marker) != 1:
        raise ValueError(f"{path}: reuse module must contain one `{start_marker}` namespace")
    body = text.split(start_marker, 1)[1].rsplit(end_marker, 1)[0]
    return {declaration.name for declaration in _parse_declarations(body, path)}


def _lean_root_name(root: str) -> str:
    prefix = f"{NAMESPACE}::"
    if not root.startswith(prefix) or root.endswith("::"):
        raise ValueError(f"root is not fully qualified under {NAMESPACE}: {root}")
    return root[len(prefix):].replace("::", ".")


def _referenced_declarations(text: str, names: set[str]) -> set[str]:
    code = "\n".join(text[start:end] for start, end in _code_spans(text))
    identifiers = set(re.findall(r"[A-Za-z_][A-Za-z0-9_'.]*", code))
    return names.intersection(identifiers)


def _dependency_closure(
    declarations: Sequence[Declaration],
    roots: Sequence[str],
) -> set[str]:
    by_name = {declaration.name: declaration for declaration in declarations}
    names = set(by_name)
    selected: set[str] = set()
    pending = list(roots)
    while pending:
        name = pending.pop()
        if name in selected:
            continue
        declaration = by_name.get(name)
        if declaration is None:
            raise ValueError(f"selected declaration is missing: {name}")
        selected.add(name)
        pending.extend(
            sorted(_referenced_declarations(declaration.text, names) - selected)
        )
    return selected


def normalize_files(
    inputs: Sequence[Path],
    *,
    extra_imports: Sequence[str] = (),
    reuse_modules: Sequence[str] = (),
    roots: Sequence[str] = (),
    lean_root: Path = LEAN_ROOT,
) -> NormalizationResult:
    """Assemble raw Types/Funs files, replacing shared declarations by imports."""
    if not inputs:
        raise ValueError("at least one raw input is required")
    if len(set(inputs)) != len(inputs):
        raise ValueError("raw input paths must be unique")
    if len(set(extra_imports)) != len(extra_imports):
        raise ValueError("extra imports must be unique")
    if len(set(reuse_modules)) != len(reuse_modules):
        raise ValueError("reuse modules must be unique")

    fixed_arrays = not roots or all(
        _lean_root_name(root).startswith("s3_07_arkworks_") for root in roots
    )
    raw_contents = [path.read_bytes() for path in inputs]
    ordered: list[Declaration] = []
    by_name: dict[str, str] = {}
    for path, raw in zip(inputs, raw_contents, strict=True):
        source = raw.decode("utf-8")
        transformed = _transform_tokens(
            _raw_namespace_body(source, path), fixed_arrays=fixed_arrays
        )
        _fail_closed(transformed)
        for declaration in _parse_declarations(transformed, path):
            previous = by_name.get(declaration.name)
            if previous is None:
                by_name[declaration.name] = declaration.text
                ordered.append(declaration)
            elif previous != declaration.text:
                raise ValueError(
                    f"{path}: conflicting declarations named {declaration.name} "
                    "across extraction roots"
                )

    reused: set[str] = set(RUNTIME_REUSE_DECLARATIONS)
    for module in reuse_modules:
        module_names = _names_from_module(module, lean_root)
        overlap = reused.intersection(module_names)
        if overlap:
            names = ", ".join(sorted(overlap))
            raise ValueError(f"reuse modules define the same declaration(s): {names}")
        reused.update(module_names)

    root_names = tuple(_lean_root_name(root) for root in roots)
    missing_roots = [root for root in root_names if root not in by_name]
    if missing_roots:
        raise ValueError(f"extraction root declaration(s) missing: {', '.join(missing_roots)}")
    replaced_roots = [root for root in root_names if root in reused]
    if replaced_roots:
        raise ValueError(f"extraction root declaration(s) cannot be reused: {', '.join(replaced_roots)}")

    retained = (
        _dependency_closure(ordered, root_names) if root_names else set(by_name)
    )
    selected = [
        declaration
        for declaration in ordered
        if declaration.name in retained and declaration.name not in reused
    ]
    if not selected:
        raise ValueError("declaration replacement removed the entire extraction")

    imports = ["Ipp.Extracted.AeneasRuntime", *extra_imports, *map(_module_name, reuse_modules)]
    if len(set(imports)) != len(imports):
        raise ValueError("runtime, extra imports, and reuse modules must be disjoint")
    preamble = [
        "-- THIS FILE WAS AUTOMATICALLY GENERATED BY AENEAS",
        f"-- Deterministically assembled by {NORMALIZER_REVISION}.",
        *(f"import {module}" for module in imports),
        "",
        "open Aeneas Aeneas.Std Result ControlFlow Error",
        "open Std.Do",
        "set_option linter.unusedVariables false",
        "set_option maxHeartbeats 1000000",
        "set_option maxRecDepth 2048",
        "",
        "noncomputable section",
        "",
        f"namespace {NAMESPACE}",
        "",
    ]
    content = "\n".join(preamble)
    content += "\n".join(declaration.text.rstrip() for declaration in selected)
    content += f"\n\nend {NAMESPACE}\n"
    _fail_closed(content)
    encoded = content.encode("utf-8")
    return NormalizationResult(
        content=encoded,
        raw_sha256=tuple(sha256_bytes(raw) for raw in raw_contents),
        normalized_sha256=sha256_bytes(encoded),
        declarations=tuple(declaration.name for declaration in selected),
    )


def check_normalized(path: Path) -> None:
    text = path.read_text(encoding="utf-8")
    if not BANNER.match(text.splitlines()[0] if text.splitlines() else ""):
        raise ValueError("normalized file is missing the Aeneas banner")
    _fail_closed(text)
    transformed = _transform_tokens(text)
    if transformed != text.replace("\r\n", "\n"):
        raise ValueError("file is not normalized (normalization would change its bytes)")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--input", type=Path, action="append")
    mode.add_argument("--check", type=Path)
    parser.add_argument("--output", type=Path)
    parser.add_argument("--extra-import", action="append", default=[])
    parser.add_argument("--reuse-module", action="append", default=[])
    parser.add_argument("--root", action="append", default=[])
    parser.add_argument("--lean-root", type=Path, default=LEAN_ROOT)
    args = parser.parse_args(argv)
    try:
        if args.check:
            check_normalized(args.check)
            content = args.check.read_bytes()
            print(json.dumps({"normalized_sha256": sha256_bytes(content)}, sort_keys=True))
            return 0
        if args.output is None:
            parser.error("--output is required with --input")
        result = normalize_files(
            args.input,
            extra_imports=args.extra_import,
            reuse_modules=args.reuse_module,
            roots=args.root,
            lean_root=args.lean_root,
        )
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_bytes(result.content)
        print(json.dumps(result.metadata(), sort_keys=True))
        return 0
    except (OSError, UnicodeError, ValueError) as exc:
        print(f"normalize_aeneas_lean: error: {exc}", file=sys.stderr)
        return 2


