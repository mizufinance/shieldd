#!/usr/bin/env python3
"""Normalize one newer Aeneas Lean artifact into the MacCampaign dialect."""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import subprocess
import sys
from pathlib import Path


NORMALIZER_REVISION = "normalize-aeneas-lean-v2"
BANNER = re.compile(r"^--\s+THIS FILE WAS AUTOMATICALLY GENERATED BY AENEAS(?:\s|$)")
FORBIDDEN = (
    "import Aeneas",
    "Std.U64",
    "Std.U128",
    "Std.I64",
    "UScalarTy.U64",
    "UScalarTy.U128",
    "IScalarTy.I64",
    "IScalar",
    "UScalar.hcast",
    "IScalar.hcast",
    "#i64",
    "core.num.I64.",
    "UScalar.cast .U64",
    "UScalar.cast .U128",
    "global_simps",
    "Array.index_usize",
    "Array.update",
    "Array.repeat",
)


def _code_spans(text: str):
    """Yield (start, end) spans which are Lean code, not comments/strings."""
    i = 0
    start = 0
    state = "code"
    while i < len(text):
        if state == "code":
            if text.startswith("--", i):
                if start < i:
                    yield start, i
                state = "line_comment"
                i += 2
                start = i
            elif text.startswith("/-", i):
                if start < i:
                    yield start, i
                state = "block_comment"
                i += 2
                start = i
            elif text[i] == '"':
                if start < i:
                    yield start, i
                state = "string"
                i += 1
                start = i
            else:
                i += 1
        elif state == "line_comment":
            if text[i] == "\n":
                state = "code"
                start = i
            i += 1
        elif state == "block_comment":
            if text.startswith("/-", i):
                i += 2
            elif text.startswith("-/", i):
                state = "code"
                i += 2
                start = i
            else:
                i += 1
        else:
            if text[i] == "\\":
                i += 2
            elif text[i] == '"':
                state = "code"
                i += 1
                start = i
            else:
                i += 1
    if state == "code" and start < len(text):
        yield start, len(text)


def _replace_code(text: str, replacements: list[tuple[re.Pattern[str], str]]) -> str:
    pieces = []
    cursor = 0
    for start, end in _code_spans(text):
        pieces.append(text[cursor:start])
        code = text[start:end]
        for pattern, replacement in replacements:
            code = pattern.sub(replacement, code)
        pieces.append(code)
        cursor = end
    pieces.append(text[cursor:])
    return "".join(pieces)


def _remove_global_simps(text: str) -> str:
    """Remove global_simps only from square-bracket attribute lists."""
    pieces = []
    cursor = 0
    for start, end in _code_spans(text):
        pieces.append(text[cursor:start])
        code = text[start:end]

        def clean(match: re.Match[str]) -> str:
            body = match.group(1)
            members = [m.strip() for m in body.split(",") if m.strip() != "global_simps"]
            if not members:
                return "[]"
            return "[" + ", ".join(members) + "]"

        # Attribute lists are the only square brackets in which this member is
        # meaningful.  Rejecting any residual below catches non-attribute use.
        code = re.sub(r"\[([^\[\]]*\bglobal_simps\b[^\[\]]*)\]", clean, code)
        pieces.append(code)
        cursor = end
    pieces.append(text[cursor:])
    return "".join(pieces)


def _remove_rust_loop_metadata(text: str) -> str:
    """Drop Aeneas loop marker attributes absent from the MacCampaign runtime."""
    return _replace_code(
        text,
        [(re.compile(r"@\[(?:rust_loop_body|rust_loop)\]\s*"), "")],
    )


def _validate_raw(text: str) -> None:
    lines = text.splitlines()
    banners = sum(bool(BANNER.match(line)) for line in lines)
    imports = sum(line.strip() == "import Aeneas" for line in lines)
    if banners != 1:
        raise ValueError(f"expected exactly one Aeneas-generated banner, found {banners}")
    if imports != 1:
        raise ValueError(f"expected exactly one bare `import Aeneas`, found {imports}")


def _validate_normalized(text: str) -> None:
    banners = sum(bool(BANNER.match(line)) for line in text.splitlines())
    runtime_imports = sum(line.strip() == "import Ipp.Extracted.AeneasRuntime" for line in text.splitlines())
    if banners != 1 or runtime_imports != 1:
        raise ValueError("input is neither a raw Aeneas artifact nor a normalized artifact")


def _transform(text: str, *, extra_imports: list[str], raw: bool) -> str:
    if raw:
        _validate_raw(text)
    replacements = [
        (re.compile(r"(?<![\w.])UScalar\.cast\s+(?:\.U128|UScalarTy\.U128)\s+([A-Za-z_][\w'.]*)"), r"MacCampaign.castU128 \1"),
        (re.compile(r"(?<![\w.])UScalar\.cast\s+(?:\.U64|UScalarTy\.U64)\s+([A-Za-z_][\w'.]*)"), r"MacCampaign.castU64 \1"),
        (re.compile(r"(?<![\w.])UScalar\.cast\s+(?:\.Usize|UScalarTy\.Usize)\s+([A-Za-z_][\w'.]*)"), r"MacCampaign.u64ToUsize \1"),
        (re.compile(r"(?<![\w.])Array\s+Std\.U64\b"), "MacCampaign.Array MacCampaign.U64"),
        (re.compile(r"(?<![\w.])Array\s+Std\.U128\b"), "MacCampaign.Array MacCampaign.U128"),
        (re.compile(r"(?<![\w.])Array\s+Std\.U8\b"), "MacCampaign.Array UInt8"),
        (re.compile(r"\bStd\.U64\.ofNat\b"), "MacCampaign.U64.ofNat"),
        (re.compile(r"\bStd\.U128\.ofNat\b"), "MacCampaign.U128.ofNat"),
        (re.compile(r"\bStd\.U64\b"), "MacCampaign.U64"),
        (re.compile(r"\bStd\.U128\b"), "MacCampaign.U128"),
        (re.compile(r"\bStd\.U8\b"), "UInt8"),
        (re.compile(r"\bcore\.num\.U64\.wrapping_mul\b"), "MacCampaign.wrappingMul64"),
        (re.compile(r"\bcore\.num\.U128\.wrapping_sub\b"), "MacCampaign.wrappingSub128"),
        (re.compile(r"(?<![\w.])Array\.index_usize\b"), "MacCampaign.Array.index_usize"),
        (re.compile(r"(?<![\w.])Array\.update\b"), "MacCampaign.Array.update"),
        (re.compile(r"(?<![\w.])Array\.make\b"), "MacCampaign.Array.make"),
        (re.compile(r"(?<![\w.])Array\.repeat\b"), "MacCampaign.Array.replicate"),
        (re.compile(r"(?<![\w.])Array\.to_slice\b"), "MacCampaign.Array.to_slice"),
    ]
    result = _replace_code(text, replacements)
    result = _replace_code(result, [(re.compile(r"^import Aeneas\r?$", re.MULTILINE), "import Ipp.Extracted.AeneasRuntime")])
    result = _remove_global_simps(result)
    result = _remove_rust_loop_metadata(result)
    result = re.sub(r"^set_option linter\.(?:dupNamespace|hashCommand) false\r?\n", "", result, flags=re.MULTILINE)
    if raw and extra_imports:
        marker = "import Ipp.Extracted.AeneasRuntime"
        insertion = marker + "\n" + "\n".join(f"import {item}" for item in extra_imports)
        result = result.replace(marker, insertion, 1)
    return result


def _fail_closed(text: str) -> None:
    code = "\n".join(text[start:end] for start, end in _code_spans(text))
    array_names = {"Array.index_usize", "Array.update", "Array.repeat"}
    residual = [needle for needle in FORBIDDEN if needle not in array_names and needle in code]
    # The target names intentionally contain the unqualified Array suffix.
    residual += [
        name
        for name in ("Array.index_usize", "Array.update", "Array.repeat")
        if re.search(rf"(?<![.\w]){re.escape(name)}\b", code)
    ]
    unknown = re.findall(
        r"\bStd\.U(?:\d+)\b|\bUScalarTy\.U\d+\b|\bUScalar\.cast\b|"
        r"\bcore\.num\.U(?:64|128)\.wrapping_[A-Za-z0-9_]+\b|"
        r"\bcore\.num\.[A-Za-z0-9_.]+",
        code,
    )
    if residual or unknown:
        details = ", ".join(dict.fromkeys(residual + unknown))
        raise ValueError(f"normalization failed closed; unsupported residual(s): {details}")


def _version(command: list[str]) -> str | None:
    try:
        return subprocess.run(command, capture_output=True, text=True, check=False).stdout.strip() or None
    except OSError:
        return None


def _provenance(raw: bytes, args: argparse.Namespace) -> dict[str, object]:
    llbc_hash = None
    if args.llbc:
        llbc_hash = hashlib.sha256(Path(args.llbc).read_bytes()).hexdigest()
    return {
        "raw_lean_sha256": hashlib.sha256(raw).hexdigest(),
        "llbc_sha256": llbc_hash,
        "normalizer_revision": NORMALIZER_REVISION,
        "hax_revision": args.hax_rev or os.environ.get("HAX_REVISION"),
        "aeneas_release_tag": args.aeneas_release or os.environ.get("AENEAS_RELEASE_TAG"),
        "charon_version": args.charon_version or os.environ.get("CHARON_VERSION"),
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--input", type=Path)
    mode.add_argument("--check", type=Path)
    parser.add_argument("--output", type=Path)
    parser.add_argument("--extra-import", action="append", default=[])
    parser.add_argument("--llbc", type=Path)
    parser.add_argument("--hax-rev")
    parser.add_argument("--aeneas-release")
    parser.add_argument("--charon-version")
    args = parser.parse_args(argv)
    try:
        if args.check:
            original = args.check.read_text(encoding="utf-8")
            _validate_normalized(original)
            _fail_closed(original)
            checked = _transform(original, extra_imports=[], raw=False)
            if checked != original:
                raise ValueError("file is not normalized (normalization would change its bytes)")
            return 0
        if args.output is None:
            parser.error("--output is required with --input")
        raw = args.input.read_bytes()
        source = raw.decode("utf-8")
        raw_imports = sum(line.strip() == "import Aeneas" for line in source.splitlines())
        if raw_imports == 0:
            _validate_normalized(source)
        normalized = _transform(source, extra_imports=args.extra_import, raw=raw_imports == 1)
        _fail_closed(normalized)
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_bytes(normalized.encode("utf-8"))
        sidecar = args.output.with_name(args.output.name + ".provenance.json")
        sidecar.write_text(json.dumps(_provenance(raw, args), indent=2) + "\n", encoding="utf-8")
        return 0
    except (OSError, UnicodeError, ValueError) as exc:
        print(f"normalize_aeneas_lean: error: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
